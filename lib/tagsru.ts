/**
 * Русская подпись тега — ТОЛЬКО ДЛЯ ВЫВОДА.
 *
 * Ключи тегов английские, и это не меняется: из них собраны tags_json,
 * game_tags, профиль вкуса, VIBE_TAGS и TIME_TAGS, приор семантики, «Чем
 * выделяется». Всё, что сравнивает теги, сравнивает английские имена, а
 * переводится только то, что видит человек, — в последний момент, на месте
 * вывода. Переведённый ключ, уехавший в сравнение, промахнулся бы мимо всех
 * таблиц разом и молча: совпадений просто стало бы ноль.
 *
 * Источник подписей — словарь Steam (lib/tagsru.steam.ts, генерирует
 * scripts/gen-tagsru.ts) поверх ручных поправок (lib/tagsru.overrides.ts).
 * Статическая карта, а не чтение tags.name_ru: подпись нужна клиентским
 * компонентам и страницам на ISR, и тянуть ради неё базу в каждый ответ
 * незачем — словарь меняется раз в месяцы.
 *
 * Тега нет в словаре (Steam завёл новый, а генератор с тех пор не гоняли) —
 * подпись английская, как было до перевода. Это честнее, чем пустое место.
 *
 * Модуль клиентобезопасный: ни базы, ни сети.
 */
import { TAGS_RU_OVERRIDES } from './tagsru.overrides'
import { TAGS_RU_STEAM } from './tagsru.steam'

/**
 * Одна карта на процесс, поправки поверх Steam. Map, а не объект: у объекта
 * «constructor» и «toString» нашлись бы в прототипе.
 */
const RU = new Map<string, string>([
  ...Object.entries(TAGS_RU_STEAM),
  ...Object.entries(TAGS_RU_OVERRIDES),
])

/**
 * Русская подпись тега; без перевода — сам тег. Пробелы по краям не в счёт:
 * у Steam бывает «Dystopian » с пробелом, и так он лежит в tags_json.
 */
export function tagRu(tag: string): string {
  const key = tag.trim()
  return RU.get(key) ?? key
}

/** Есть ли у тега русская подпись */
export function hasTagRu(tag: string): boolean {
  return RU.has(tag.trim())
}
