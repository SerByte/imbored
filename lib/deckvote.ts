/**
 * ГОЛОС КОЛОДЫ ПАТИ: СКОЛЬКО РАЗ ОН УХОДИТ И ЧТО ДЕЛАТЬ С ОТКАЗОМ.
 *
 * Вынесено из страницы комнаты по той же причине, что решение опроса в
 * lib/roompoll.ts: пока правила жили условиями внутри обработчика, в них
 * жили и ошибки, которых не видел никто.
 *
 * Первая — двойной голос. Замерено на демо-комнате: Enter на «✖ Не хочу», и
 * через 60 мс фокус всё ещё на кнопке УЛЕТАЮЩЕЙ карты — она живёт в DOM ещё
 * 220 мс анимации, со старым обработчиком. Второй Enter голосовал за ту же
 * карту ещё раз: прогресс прыгал 2/10 → 4/10 при сдвиге колоды на одну карту.
 * Сервер идемпотентен (первый голос остаётся, повтор отвечает тем же — см.
 * castDeckVote), так что врал «только» счётчик — до следующей перезагрузки
 * колоды, и под конец полоса уходила за сто процентов.
 *
 * Вторая — отказы, сведённые к одному. 401 и 403 возвращали карту в колоду
 * со строкой «свайпни ещё раз», хотя повтор откажет ровно так же: сессии нет,
 * или участника из комнаты убрали.
 */

/**
 * Голос за карту уходит один раз.
 *
 * voted — карты, чей голос в пути или уже записан (votedLocally на странице).
 * false — этот голос уже отдан, второй жест по той же карте — пустышка.
 * Отказ, после которого карта возвращается, вычёркивает её из набора, и тот
 * же жест снова работает: повтор после моргнувшей сети — не двойной голос.
 */
export function claimVote(voted: Set<number>, appid: number): boolean {
  if (voted.has(appid)) return false
  voted.add(appid)
  return true
}

/**
 * Что делать с голосом, который не записался.
 *
 * Статус 0 — ответа нет вовсе: обрыв сети или истёкший потолок ожидания.
 */
export type VoteMiss =
  /** 409: комната договорилась или карты нет среди розданных — повтор откажет так же */
  | 'gone'
  /** 401: сессия истекла — на вход, который вернёт в эту же комнату */
  | 'bounce'
  /** 403: участника убрали из комнаты — карту не возвращать, экран перечитать */
  | 'removed'
  /** Остальное — сеть, 5xx, 429: карта возвращается, повтор тем же жестом */
  | 'retry'

export function voteMiss(status: number): VoteMiss {
  if (status === 409) return 'gone'
  if (status === 401) return 'bounce'
  if (status === 403) return 'removed'
  return 'retry'
}

/**
 * Потолок ожидания голоса.
 *
 * Без него повисший POST (телефон сменил Wi-Fi на LTE, соединение HTTP/2
 * умерло молча) держал карту «улетевшей» бесконечно: на экране она уже
 * исчезла, в базе голоса нет, и откатывать нечего — отказ так и не пришёл.
 * Голос по потолку откатывается как любой другой отказ. Если сервер его
 * всё-таки записал, повтор ничего не испортит: запись идемпотентна. Повтор
 * другим жестом тоже ответит успехом, но останется первый голос — голос
 * отдаётся один раз (castDeckVote), и в этой редкой гонке выигрывает он.
 */
export const VOTE_TIMEOUT_MS = 10_000

/**
 * Сигнал запроса с потолком ms.
 *
 * Без AbortSignal.timeout (старые браузеры) — без потолка, а не с
 * исключением: брошенное здесь уронило бы каждый запрос, а не только
 * повисший.
 *
 * Голос — не единственная кнопка комнаты, которая ждёт ответа. «Выйти из
 * пати», ✕ хоста и переключатель доски держат флаг «в пути», который гасит
 * повтор, — и запрос, повисший на смене Wi-Fi на LTE, оставлял их
 * aria-disabled пустышками без строки отказа, пока браузер сам не сдастся.
 * По потолку запрос отменяется, попадает в catch и становится отказом.
 */
export function cappedSignal(ms: number): AbortSignal | undefined {
  return typeof AbortSignal.timeout === 'function' ? AbortSignal.timeout(ms) : undefined
}

/** Сигнал голоса с потолком VOTE_TIMEOUT_MS */
export function voteSignal(): AbortSignal | undefined {
  return cappedSignal(VOTE_TIMEOUT_MS)
}

/** Членство в снимке комнаты: участник ли и сколько своих голосов у сервера */
export type MembershipView = {
  isMember: boolean
  /** свои голоса по счёту сервера; null — себя в ростере нет */
  myVotes: number | null
}

/**
 * ПРЕРВАЛОСЬ ЛИ ЧЛЕНСТВО МЕЖДУ ДВУМЯ СНИМКАМИ КОМНАТЫ.
 *
 * Хост убирает участника вместе со ВСЕМИ его голосами (removeRoomMember), и
 * всё, что колода этого устройства помнит, — votedLocally, ключ колоды, карты
 * на руках, — с этой минуты врёт: карты, чьи голоса стёрты, сервер раздаёт
 * снова, а набор отсвайпанного их отсеивает. Сбрасывать эту память только на
 * своём «Войти в комнату» мало: вернуться можно из второй вкладки или с
 * телефона той же сессии. Тогда эта вкладка следующим опросом просто снова
 * видит себя участником, ключ «состав:раунд» прежний, колода не
 * перечитывается — и комната встаёт навсегда: у него «ждём ещё одного», у
 * остальных он «ещё свайпает».
 *
 * Два признака:
 *  - участник → не участник: удаление видно прямо;
 *  - свои голоса у сервера убыли. При непрерывном членстве их счёт только
 *    растёт — голос пишется INSERT OR REPLACE, стирает их одно удаление, —
 *    значит, между снимками было удаление и повторный вход. Скрытая вкладка
 *    опрашивает раз в минуту или не опрашивает вовсе, и момент «не участник»
 *    она могла не застать.
 *
 * Не ловится одно: вход с другого устройства, успевший до опроса этой вкладки
 * набрать больше голосов, чем она видела в прошлый раз. Счёт тогда не убыл, а
 * членство было прервано — по одним числам ростера это не отличить.
 *
 * Сравниваются только снимки по порядку чтения (seq новее показанного):
 * снимок с матчем встаёт и со старым номером (snapshotFate в lib/roompoll), и
 * его членство и голоса — прошлое, а не новость.
 */
export function membershipLapsed(args: {
  /** номер запроса нового снимка */
  seq: number
  /** снимок на экране; null — ещё ничего не показано */
  shown: (MembershipView & { seq: number }) | null
  next: MembershipView
}): boolean {
  const { seq, shown, next } = args
  if (!shown || seq < shown.seq || !shown.isMember) return false
  if (!next.isMember) return true
  return shown.myVotes !== null && next.myVotes !== null && next.myVotes < shown.myVotes
}

/**
 * Застряла ли колода: на руках пусто, а сервер считает, что человек не
 * дошёл до конца.
 *
 * Так выглядит голос, потерянный мимо отката: карта ушла, а записи нет —
 * например, отказ 409 notindeck после пересборки колоды или вкладка, которую
 * усыпили посреди запроса. Остальные в это время видят его «ещё свайпает»
 * бесконечно, а он сам — «ждём ещё одного».
 *
 * deckSize ноль или неизвестен — признака конца у сервера нет вовсе (done там
 * всегда false, см. /api/room/[id]), и «не дошёл» ничего не значит.
 */
export function deckStuck(args: {
  /** карт на руках; null — колода ещё не загружена */
  left: number | null
  /** done своего участника из опроса; undefined — не участник */
  meDone: boolean | undefined
  deckSize: number | null
}): boolean {
  if (args.left !== 0 || args.meDone !== false) return false
  return args.deckSize !== null && args.deckSize > 0
}

/**
 * Догнал ли снимок комнаты свои голоса: в пути нет ни одного, и снимок
 * запрошен ПОСЛЕ того, как на последний из них пришёл ответ.
 *
 * Без этого deckStuck истинно на каждом штатном конце колоды. Последний свайп
 * убирает карту сразу, а done в последнем снимке опроса ещё false — голос в
 * пути, сервер его не видел (lib/room называет это «штатным состоянием»).
 * Самолечение по нему уходило полной пересборкой /deck у каждого участника в
 * каждом раунде — самый дорогой маршрут комнаты и место в DECK_LIMIT, — при
 * том что ответ ничего не менял: последняя карта отсеяна votedLocally. И
 * тратило единственное лечение на ключ колоды, прежде чем настоящая потеря
 * голоса вообще могла проявиться.
 *
 * askedAt — когда ушёл запрос снимка, а не когда пришёл ответ: снимок,
 * прочитанный до записи голоса, о голосе не знает, когда бы он ни приехал.
 * Та же миллисекунда — «не знает»: подождать один опрос дешевле, чем
 * пересобрать колоду.
 */
export function pollCaughtUp(args: {
  /** голосов этого устройства без ответа */
  votesInFlight: number
  /** когда ушёл запрос снимка (Date.now) */
  askedAt: number
  /** когда пришёл ответ на последний голос; 0 — голосов не было */
  votesSettledAt: number
}): boolean {
  return args.votesInFlight === 0 && args.askedAt > args.votesSettledAt
}

/** Порог голоса жестом по смещению, px — тот же, что был в SwipeDeck */
const SWIPE_DISTANCE = 110
/** Скорость щелчка, px/с: быстрее — голос и без порога по смещению */
const SWIPE_FLICK_SPEED = 500
/** Щелчку всё же нужно смещение, px: иначе отмена, перелетевшая центр, голосовала бы */
const SWIPE_FLICK_MIN = 30

/**
 * ГОЛОС ЖЕСТОМ: КУДА УШЛА КАРТА, КОГДА ПАЛЕЦ ЕЁ ОТПУСТИЛ.
 *
 * Порог проходили по смещению ИЛИ по скорости, а сторону брали всегда по
 * смещению. Скорость у framer-motion считается по последним 100 мс движения,
 * и быстрый возврат пальца к центру легко даёт больше 500 px/с в сторону,
 * ПРОТИВОПОЛОЖНУЮ остаточному смещению. Человек тянул карту вправо до штампа
 * «Играем!», передумывал, резко вёл палец назад, отпускал на +20 px — и
 * записывалось «Играем!» за игру, от которой он как раз отказывался. Голос не
 * отменить, а «да» последнего несогласного сводит матч сразу.
 *
 * Поэтому:
 *   • скорость, направленная против смещения, — отмена, а не голос, и тем
 *     более не голос за другую сторону: сторону по скорости брать нельзя, за
 *     порогом она перевернула бы голос против штампа на экране;
 *   • смещение за SWIPE_DISTANCE — голос стороны смещения, как и было;
 *   • щелчок (быстро и в ту же сторону) — голос, но не дрожь у центра: отмена,
 *     перелетевшая центр (−5 px при −1000 px/с), иначе голосовала бы за
 *     противоположную сторону. Настоящие щелчки по замеру проходят 58–74 px.
 *
 * null — карта возвращается на место; ничего не записано, жест можно
 * повторить. Ошибаться в эту сторону и надо: лишний возврат стоит одного
 * свайпа, лишний голос не исправить.
 */
export function deckSwipeVote(offsetX: number, velocityX: number): boolean | null {
  const side = Math.sign(offsetX)
  if (side === 0) return null
  const fast = Math.abs(velocityX) > SWIPE_FLICK_SPEED
  // палец уходит обратно — отмена
  if (fast && Math.sign(velocityX) !== side) return null
  if (Math.abs(offsetX) > SWIPE_DISTANCE) return side > 0
  if (fast && Math.abs(offsetX) >= SWIPE_FLICK_MIN) return side > 0
  return null
}

/**
 * Позиция в колоде: какая по счёту карта сейчас сверху.
 *
 * Числитель зажат знаменателем — ровно как в components/room/MemberRoster,
 * где та же оговорка записана: «голосов может оказаться больше, чем карт».
 *
 * Случай штатный, а не выдуманный: loadDeck МЕРЖИТ колоду, а не заменяет
 * («Мержим по appid, а не заменяем» — app/room/[id]/page), поэтому старые
 * неотсвайпанные карты остаются на руках, а deckTotal приезжает уже от НОВОЙ
 * колоды. Вошёл человек с маленькой библиотекой — новая колода схлопнулась,
 * старые карты остались, и каждый следующий свайп уводил числитель за
 * знаменатель: «16/12». Полоса при этом считалась тем же выражением и уходила
 * за сто процентов.
 *
 * Вырожденный край — новая колода пустая при непустых картах на руках: строка
 * читалась «1/0». Поэтому при нулевом знаменателе — одна позиция без дроби,
 * как это делает ростер, и пустая полоса.
 */
export function deckPosition(
  votedCount: number,
  deckTotal: number,
): { n: number; total: number | null; label: string; pct: number } {
  if (!deckTotal) return { n: votedCount + 1, total: null, label: String(votedCount + 1), pct: 0 }
  const n = Math.min(votedCount + 1, deckTotal)
  return { n, total: deckTotal, label: `${n}/${deckTotal}`, pct: Math.min(100, (n / deckTotal) * 100) }
}

/**
 * Что колода говорит скринридеру, когда сверху новая карта.
 *
 * Глазу смена видна — карта улетает, приезжает другая. Скринридеру не было
 * сказано ничего: замер показал ноль живых областей на экране колоды, а
 * заголовок сменился Dota 2 → Counter-Strike 2 молча. Название — ради него
 * строка и звучит; номер — тот же, что на полосе под колодой.
 */
export function deckCardLine(pos: { n: number; total: number | null }, name: string): string {
  return pos.total === null ? `Карта ${pos.n}: ${name}` : `Карта ${pos.n} из ${pos.total}: ${name}`
}

/**
 * ГОЛОС СТРЕЛКОЙ: → — «да», ← — «нет».
 *
 * С клавиатуры колоду можно было листать только кнопками: Tab до «Играем!»,
 * Enter, и так двадцать раз. Жест на телефоне — одно движение на карту, а на
 * десктопе самый быстрый путь требовал сначала найти кнопку фокусом. Стрелки —
 * тот же язык, что у жеста: вправо — да, влево — нет.
 *
 * Стрелка голосует, только когда её больше никто не ждёт:
 *   • ownArrows — фокус там, где стрелки уже чьи-то: поле ввода, карусель
 *     скриншотов, радиогруппа, диалог. Отнять у них стрелку — сломать их;
 *   • onScreen — колода в экране. Человек, уехавший вниз к полке
 *     «Приглянулось», иначе голосовал бы за карту, которой не видит;
 *   • repeat — зажатая клавиша не пролистывает колоду очередью;
 *   • модификаторы — Alt+← это «Назад» браузера, Shift+стрелки выделяют текст;
 *   • defaultPrevented — стрелку уже обработал кто-то ниже по дереву.
 *
 * null — это не голос, и событие остаётся тому, кому адресовано.
 */
export type DeckKeyEvent = {
  key: string
  altKey: boolean
  ctrlKey: boolean
  metaKey: boolean
  shiftKey: boolean
  repeat: boolean
  defaultPrevented: boolean
  ownArrows: boolean
  onScreen: boolean
}

export function deckKeyVote(e: DeckKeyEvent): boolean | null {
  if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return null
  if (e.defaultPrevented || e.repeat || e.ownArrows || !e.onScreen) return null
  if (e.altKey || e.ctrlKey || e.metaKey || e.shiftKey) return null
  return e.key === 'ArrowRight'
}

/**
 * Где стрелки уже заняты — см. ownArrows у deckKeyVote. Карусель скриншотов
 * (components/morph) помечена aria-roledescription, лайтбокс — aria-modal.
 */
export const OWN_ARROWS_SELECTOR = [
  'input',
  'textarea',
  'select',
  '[contenteditable]:not([contenteditable="false"])',
  '[role="slider"]',
  '[role="radiogroup"]',
  '[role="tablist"]',
  '[role="listbox"]',
  '[role="menu"]',
  '[role="dialog"]',
  '[aria-modal="true"]',
  '[aria-roledescription]',
].join(', ')

/**
 * Видна ли колода: хотя бы 120 px карты между верхом и низом окна. Меньше —
 * это край карты под шапкой или над нижней панелью, по нему не понять, за
 * какую игру голос.
 */
export function deckOnScreen(box: { top: number; bottom: number }, viewportH: number): boolean {
  return Math.min(box.bottom, viewportH) - Math.max(box.top, 0) >= 120
}
