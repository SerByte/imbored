import { describe, expect, test } from 'vitest'
import { claimsNoUpdates, modelTextFlaw, point, pointsLine } from './modeltext'

/**
 * Фикстуры — дословно то, что модель написала на живых карточках и в
 * пересказах патчей (аудит прода: /game/730, /game/317400, /game/359550,
 * /game/3191050, /game/1149460, Dark and Darker). Модель в тестах не зовётся:
 * проверяется только то, что делает с её ответом код.
 */

describe('modelTextFlaw: обломки JSON', () => {
  test('хвост массива в пункте — обломок, а не текст (Portal Stories: Mel)', () => {
    expect(modelTextFlaw("Сложность хорошо подобрана, справедливо'],")).toBe('debris')
  })

  test('скобки, непарные кавычки, экранирование и оборванная запятая', () => {
    const debris = [
      'Атмосфера", "cons": ["Мало контента',
      '{"pros": "Атмосфера"}',
      'Отличный саундтрек"]',
      '["Красивая графика',
      'Нет "кавычки',
      "Хороший 'кооператив",
      'Красивая графика\\nи музыка',
      'Хороший сюжет,',
    ]
    for (const s of debris) expect(modelTextFlaw(s), s).toBe('debris')
  })

  test('парные кавычки, апостроф внутри слова и скобки по делу — не обломки', () => {
    const fine = [
      'Режим "Королевская битва" затягивает',
      "Режим 'Королевская битва' затягивает",
      "Сюжет в духе Assassin's Creed",
      "Д'Артаньян в роли наставника",
      'Короткая кампания (5–6 часов)',
      'Исправлен вылет [DX12] при запуске',
    ]
    for (const s of fine) expect(modelTextFlaw(s), s).toBeNull()
  })
})

describe('modelTextFlaw: смесь алфавитов в одном слове', () => {
  test('русское окончание к английскому слову — брак (Dark and Darker)', () => {
    expect(modelTextFlaw('Добавили сундуки с космetics-предметами')).toBe('mixed')
    // латинская «о» внутри русского слова — та же смесь, хоть на глаз и не видна
    expect(modelTextFlaw('Атм\u006Fсфера и звук')).toBe('mixed')
  })

  test('дефис, цифры и целые английские слова — не смесь', () => {
    const fine = [
      'PvE-игра с друзьями',
      'Стабильный Wi-Fi не нужен: есть офлайн',
      'Работает на Unreal Engine 5.8',
      '3D-графика и 60 FPS на Steam Deck',
      'Урон x2 в режиме хардкор',
    ]
    for (const s of fine) expect(modelTextFlaw(s), s).toBeNull()
  })
})

describe('modelTextFlaw: битый русский', () => {
  test('несогласованные род и падеж из живых карточек', () => {
    const broken = [
      // CS2
      'Глубокая и увлекательная геймплей механика для длительной игры',
      'Огромное количество читеров в каждой матч невозможно получить бан',
      // BRAZILIAN DRUG DEALER 3
      'Отличный модификация Quake',
      // ICARUS
      'Сложный реалистичный выживание',
      // Rainbow Six Siege
      'Глубокая тактическая геймплей с уникальными операторами',
      // причастие перед существительным, чей винительный другой, судится как
      // прилагательное: «концовку» было бы дополнением, «концовка» — нет
      'Сюжет хуже первой части, разочаровывающий концовка',
    ]
    for (const s of broken) expect(modelTextFlaw(s), s).toBe('grammar')
  })

  /*
   * Честные фразы с выгрузки прода, которые первая версия правила браковала:
   * действительное причастие берёт дополнение в винительном, а он у мужского,
   * среднего и женского на -ь совпадает с именительным.
   */
  test('причастие с дополнением — не ошибка рода', () => {
    const fine = [
      'Захватывающий геймплей, вызывающий зависимость',
      'Уникальный нарратив с рассказчиком, создающий погружение',
      'Отличная система подсказок, не портящая опыт игры',
      'Интересный сюжет, раскрывающий происхождение аниматроников',
      'Корабли получают боевой опыт, повышающий точность',
    ]
    for (const s of fine) expect(modelTextFlaw(s), s).toBeNull()
  })

  test('«не» вплотную к глаголу (CS2)', () => {
    expect(modelTextFlaw('Античит система полностью неэффективна и неработает')).toBe('grammar')
    // а причастие пишется слитно правильно
    expect(modelTextFlaw('Неработающий античит')).toBeNull()
  })

  /*
   * Правило согласования узкое намеренно: ложное срабатывание выбрасывает
   * честный плюс. Поэтому оно знает только частые слова отзывов и обходит
   * деепричастия, которые оканчиваются так же, как прилагательные женского
   * рода («изучая мир», «делая выбор», «запуская режим»), родительный
   * множественного («без обновлений игра»), относительное «который» и
   * несклоняемые «онлайн», «хоррор».
   */
  test('правильный русский не бракуется', () => {
    const fine = [
      'Огромный открытый мир, который хочется исследовать',
      'Красивая графика и атмосфера',
      'Тактическая глубина и командная игра',
      'Высокая реиграбельность',
      'Глубокая система крафта',
      'Сложная, но честная боёвка',
      'Отличная оптимизация даже на слабых ПК',
      'Интересное исследование мира',
      'Разнообразное оружие и удобное управление',
      'Каждый матч не похож на предыдущий',
      'Каждая карта уникальна',
      'Большая часть контента — за донат',
      'Последний патч сломал баланс',
      'Русская озвучка',
      'Ролевая система и боевая механика',
      'Затягивающий геймплей',
      'Хорошая музыка и стильный визуал',
      'Изучая мир, находишь секреты',
      'Делая выбор, чувствуешь последствия',
      'Запуская режим впервые, путаешься в меню',
      'Всё, включая сюжет, на высоте',
      'Без обновлений игра быстро надоедает',
      'Мир, который игра строит вокруг тебя',
      'Остальное игра делает отлично',
      'Отличная онлайн составляющая',
      'Атмосферная хоррор игра',
      'Отличный кооператив с друзьями',
      'Добавлен новый режим и переработана система прокачки',
      'Добавлено новое оружие, улучшено управление',
      'Новая глава кампании и 72 новых пала',
      'Исправлен баланс оружия; новый сезон',
      'Слабый сюжет',
      'Долгие загрузки',
      'Мало контента',
      'Красивая, хотя и устаревшая графика',
    ]
    for (const s of fine) expect(modelTextFlaw(s), s).toBeNull()
  })
})

describe('claimsNoUpdates', () => {
  test('«не обновляют» и «забросили» — утверждение про обновления', () => {
    const claims = [
      'Разработчики не обновляют игру и забросили её развитие',
      'Игра заброшена разработчиками',
      'Нет новых обновлений',
      'Обновлений нет уже давно',
      'Игра давно не обновлялась',
      'Старая игра, никогда не обновлялась издателем после выпуска',
      'Без обновлений',
      'Разработчики прекратили поддержку',
      'Разработчики забросили проект',
    ]
    for (const s of claims) expect(claimsNoUpdates(s), s).toBe(true)
  })

  test('минус про другое — не про обновления', () => {
    const other = [
      'Обновления ломают баланс',
      'Частые обновления сбрасывают прогресс',
      'Заброшенные локации однообразны',
      'Не поддерживает геймпад',
      'Мало контента',
      'Сюжет забросили на полпути',
      // не про игру, а про её часть: свежим патчам мультиплеера не противоречит
      'Кампания содержит баги, неполная и не обновляется вместе с мультиплеером',
      'Древняя графика, не обновлялась много лет',
    ]
    for (const s of other) expect(claimsNoUpdates(s), s).toBe(false)
  })
})

describe('пункты одной строкой', () => {
  test('каждый пункт — своё предложение, без «; » и строчной путаницы', () => {
    // хаб жанра склеивал «…повторяемость; Богатая история» — заглавная после
    // точки с запятой читается опечаткой
    expect(pointsLine(['Высокая повторяемость', 'Богатая история.'])).toBe(
      'Высокая повторяемость. Богатая история.',
    )
    expect(pointsLine(['PvP-режим!', '  Кооператив  на  четверых '])).toBe('PvP-режим. Кооператив на четверых.')
    expect(pointsLine([])).toBe('')
  })

  test('point снимает собственный знак в конце и лишние пробелы', () => {
    expect(point('  Огромный  открытый мир!  ')).toBe('Огромный открытый мир')
    expect(point('Оптимизация на ПК.')).toBe('Оптимизация на ПК')
  })
})
