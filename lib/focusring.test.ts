import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'vitest'

/**
 * Сторож видимого фокуса.
 *
 * Общее правило `:focus-visible` в globals.css рисует кольцо в два слоя и
 * заведено было ровно по одной причине: пройти продукт с клавиатуры можно было,
 * но вслепую. Его докблок начинается словами «браузерное кольцо снималось у
 * инпута через outline-none».
 *
 * ПОСЛЕ ЭТОГО КОЛЬЦО СНЯЛИ У ИНПУТА ЕЩЁ РАЗ. Одной строкой:
 *
 *     .field:focus { outline: none; border-color: var(--ember); … }
 *
 * Специфичность `.field:focus` — 0,2,0, у общего правила — 0,1,0. Класс
 * выигрывает, кольцо не рисуется. Единственное поле продукта — то самое, куда
 * вводят ссылку на профиль, — оставалось без видимого фокуса.
 *
 * Почему это не заметили глазом: рядом стояло `border-color: var(--ember)`, и
 * рамка при фокусе честно загоралась тёплым. Кадр выглядел отзывчивым. Не
 * хватало только кольца, а его отсутствие видно, лишь когда знаешь, что оно
 * должно быть.
 *
 * Замерено настоящими событиями Tab через протокол (не программным .focus()):
 * на десятом шаге обхода продовой страницы `outline-style: none` при
 * `:focus-visible` = true.
 *
 * Отсюда и сторож. Комментарий здесь не работает: правило снимается одной
 * строкой в любом новом классе, и следующий раз будет таким же незаметным.
 */

const RAW = fs.readFileSync(path.join(__dirname, '..', 'app', 'globals.css'), 'utf8')

/**
 * Комментарии гасятся пробелами той же длины — иначе сторож ловит объяснение,
 * зачем он заведён (докблок выше цитирует само правило). Номера строк в жалобе
 * при этом остаются настоящими. Тот же приём: lib/backdrop.test.ts.
 */
const CSS = RAW.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))

describe('видимый фокус', () => {
  test('кольцо не снимается в стилях', () => {
    const offenders: string[] = []
    CSS.split('\n').forEach((line, i) => {
      if (/outline:\s*(none|0)\b/.test(line)) offenders.push(`globals.css:${i + 1} — ${line.trim()}`)
    })
    expect(
      offenders,
      'outline: none в классе перебивает общее :focus-visible по весу, и обход с клавиатуры слепнет; ' +
        'для целей программного переноса фокуса есть tabIndex={-1} с утилитой в разметке',
    ).toEqual([])
  })

  /**
   * Обратная половина сделки. Тест выше останется зелёным и в том случае, если
   * однажды удалят само общее правило: снимать будет нечего. Здесь проверяется,
   * что кольцо вообще объявлено.
   */
  test('общее правило по-прежнему рисует кольцо', () => {
    const at = CSS.indexOf(':focus-visible {')
    expect(at, 'правило :focus-visible не найдено').toBeGreaterThan(-1)
    const block = CSS.slice(at, CSS.indexOf('}', at))
    expect(block, ':focus-visible без outline — это и есть слепой обход').toMatch(
      /outline:\s*\d+px\s+solid/,
    )
    expect(block, 'подложка под кольцом держит его видимым на игровом арте').toMatch(/box-shadow:/)
  })
})
