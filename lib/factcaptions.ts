import { plural } from './plural'

/**
 * ПОДПИСИ ПОД ТРЕМЯ ЧИСЛАМИ ПОРТРЕТА.
 *
 * Они были статическими строками — «игр в библиотеке», «часов сыграно», «так
 * и не запущены», — то есть не согласовывались с числом никогда. На демо-
 * библиотеке это читалось как «22 игр в библиотеке»; правильно «22 игры».
 * Ошибка выпадает на каждое число, оканчивающееся на 1 и на 2–4, кроме
 * одиннадцати-четырнадцати, — то есть примерно на треть всех значений.
 *
 * Обиднее всего место. Портрет — единственная страница продукта, сделанная
 * ради того, чтобы её отправляли другим, и те же три подписи стоят в карточке
 * для мессенджеров (share-card.tsx). Неверное окончание уезжало в чужой чат
 * картинкой, которую уже не отозвать.
 *
 * Инструмент при этом был: plural() лежит в lib и вызывается в том же файле
 * портрета шесть раз. Просто подпись приходила в <Fact> отдельным пропом от
 * значения, и согласовывать было нечего — связь между числом и словом
 * существовала только в голове у того, кто писал разметку.
 *
 * Отсюда этот файл: одна функция на страницу и на карточку. Дублировать
 * подписи в двух местах — значит однажды поправить их в одном.
 */

/** «1 игра в библиотеке» · «22 игры в библиотеке» · «5 игр в библиотеке» */
export function gamesCaption(n: number): string {
  return `${plural(n, 'игра', 'игры', 'игр')} в библиотеке`
}

/** «1 час сыгран» · «22 часа сыграно» · «5 часов сыграно» */
export function hoursCaption(n: number): string {
  return `${plural(n, 'час', 'часа', 'часов')} ${plural(n, 'сыгран', 'сыграно', 'сыграно')}`
}

/** «1 так и не запущена» · «22 так и не запущены» */
export function unplayedCaption(n: number): string {
  return `так и не ${plural(n, 'запущена', 'запущены', 'запущены')}`
}
