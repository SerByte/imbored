/**
 * Размер кадра скриншота под место показа.
 *
 * В базе лежит `path_full` из appdetails, а это всегда 1920×1080 по ~350 КБ.
 * Обычной картинке такой вес прощается — браузер сам решит, когда её тянуть.
 * WebGL-слайдеру не прощается: он грузит все кадры сразу и держит их
 * распакованными в видеопамяти, где 1920×1080 стоит 8 МБ независимо от того,
 * во сколько ужался JPEG. Шесть кадров — это 2 МБ трафика и полсотни мегабайт
 * VRAM, и всё это ради блока шириной в 375 CSS-пикселей на телефоне.
 *
 * Steam отдаёт ровно два размера одного кадра. Промежуточных нет: 1024×576 и
 * 1280×720 отвечают 404 (проверено 13.08.2026). Поэтому выбор бинарный, и
 * делается он подменой размера прямо в имени файла — заново ходить в
 * appdetails за `path_thumbnail` не нужно.
 */

export type ShotSize = 'small' | 'full'

/**
 * Сколько кадров крутит полноэкранный герой.
 *
 * Живёт здесь, а не в компоненте, потому что число знают обе стороны: герой —
 * чтобы обрезать список, и /api/recommend — чтобы не тащить в ответ кадры,
 * которых никто не покажет.
 *
 * Упирается не в красоту, а в цену. Герою кадры нужны полноразмерные, по
 * ~350 КБ, и движок держит их все распакованными в видеопамяти. На /play
 * пятёрку подборки листают руками, и каждая новая игра — это полный комплект
 * заново: на четырёх кадрах проход по всем пяти стоил около 7 МБ трафика.
 * Три кадра дают ~1 МБ на игру и ~25 МБ видеопамяти, а на глаз разница между
 * тремя и четырьмя не читается — герой редко живёт дольше одного круга.
 */
export const HERO_SLIDES = 3

/** 1920×1080 — то, что приезжает в базу из appdetails */
const FULL = '1920x1080'
/** 600×338 — он же path_thumbnail, в семь раз легче */
const SMALL = '600x338'

/**
 * Размер в имени файла: `ss_<hash>.1920x1080.jpg` перед концом строки или `?t=`.
 *
 * Список размеров закрытый, а не `\d+x\d+`: подставить стимовский размер в
 * чужую ссылку — гарантированный 404, и лучше отдать её нетронутой. Якорь на
 * расширение отсекает совпадения где-нибудь в середине пути.
 */
const SIZE_RE = /\.(1920x1080|600x338)\.(jpe?g|png)(?=$|\?)/i

/**
 * Ссылка на тот же кадр в нужном размере.
 *
 * Всё, что не похоже на скриншот Steam, возвращается как есть: в каталоге
 * живут игры других магазинов с отрицательным appid, и их пути к этому
 * шаблону отношения не имеют.
 */
export function shotUrl(url: string, size: ShotSize): string {
  const want = size === 'small' ? SMALL : FULL
  return url.replace(SIZE_RE, (whole, dims: string, ext: string) =>
    dims.toLowerCase() === want ? whole : `.${want}.${ext}`,
  )
}

/**
 * Какой размер брать под фактическую ширину блока.
 *
 * Порог 900 физических пикселей стоит чуть выше маленького кадра с запасом на
 * ретину: телефон в 375 CSS-пикселей при DPR 2 просит 750, и шестисотпиксельный
 * кадр там от полного почти неотличим. Всё, что шире, уже заметно мылит —
 * туда идёт 1920.
 *
 * DPR выше двух срезается: третьего размера у Steam всё равно нет, а движок
 * слайдера и сам ограничивает плотность канваса двойкой.
 */
export function pickShotSize(cssWidth: number, dpr: number): ShotSize {
  const density = Math.min(Math.max(dpr, 1), 2)
  return cssWidth * density <= 900 ? 'small' : 'full'
}

/** Оба размера кадра — 16:9, поэтому пропорция одна на всю функцию */
const SHOT_ASPECT = 16 / 9

/**
 * То же решение, но для бокса, который может резать кадр по высоте.
 *
 * pickShotSize исходит из того, что ширина бокса и есть ширина картинки. Для
 * блока 16:9 это правда, для полноэкранного героя — нет: в бокс 375×812 кадр
 * вписывается по высоте и растягивается почти на 1400 CSS-пикселей ширины, из
 * которых видно 375. Спросив по ширине бокса, мы получили бы шестисотпиксельный
 * кадр там, где нужно вчетверо больше, и мыло на весь экран.
 *
 * Считаем, какой ширины картинка окажется на самом деле, и отдаём тот же порог:
 * держать его в одном месте важнее, чем сэкономить вызов. На боксе шире кадра
 * cover упирается в ширину, максимум берёт её, и ответ сходится с pickShotSize
 * структурно, а не по счастливому совпадению.
 */
export function pickCoverShotSize(cssWidth: number, cssHeight: number, dpr: number): ShotSize {
  return pickShotSize(Math.max(cssWidth, cssHeight * SHOT_ASPECT), dpr)
}
