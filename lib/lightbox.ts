/**
 * Листание в лайтбоксе: стрелки, кнопки и свайп сходятся в одном шаге.
 *
 * Открытый кадр листался только стрелками клавиатуры. Мышью и пальцем — никак:
 * внутри окна была одна кнопка, «Закрыть», а свайп по кадру уходил в фон
 * страницы. На телефоне человек открывал кадр и мог только закрыть его.
 *
 * Модуль без импортов: components/Lightbox.tsx отдаёт сюда числа, решения
 * проверяются в node — lib/lightbox.test.ts.
 */

/**
 * Сколько пикселей по горизонтали — уже свайп, а не дрожь пальца на нажатии.
 * Нажатие по фону закрывает окно, и порог отделяет «листнул» от «ткнул».
 */
export const SWIPE_MIN = 48

/**
 * Шаг от свайпа: -1 — назад, 1 — вперёд, 0 — не свайп.
 *
 * Палец ведут влево, чтобы увидеть следующий кадр — как в любой галерее
 * телефона. Движение, больше вертикальное, чем горизонтальное, — не свайп:
 * это попытка прокрутить или жест закрытия, и листать на нём нельзя.
 */
export function swipeStep(dx: number, dy: number): -1 | 0 | 1 {
  if (Math.abs(dx) < SWIPE_MIN || Math.abs(dx) <= Math.abs(dy)) return 0
  return dx < 0 ? 1 : -1
}

/** Индекс после шага — по кругу, как у стрелок. */
export function stepIndex(index: number, step: number, count: number): number {
  if (count <= 0) return 0
  return (((index + step) % count) + count) % count
}

/**
 * Выше этого масштаба визуального вьюпорта страница увеличена щипком.
 *
 * Не ровно 1: после щипка обратно браузер оставляет масштаб с хвостом
 * округления, и «увеличение» на тысячные доли не должно отнимать свайп.
 */
export const ZOOM_EPS = 1.01

/** Увеличена ли страница щипком; масштаба нет (без visualViewport) — нет. */
export function zoomedIn(scale: number | undefined): boolean {
  return (scale ?? 1) > ZOOM_EPS
}

/**
 * Начинает ли это нажатие свайп по кадрам.
 *
 * На увеличенной щипком странице палец и перо водят по кадру: увеличивают,
 * чтобы рассмотреть угол, и один палец обязан этот угол двигать. Листание
 * там же уводило к следующему кадру, оставляя увеличенным тот же угол.
 * Листают увеличенный кадр кнопки по бокам и стрелки клавиатуры, а щипок
 * обратно возвращает и свайп.
 *
 * Мышь — исключение: вьюпорт она не двигает и при щипке трекпадом, а click
 * после её протяжки приходит всегда. Не начни нажатие свайп — этот click
 * закрыл бы окно, и протяжка вместо листания убирала бы кадр.
 */
export function pressSwipes(pointerType: string, scale: number | undefined): boolean {
  return pointerType === 'mouse' || !zoomedIn(scale)
}
