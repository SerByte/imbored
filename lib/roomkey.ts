import { createHmac } from 'node:crypto'

/**
 * Ключ участника комнаты — то, чем ростер называет человека наружу.
 *
 * Раньше это был hashString(roomId + steamid): 32-битный FNV-1a без ключа.
 * Код комнаты виден каждому, кто в неё зашёл, а личных SteamID64 — порядка
 * 2^31, так что перебор всего пространства возвращал steamid по одному ключу
 * за минуты на ноутбуке. А в открытую комнату с доски «Пати» подсаживаются
 * незнакомые, и ради них steamid наружу не отдаётся вовсе (шапка lib/room).
 *
 * HMAC с серверным секретом перебором не обращается: без секрета ключ не
 * посчитать даже для известного steamid. Двенадцать знаков base64url — 72
 * бита: для различения участников одной комнаты с огромным запасом.
 *
 * Код комнаты в сообщении — чтобы один человек в двух комнатах получил разные
 * ключи и сшить его по ним было нельзя.
 *
 * Отдельный модуль, а не lib/room: тот тянут клиентские компоненты ростера, а
 * node:crypto в клиентскую сборку не едет. Секрет приходит аргументом — модуль
 * не знает, откуда он, и проверяется без окружения.
 */
export function memberKey(secret: string, roomId: string, steamid: string): string {
  return createHmac('sha256', secret).update(`${roomId}:${steamid}`).digest('base64url').slice(0, 12)
}
