/**
 * ЗАГОЛОВОК ПАТЧА БЕЗ НАЗВАНИЯ ИГРЫ, КОТОРОЕ УЖЕ СТОИТ СТРОКОЙ ВЫШЕ.
 *
 * Строка ленты устроена так: крупно название игры, под ним заголовок патча.
 * Заголовок приходит из Steam как есть, а издатели пишут его в расчёте на то,
 * что он будет стоять сам по себе, — и очень часто начинают с названия игры.
 * В ленте выходит:
 *
 *   Portal 2
 *   Portal 2 - Update
 *
 *   Dead Cells
 *   Dead Cells Stability Patch: Less Null Access, More Monster Slaying.
 *
 * Замерено на 107 крупных патчах из локальной базы: так написаны 19, то есть
 * каждая пятая строка ленты. Это не редкий случай, а привычка источника.
 *
 * Чистим на показе, а не при записи: в базе заголовок обязан остаться таким,
 * каким его написал издатель — по нему сверяются с оригиналом, ссылка на
 * который стоит рядом в той же карточке.
 */

/** Разделители, которыми издатели отбивают название от сути патча. */
const SEP = '[-–—:·|]'

/**
 * Убирает из заголовка ведущее название игры вместе с разделителем.
 * Если название не в начале или после него ничего не остаётся — заголовок
 * возвращается нетронутым.
 */
export function stripGameName(title: string, gameName: string): string {
  const t = (title ?? '').trim()
  const name = (gameName ?? '').trim()
  if (!t || !name) return t

  const escaped = nameSource(name)
  /*
   * Заглядывание вперёд обязательно. Без него игра «Rust» срезала бы четыре
   * буквы у «Rusty Update» и оставляла «y Update»: совпадение по префиксу — не
   * то же самое, что совпадение по названию.
   */
  const re = new RegExp(`^${escaped}(?=$|[\\s${SEP.slice(1, -1)}])\\s*${SEP}*\\s*`, 'i')
  const rest = t.replace(re, '').trim()

  // Заголовок был ровно названием игры — оставляем как есть, иначе строка пуста
  if (!rest || rest === t) return t
  return capitalizeWord(rest)
}

/** Название игры как исходник регулярки: буквально, пробелы — любой длины */
function nameSource(name: string): string {
  return name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\s+/g, '\\s+')
}

/**
 * Текст без названия игры — где бы оно в нём ни стояло, сколько бы раз ни
 * повторялось. Для показа не годится (там срезается только ведущее, см.
 * stripGameName), годится для вопросов О заголовке.
 *
 * Valve пишет каждое обновление CS2 одной строкой «Обновление Counter-Strike
 * 2» — название в конце, и stripGameName его законно не трогает. Но два
 * решения о заголовке обязаны название не замечать:
 *   - <title> страницы патча (newsPageTitle): есть ли в заголовке номер
 *     версии, или без даты все патчи игры называются одинаково, — «2» из
 *     названия версией не считается; и не повторить ли имя игры впереди;
 *   - язык заголовка (textLang): имя собственное в латинице перевешивало
 *     русские слова, и русский заголовок уходил английским голосом.
 *
 * Граница — не буква и не цифра с обеих сторон, по той же причине, что
 * заглядывание вперёд у stripGameName: «Rust» не вырезается из «Rusty».
 */
export function withoutGameName(text: string, gameName: string | null | undefined): string {
  const name = (gameName ?? '').trim()
  if (!text || !name) return text
  const re = new RegExp(`(?<![\\p{L}\\p{N}])${nameSource(name)}(?![\\p{L}\\p{N}])`, 'giu')
  return text.replace(re, ' ').replace(/\s+/g, ' ').trim()
}

/**
 * Первая буква — заглавной, но только если остаток начинается СЛОВОМ.
 *
 * После срезки хвост нередко начинается со строчной: «Black Myth: Wukong —
 * описание обновления 1.0.21» превращается в «описание обновления 1.0.21», и
 * под дисплейным заголовком это читается как обрубок.
 *
 * Условие узкое намеренно. У «Palworld v1.0 - Official Release Changelog»
 * остаток начинается с «v1.0», и заглавная там была бы прямой ошибкой —
 * версия пишется как пишется. Поэтому поднимаем регистр, только если первое
 * слово целиком из букв и не короче трёх: «описание» подходит, «v1» нет.
 */
function capitalizeWord(s: string): string {
  const first = s.split(/[\s]/, 1)[0] ?? ''
  if (!/^\p{L}{3,}$/u.test(first)) return s
  return s[0].toUpperCase() + s.slice(1)
}
