import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'vitest'

/**
 * Сторож: фокус не заходит в невидимое.
 *
 * Сцены главной прячут содержимое начальным состоянием внутри `build`/`enter`
 * — так и задумано, и на «уменьшить движение» эти функции не вызываются вовсе.
 * Но способ прятать имеет значение.
 *
 * `opacity: 0` гасит пиксели и НЕ трогает ни обход с клавиатуры, ни попадание
 * курсором. Элемент невидим — и при этом фокусируем, нажимаем, озвучиваем
 * скринридером.
 *
 * ЗАМЕРЕНО НА ПРОДЕ настоящими событиями Tab через протокол: из 34 остановок
 * фокуса ПЯТЬ приходились на элементы с эффективной непрозрачностью 0 —
 * четыре переключателя сцены подбора (шаги 15–18) и парадная кнопка сцены
 * денег (шаг 25). Нажатие Enter на чипе не меняло ни `aria-pressed`, ни
 * подборку: замерено снимком состояния до и после.
 *
 * Отдельно стоит сказать, ПОЧЕМУ это не поймали раньше. Прошлый обход считал
 * элемент дошедшим по двум признакам: рамка в пределах экрана и объявленное
 * `outline`. Оба отвечают «да» на `opacity: 0`. Инструмент не соврал — он
 * мерил не то, и отчёт «фокус доходит, кольцо видно» был неверен. Видимость
 * добавили в замер только после того, как снимок кадра показал пустую правую
 * половину экрана под сфокусированной кнопкой.
 *
 * Лечится штатным средством GSAP: `autoAlpha` — прозрачность плюс
 * `visibility`, и на нуле элемент выпадает из обхода сам. Ни строчки в CSS,
 * ни новой сущности в Stage.
 *
 * Сторож статический и намеренно грубый: любое начальное обнуление в сценах
 * обязано быть `autoAlpha`. Разбирать по месту, есть ли в поддереве
 * фокусируемое, бессмысленно — ссылку туда добавят завтра, и правило сгниёт.
 */

const DIR = path.join(__dirname, '..', 'components', 'landing', 'scenes')

/** Комментарии гасятся пробелами: докблоки цитируют само правило. Номера строк
 *  при этом остаются настоящими. Тот же приём: lib/backdrop.test.ts. */
const strip = (src: string) => src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))

describe('фокус не заходит в невидимое', () => {
  test('начальное обнуление в сценах — autoAlpha, а не opacity', () => {
    const offenders: string[] = []
    for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('.tsx'))) {
      strip(fs.readFileSync(path.join(DIR, file), 'utf8'))
        .split('\n')
        .forEach((line, i) => {
          if (/gsap\.set\(/.test(line) && /\bopacity:\s*0\b(?!\.)/.test(line)) {
            offenders.push(`${file}:${i + 1} — ${line.trim()}`)
          }
        })
    }
    expect(
      offenders,
      'opacity: 0 оставляет элемент в обходе с клавиатуры и под курсором; autoAlpha снимает его с обхода',
    ).toEqual([])
  })

  /**
   * Обратная половина сделки. Тест выше зелёный и в том случае, если обнуления
   * просто удалят, — а тогда сцены перестанут собираться. Здесь проверяется,
   * что механизм вообще на месте и что возвращают его тем же свойством: пара
   * `autoAlpha: 0` без `autoAlpha: 1` оставила бы содержимое скрытым навсегда.
   */
  test('спрятанное возвращается тем же свойством', () => {
    for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('.tsx'))) {
      const src = strip(fs.readFileSync(path.join(DIR, file), 'utf8'))
      const hides = (src.match(/autoAlpha:\s*0\b/g) ?? []).length
      if (!hides) continue
      expect(
        (src.match(/autoAlpha:\s*1\b/g) ?? []).length,
        `${file}: спрятано autoAlpha ${hides} раз, а возвращено ни разу — содержимое осталось бы скрытым`,
      ).toBeGreaterThan(0)
    }
  })
})
