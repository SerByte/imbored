import { revalidateSitePath } from './revalidate'

/**
 * Адрес карточки комнаты в мессенджере — тот, под которым её кэширует ISR
 * (app/room/[id]/opengraph-image.tsx, revalidate = 300). Групп и
 * параллельных сегментов в пути нет, поэтому Next не добавляет к имени
 * хеш-хвост (getMetadataRouteSuffix), и путь совпадает с адресом картинки
 * без её «?<хеш>» — по нему же ставится неявный тег, который снимает
 * revalidatePath.
 */
export function roomCardPath(roomId: string): string {
  return `/room/${roomId}/opengraph-image`
}

/**
 * Сбросить карточку комнаты, когда комната сошлась.
 *
 * Билет «зовёт выбрать игру» ложится в кэш ещё в лобби: ссылку на комнату
 * кидают в чат первым делом, и краулер мессенджера тут же тянет картинку.
 * Пять минут кэша — и пати, сошедшаяся за эти минуты (колода в двадцать карт
 * свайпается быстрее), нажимала «Поделиться» на экране матча и получала в
 * чате приглашение свайпать в комнату, где выбирать уже нечего. Заголовок
 * страницы при этом уже говорил «сошлась» — он собирается на каждый запрос.
 *
 * Только картинка, а не сама страница: её layout читает headers(), и она
 * рендерится заново на каждый заход — сбрасывать там нечего.
 *
 * Из Route Handler revalidatePath ничего не рендерит сам: путь помечается, и
 * карточка перерисуется на следующем заходе краулера (docs Next,
 * revalidatePath.md; opengraph-image — особый Route Handler, его путь
 * принимается так же).
 *
 * Сбой сброса матч не роняет. Матч к этой строке уже записан
 * (setRoomMatched), и пятисотка в ответ на последний голос показала бы
 * «Голос не ушёл — карточка вернулась» над комнатой, которая сошлась.
 * Карточка в худшем случае догонит сама — через свои пять минут.
 *
 * revalidate — аргументом, как у revalidateGamePages (lib/gamecache): вне
 * сервера Next настоящий revalidatePath бросает.
 */
export function forgetRoomCard(
  roomId: string,
  revalidate: (path: string) => void = revalidateSitePath,
): void {
  try {
    revalidate(roomCardPath(roomId))
  } catch {
    // см. выше: карточка догонит сама, матч важнее
  }
}
