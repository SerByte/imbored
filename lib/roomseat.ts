import { NextResponse } from 'next/server'

/**
 * Кем сессия сидит в комнате — и может ли действовать от имени участника.
 *
 * Участник комнаты — это steamid: на нём членство, голоса, право хоста
 * (rooms.created_by) и личные потолки. А сессию на ЛЮБОЙ открытый профиль
 * /api/connect выдаёт без доказательства владения (Resolved.verified в
 * lib/sessions). Пока членство не помнило, как оно заведено, сессия по
 * вставленной чужой ссылке была в комнате неотличима от самого человека:
 * читала его «играем» (/likes отдаёт их по именам), голосовала за него —
 * хоть добирая единогласие до матча, хоть «нет» на чужую любимую игру, —
 * уводила его из пати вместе со всеми голосами, а на профиль хоста убирала
 * остальных. Довод «голос живёт внутри комнаты и профиль не трогает» здесь
 * не работал: в комнате профиль и есть личность.
 *
 * Правило то же, что у Resolved.verified: кука, полученная без
 * доказательства, не действует поверх куки, полученной с ним. Поэтому
 * членство помнит, заведено ли оно пишущей сессией (room_members.writer,
 * isWriter в lib/server — вход через Steam или демо-личность, которую не
 * выдают никому, кроме её посетителя), и такое членство действует только от
 * пишущей сессии.
 *
 * Что остаётся открытым, и это решение, а не недосмотр:
 *   • вход по своей ссылке и всё, что участник делает в комнате, — так в
 *     пати подключается большинство друзей (README, «Режим пати»);
 *   • членство, заведённое по ссылке, не отличает самого человека от чужой
 *     ссылки на тот же профиль. Различить их без входа через Steam нечем:
 *     привязка к sid заперла бы честного гостя, переподключившегося с
 *     другого устройства (новое подключение — новый sid). Вошёл через Steam
 *     и открыл пати — членство поднимается, и дальше оно его: с приглашения
 *     или с ?join= это делает сам вход (joinRoom), а вошедшему через Steam
 *     где-то ещё — первая же колода или голос в этой комнате (seatToRaise
 *     ниже). До того членство остаётся заведённым по ссылке;
 *   • посадить в комнату профиль, которого там ещё нет, по-прежнему может
 *     любая ссылка — это тот же вход по ссылке, только чужой.
 *
 * Хозяйские права (убрать другого, доска) требуют пишущей сессии и сверх
 * этого — leave/route.ts и public/route.ts: хозяином комнаты может оказаться
 * и участник по ссылке (передача хоста в removeRoomMember).
 *
 * Личные потолки роутов комнаты (room-vote, room-likes, room-deck,
 * room-trivia, room-leader) считаются по personalRateId (lib/ratelimit), а не
 * по голому steamid, — по той же причине. Чужая ссылка на профиль сажала его
 * в любую комнату, хоть в собранную тут же с демо, и выедала там потолки,
 * общие с настоящим человеком: сто двадцать голосов в минуту — и в своей пати
 * он свайпал в 429.
 *
 * Потолка адреса вторым гейтом, которого personalRateId требует от дорогих
 * ручек, здесь нет, и он не нужен. Сессия по ссылке действует только за
 * членство, заведённое по ссылке (seatOf), а свежую сессию на тот же профиль
 * /api/connect чеканит не чаще своего лимита по адресу — ровно как сессию на
 * другой открытый профиль, которую так же можно было посадить в комнату и до
 * этой правки. Лишнего объёма ключ по сессии не открывает. А потолок адреса
 * на опросе и свайпе ударил бы по своим: компания в одной квартире — один
 * адрес.
 */
export type Seat =
  /** участник, и эта сессия вправе действовать от его имени */
  | 'member'
  /** участник есть, но вошёл пишущей сессией, а эта — нет */
  | 'needsteam'
  /** такого участника в комнате нет */
  | 'none'

export function seatOf(
  members: ReadonlyArray<{ steamid: string; writer: boolean }>,
  steamid: string,
  writer: boolean,
): Seat {
  const member = members.find((m) => m.steamid === steamid)
  if (!member) return 'none'
  return member.writer && !writer ? 'needsteam' : 'member'
}

/**
 * Пишущая сессия действует за членство, заведённое по ссылке, — его пора
 * поднять (raiseRoomSeat в lib/db).
 *
 * Иначе обещание выше — «вошёл через Steam, и дальше членство его» —
 * держалось бы только на одном пути: входе в комнату с ?join=. Друг, вошедший
 * в пати по ссылке и потом через Steam со строки на /play, оставался бы в
 * комнате членом по ссылке, и любая чужая ссылка на его профиль по-прежнему
 * голосовала бы за него. Зовут роуты колоды и голоса, а не опрос: опрос идёт
 * у каждого каждые 2.5 секунды и обязан оставаться чтением, а запись здесь —
 * однажды на членство, первым же жестом.
 */
export function seatToRaise(
  members: ReadonlyArray<{ steamid: string; writer: boolean }>,
  steamid: string,
  writer: boolean,
): boolean {
  return writer && members.some((m) => m.steamid === steamid && !m.writer)
}

/**
 * Отказ роута участника, если сессия не может действовать от его имени.
 *
 * needsteam — тем же кодом, что у пишущих роутов (requireWriter): страница
 * узнаёт его через isNeedSteam (lib/writer) и говорит «войди через Steam», а
 * не «нажми ещё раз». Зовётся после потолка просмотра и проверки «комната
 * есть»: needsteam значит, что комната существует, — а это ровно то, что
 * потолок room-peek (lib/roompeek) и прячет от перебора.
 */
export function seatRefusal(seat: Seat): NextResponse | null {
  if (seat === 'needsteam') return NextResponse.json({ error: 'needsteam' }, { status: 403 })
  if (seat === 'none') return NextResponse.json({ error: 'notmember' }, { status: 403 })
  return null
}
