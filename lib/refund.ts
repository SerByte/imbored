/**
 * Страховка покупки: Steam возвращает деньги за игру, если с покупки прошло
 * меньше двух недель и наиграно меньше двух часов.
 *
 * Для человека, который не знает, чего хочет, «купить» — самое дорогое из
 * решений на экране: к «а вдруг не зайдёт» добавляются деньги. Правило возврата
 * снимает ровно этот страх, и сказать о нём — не реклама, а факт, который
 * почти никто не держит в голове в момент выбора.
 *
 * Модуль без серверных зависимостей, по образцу lib/sources.ts: текст читают
 * клиентские страницы (/play, /daily), а решение «показывать ли» принимает
 * сервер. Текст и условие живут в одном месте, потому что правила Valve могут
 * поменяться, и тогда править придётся одну строку, а не три страницы.
 *
 * В промпт Claude это НЕ уходит, и это осознанно: возврат — факт интерфейса,
 * а не довод причины. Модель, которой разрешили упоминать возврат, начнёт
 * продавать «купи и верни», а за злоупотребление Steam перестаёт возвращать.
 */

