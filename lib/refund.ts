/** Месяцы в том виде, в каком их пишет магазин: английский и русский appdetails */
const MONTHS: RegExp[] = [
  /\bjan|янв/i,
  /\bfeb|фев/i,
  /\bmar|мар/i,
  /\bapr|апр/i,
  /\bmay|ма[йя]/i,
  /\bjun|июн/i,
  /\bjul|июл/i,
  /\baug|авг/i,
  /\bsep|сен/i,
  /\boct|окт/i,
  /\bnov|ноя/i,
  /\bdec|дек/i,
]

/**
 * Самый ранний момент, когда игра могла выйти (unix-секунды), или null — из
 * строки ничего не понять.
 *
 * Дата выхода приезжает двумя путями: GetItems даёт ISO («2025-06-16»), а
 * appdetails — строку в локали магазина («18 апр. 2011 г.», «4 кв. 2026 г.»,
 * «Скоро»). Date.parse здесь не помощник: он разбирает только английское и
 * охотно находит дату там, где её нет («hello 2011» у него — первое января).
 *
 * Нижняя граница, а не середина: «2027» — это не раньше первого января,
 * «4 кв.» — не раньше октября. Ошибка в эту сторону безобидна: для игры,
 * выход которой назван только месяцем, строка появится в начале месяца, а не
 * в день релиза.
 */
export function releaseStartSec(raw: string | undefined | null): number | null {
  if (!raw) return null
  const iso = raw.match(/^(\d{4})-(\d{2})-(\d{2})/)
  if (iso) return Date.UTC(Number(iso[1]), Number(iso[2]) - 1, Number(iso[3])) / 1000

  const y = raw.match(/(?:^|\D)((?:19|20)\d{2})(?!\d)/)
  if (!y) return null
  const year = Number(y[1])

  const month = MONTHS.findIndex((re) => re.test(raw))
  if (month >= 0) {
    // День — одно- или двузначное число рядом с месяцем; без него — первое
    const d = raw.match(/(?:^|\D)(\d{1,2})(?!\d)/)
    const day = d && Number(d[1]) >= 1 && Number(d[1]) <= 31 ? Number(d[1]) : 1
    return Date.UTC(year, month, day) / 1000
  }

  // «Q4 2026», «4 кв. 2026 г.»
  const q = raw.match(/\bq\s*([1-4])\b|([1-4])\s*(?:-?й\s*)?кв/i)
  if (q) return Date.UTC(year, (Number(q[1] ?? q[2]) - 1) * 3, 1) / 1000

  return Date.UTC(year, 0, 1) / 1000
}

/**
 * Можно ли обещать возврат.
 *
 *   — только Steam: у других магазинов свои правила, и чужое обещание от
 *     нашего имени было бы враньём (отсутствие store означает Steam);
 *   — только платное: у бесплатной возвращать нечего;
 *   — только вышедшее: у предзаказа в Steam свои, более мягкие правила, и
 *     «14 дней и 2 часа» про него неточны. Дату, которую не разобрать,
 *     считаем прошедшей: у такой строки почти всегда нет и цены.
 */
export function refundEligible(
  meta: Pick<GameMeta, 'store' | 'isFree' | 'priceFinal' | 'releaseDate'>,
  nowSec: number,
): boolean {
  if (meta.store) return false
  if (meta.isFree) return false
  if (meta.priceFinal === undefined || meta.priceFinal <= 0) return false
  const start = releaseStartSec(meta.releaseDate)
  return start === null || start <= nowSec
}
