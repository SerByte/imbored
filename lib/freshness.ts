import { fmtDate, pl, tr, type Locale } from './i18n'

const DAY = 86_400

/** Формы слова при числе — как их ждёт pl(): три русские, две английские */
type Forms = Parameters<typeof pl>[2]

/**
 * «N единиц назад» на языке подписи. one — как сказать про ровно одну
 * единицу: по-русски «неделю назад», по-английски «a week ago». Без one
 * единица идёт с числом, как остальные.
 */
function unitsAgo(locale: Locale, n: number, forms: Forms, one?: { ru: string; en: string }): string {
  if (n === 1 && one) return tr(locale, one)
  const word = pl(locale, n, forms)
  return tr(locale, { ru: `${n} ${word} назад`, en: `${n} ${word} ago` })
}

const DAYS: Forms = { ru: ['день', 'дня', 'дней'], en: ['day', 'days'] }

/**
 * Свежесть словами. В ленте это несёт больше смысла, чем полная дата: человек
 * листает сверху вниз и хочет понять «это вчера или полгода назад», а не
 * вычитать числа в уме. Точная дата остаётся рядом, в <time>.
 *
 * Живёт в lib/, а не рядом с разметкой, вместе с nextFreshnessTickMs: эти две
 * функции обязаны одинаково понимать, где проходит граница суток. Разъедься
 * они — и вкладка просыпалась бы не в тот момент, когда подпись меняется.
 * Плюс vitest собирает только lib/, а до переезда на freshness не было ни
 * одного теста.
 */
export function freshness(publishedAt: number, nowSec: number, locale: Locale = 'ru'): string {
  const days = Math.floor((nowSec - publishedAt) / DAY)
  if (days <= 0) return tr(locale, { ru: 'сегодня', en: 'today' })
  if (days === 1) return tr(locale, { ru: 'вчера', en: 'yesterday' })
  if (days < 7) return unitsAgo(locale, days, DAYS)
  /*
   * Границы считаются по ДНЯМ, а не по производной величине, и это чинит
   * настоящую дыру. Было `const m = days/30; if (m < 12)` — при 360–364 днях
   * m равно двенадцати, в месяцы запись уже не попадала, а y = days/365 ещё
   * равнялся нулю. Подпись выходила «0 лет назад» — пятидневное окно раз в год
   * на каждой карточке и в каждой строке ленты.
   *
   * Единица в этих оборотах опускается: по-русски говорят «неделю назад», а не
   * «1 неделю назад». Числовая форма была закреплена тестом, то есть выбрана
   * сознательно, — меняю её как раз потому, что весь остальной текст сайта
   * написан живым языком, а в обложке ленты подпись стоит капслоком с разрядкой,
   * где «1 НЕДЕЛЮ НАЗАД» особенно спотыкается. Двойка и дальше остаются числом:
   * «2 недели назад» — уже нормальная речь.
   *
   * По-английски единица тоже без цифры, но со своим артиклем: «a week ago»,
   * а не «1 week ago», — та же живая речь, а не перевод русского оборота.
   */
  if (days < 31) {
    return unitsAgo(
      locale,
      Math.floor(days / 7),
      { ru: ['неделю', 'недели', 'недель'], en: ['week', 'weeks'] },
      { ru: 'неделю назад', en: 'a week ago' },
    )
  }
  if (days < 365) {
    return unitsAgo(
      locale,
      Math.floor(days / 30),
      { ru: ['месяц', 'месяца', 'месяцев'], en: ['month', 'months'] },
      { ru: 'месяц назад', en: 'a month ago' },
    )
  }
  return unitsAgo(
    locale,
    Math.floor(days / 365),
    { ru: ['год', 'года', 'лет'], en: ['year', 'years'] },
    { ru: 'год назад', en: 'a year ago' },
  )
}

/**
 * Дата события словами, В ЗОНЕ UTC.
 *
 * Зона зафиксирована, и это чинит расхождение гидратации, а не вкусовщину.
 *
 * toLocaleDateString без timeZone берёт зону процесса. На сервере Vercel это
 * UTC, в браузере — зона читателя, и для всего, что опубликовано после
 * 21:00 UTC, стороны печатают РАЗНЫЕ дни. Замер на живой /game/730: из шести
 * элементов <time> четыре расходятся у московского читателя («12 августа» на
 * сервере против «13 августа» в браузере).
 *
 * Это не гонка, а константа: страница кэшируется надолго (карточка игры —
 * на неделю), разметка одна и та же для всех. React на расхождении
 * разматывает поддерево до ближайшей границы Suspense — а у этих страниц её
 * нет вовсе (loading.tsx сняты ради первого ответа без JS, см.
 * lib/firstpaint.test.ts), — то есть выбрасывает и перерисовывает весь
 * документ, не одну подпись.
 *
 * Почему именно UTC, а не зона читателя: дата выхода патча — это про
 * событие, а не про то, где стоит смотрящий. Показывать её в местной зоне
 * можно только дорисовкой после монтирования, то есть мигнув. Тот же выбор
 * уже сделан у dayLabel выше.
 */
export function dateLabel(atSec: number, opts: { year?: boolean; locale?: Locale } = {}): string {
  // fmtDate и есть Intl.DateTimeFormat: русская строка та же, что давал
  // toLocaleDateString('ru-RU'), а английская — «August 12, 2026».
  // timeZone задан здесь явно, хотя fmtDate и сам ставит UTC: причина
  // зафиксирована в докблоке выше, и она не должна держаться на чужом дефолте
  return fmtDate(opts.locale ?? 'ru', atSec, {
    day: 'numeric',
    month: 'long',
    ...(opts.year ? { year: 'numeric' as const } : {}),
    timeZone: 'UTC',
  })
}

/**
 * Давность в минутах — словами. Для доски пати, где счёт идёт на минуты и
 * часы, а не на дни: freshness() выше начинается с суток и всё, что моложе,
 * называет «сегодня».
 *
 * Часы обязательны. Комната живёт на доске до суток (PUBLIC_ROOM_MAX_AGE_SEC),
 * а подпись собиралась как `${minutes} мин назад` — то есть комната
 * двадцатитрёхчасовой давности честно писала «1380 мин назад».
 */
export function minutesAgoLabel(minutes: number, locale: Locale = 'ru'): string {
  if (minutes < 1) return tr(locale, { ru: 'только что', en: 'just now' })
  // «мин» — сокращение, оно не склоняется ни по-русски, ни по-английски
  if (minutes < 60) return tr(locale, { ru: `${minutes} мин назад`, en: `${minutes} min ago` })
  const h = Math.floor(minutes / 60)
  // Русская подпись про один час — с цифрой («1 час назад»), так она и жила;
  // по-английски «an hour ago»: «1 hour ago» звучит счётчиком, а не речью
  if (h < 24) {
    return unitsAgo(
      locale,
      h,
      { ru: ['час', 'часа', 'часов'], en: ['hour', 'hours'] },
      { ru: '1 час назад', en: 'an hour ago' },
    )
  }
  return unitsAgo(locale, Math.floor(h / 24), DAYS, { ru: '1 день назад', en: 'a day ago' })
}

/**
 * Подпись даты «19 августа» из ключа суток вида 2026-08-19.
 *
 * Именно ИЗ КЛЮЧА, а не из второго вызова new Date(), и это не педантизм.
 *
 * В app/api/daily ключ записи считался в UTC в начале обработки, а подпись —
 * отдельным new Date() в самом конце, уже после отбора. Отбор стоит около
 * полутора секунд (см. докблок там же), то есть запрос, начавшийся в
 * 23:59:59, дорисовывал подпись уже следующими сутками: «игра дня 20
 * августа» под выбором, записанным на 19-е.
 *
 * Вторая причина — зона. toLocaleDateString без timeZone берёт зону
 * рантайма. На Vercel это UTC, и сегодня всё сходится, но зависимость
 * подразумеваемая: достаточно кому-нибудь задать TZ, и подпись разъедется с
 * ключом навсегда, а не только на границе суток.
 */
export function dayLabel(dateStr: string, locale: Locale = 'ru'): string {
  return fmtDate(locale, new Date(`${dateStr}T00:00:00Z`), {
    day: 'numeric',
    month: 'long',
    timeZone: 'UTC',
  })
}

/** Запись из будущего (кривая дата в фиде) не должна давать нулевую задержку */
const MIN_TICK_MS = 1_000

/**
 * Ноутбук, проспавший границу суток, таймером не разбудить: setTimeout в
 * suspend не тикает. Потолок гарантирует, что подпись всё равно пересчитается
 * в обозримое время, а не через неделю.
 */
const MAX_TICK_MS = 6 * 3_600_000

/**
 * Через сколько миллисекунд подпись свежести может смениться.
 *
 * freshness() считает сутки ОТ publishedAt, а не от полуночи, поэтому граница
 * у каждой записи своя: publishedAt + (days + 1) * DAY. Берём ближайшую по
 * всей ленте и просыпаемся ровно на ней.
 *
 * Тикать ежеминутно было бы проще и заметно хуже: подпись меняется раз в
 * сутки, а перерисовка тридцати строк заставляет каждую заново пересчитать
 * число правок по всему телу патча — 1440 раз в день впустую.
 */
export function nextFreshnessTickMs(publishedAts: readonly number[], nowSec: number): number {
  let soonest = Number.POSITIVE_INFINITY
  for (const at of publishedAts) {
    const days = Math.floor((nowSec - at) / DAY)
    const boundary = at + (days + 1) * DAY
    const left = (boundary - nowSec) * 1000
    if (left < soonest) soonest = left
  }
  if (!Number.isFinite(soonest)) return MAX_TICK_MS
  return Math.min(MAX_TICK_MS, Math.max(MIN_TICK_MS, soonest))
}
