import { createHash, randomBytes } from 'node:crypto'

/**
 * Личная RSS-лента по секретной ссылке: /whatsnew/feed/<ключ>.
 *
 * ЗАЧЕМ. Личная лента «Что нового в твоих играх» видна только тому, кто
 * зашёл на /whatsnew, а пушей и писем в продукте нет намеренно (lib/wishlist,
 * «Пушей и писем нет»). RSS — тянет сам читатель, и это та же позиция: мы
 * никому ничего не шлём, ридер или телеграм-бот приходит за лентой сам.
 *
 * ПОЧЕМУ КЛЮЧ, А НЕ КУКА. Ридер и бот ходят без нашей куки, так что
 * доказательство — сам адрес. Отсюда всё остальное:
 *
 *   • 128 бит из crypto (как sid сессии, newSid в lib/session) — угадать
 *     нельзя, перебирать бессмысленно;
 *   • ключ показывается один раз, в ответе на выпуск, а в базе лежит только
 *     его sha256. Утечка базы (бэкап, выгрузка для отладки) не даёт ни одной
 *     рабочей ссылки. Соли нет, и она не нужна: соль спасает слабые пароли
 *     от словаря, а у случайного ключа в 128 бит словаря нет;
 *   • поиск — равенством по отпечатку в индексе. Время такого поиска может
 *     зависеть от префикса ОТПЕЧАТКА, но отпечаток подбирающий не выбирает:
 *     он выбирает ключ, а узнать по префиксу sha256 что-то о ключе нельзя.
 *     Поэтому timingSafeEqual здесь не нужен — сравнивать в JS нечего;
 *   • формат проверяется до базы (isFeedToken): мусор в адресе не стоит ни
 *     одного чтения.
 *
 * Модуль без базы и без Next — его читают роуты и тесты.
 */

/** Ключ: 16 байт случайности в hex — 32 знака, строчные */
const TOKEN_RE = /^[0-9a-f]{32}$/

/** Новый ключ ленты. Показывается человеку один раз и не хранится. */
export function newFeedToken(): string {
  return randomBytes(16).toString('hex')
}

/** Похож ли кусок адреса на ключ — до всякого похода в базу */
export function isFeedToken(token: unknown): token is string {
  return typeof token === 'string' && TOKEN_RE.test(token)
}

/** То, что хранится вместо ключа: sha256 в hex */
export function feedTokenHash(token: string): string {
  return createHash('sha256').update(token).digest('hex')
}

/**
 * Путь ленты — без origin. Адрес целиком собирает страница от того, где
 * человек сейчас (window.location.origin, как ссылка на выбор в SharePick):
 * ключ проверяет база, стоящая за этим адресом, и превью со своей базой
 * выдало бы ссылку на прод, где такого ключа нет.
 */
export function feedPath(token: string): string {
  return `/whatsnew/feed/${token}`
}

/**
 * Опрос ленты: шестьдесят в час на ссылку — раз в минуту.
 *
 * Ридеры ходят раз в 15–60 минут, телеграм-боты — бывает, что раз в
 * несколько минут; потолок с запасом выше любого из них. Он нужен против
 * ссылки, которая утекла и которую дёргают скриптом: каждый опрос — это
 * чтение снимка библиотеки и ленты, а платим за чтения мы.
 */
export const FEED_POLL_LIMIT = 60
export const FEED_POLL_WINDOW_SEC = 3600

/**
 * Выпуск, перевыпуск и отключение: десять в час. Человеку столько не нужно
 * никогда, а скрипт с чужой кукой не жжёт записи без предела.
 */
export const FEED_LINK_LIMIT = 10
export const FEED_LINK_WINDOW_SEC = 3600
