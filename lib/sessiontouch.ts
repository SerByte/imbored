/**
 * Когда эта вкладка последний раз продлевала вход — одна отметка на документ.
 *
 * Продление зовут двое: главная (components/landing/ConnectCard — ей нужен
 * ответ, он решает, что рисовать) и SessionKeeper на остальных страницах. Им
 * нужна одна отметка, иначе переход с главной клиентским роутером давал бы
 * второй вызов touch следом за первым.
 *
 * Отдельным модулем, а не в components/SessionKeeper, как было: сам
 * SessionKeeper теперь едет чанком закулисья (components/BackstageLazy), а
 * импорт отметки из компонента вёз бы его в первую загрузку главной, где ему
 * делать нечего. Модуль один на вкладку при любом числе чанков, так что
 * отметка у обоих общая. Сторож — lib/sharedchunk.test.ts.
 *
 * Отметка держится В ПАМЯТИ модуля, а не в sessionStorage. Разница не
 * косметическая: sessionStorage переживает перезагрузки и умирает только с
 * вкладкой, а вкладка на телефоне не закрывается месяцами — флаг там встал бы
 * навсегда, и продление не случилось бы ни разу. Память модуля живёт ровно
 * столько, сколько документ, то есть именно то, что нужно.
 *
 * Модуль без импортов: его читают главная и закулисье.
 */
const AGAIN_AFTER_MS = 12 * 60 * 60 * 1000

let lastTouch = 0

/** Главная зовёт /api/session/touch сама (ей нужен ответ) — пусть не дублируется */
export function markSessionTouched(): void {
  lastTouch = Date.now()
}

/**
 * Пора ли продлевать. Да — отметка ставится сразу, до ответа: второй вызов,
 * пока первый в пути (возврат на вкладку следом за загрузкой), не уходит.
 */
export function claimSessionTouch(): boolean {
  const now = Date.now()
  if (now - lastTouch < AGAIN_AFTER_MS) return false
  lastTouch = now
  return true
}

/** Продление не дошло — отметка снимается, и следующая попытка состоится */
export function forgetSessionTouch(): void {
  lastTouch = 0
}
