/**
 * Проверка адреса возврата (`next`).
 *
 * Появился он ради одной сцены: человек смотрит выдачу на демо-библиотеке и
 * жмёт «подключить свою». Возврат из Steam OpenID до сих пор был зашит на
 * /quiz, то есть подключившийся получал анкету заново вместо того места, где
 * стоял. То же касается входа с /daily, /library и игровых страниц.
 *
 * Но `next` целиком приходит снаружи и подставляется в Location. Существующие
 * join (^[A-Z0-9]{6}$) и compat (^\d{17}$) безопасны сами по себе: их форма не
 * оставляет места для адреса. Свободный путь такой роскоши не даёт, поэтому
 * здесь не «санитайзер», а белый список.
 *
 * Зависимостей у модуля нет намеренно: его импортирует и серверный роут, и
 * клиентский лендинг.
 */

/** Куда вообще осмысленно возвращать. /api/* отсутствует здесь не случайно. */
const ALLOWED_PREFIXES = [
  '/play',
  '/daily',
  '/quiz',
  '/library',
  '/rooms',
  '/room/',
  '/compat',
  '/portrait',
  '/whatsnew',
  '/game/',
  '/support',
] as const

/**
 * Потолок длины. Строку в Location никто не обрезает, а раздутый `next`
 * способен упереться в лимит заголовка у прокси — то есть сломать вход
 * способом, который со стороны выглядит как «Steam не работает».
 */
const MAX_LEN = 512

/**
 * Код бэкслэша. Сравниваем по коду, а не по литералу: символ, стоящий вплотную
 * к закрывающей кавычке, — классическое место для опечатки при правке, а цена
 * ошибки здесь — открытый редирект.
 */
const BACKSLASH = 92

/**
 * Бэкслэш, управляющие символы, пробел и DEL. Собрано перебором кодов, а не
 * регуляркой с escape-последовательностями: класс символов с экранированием
 * ровно здесь читается хуже всего и правится с ошибками.
 */
function hasForbiddenChar(s: string): boolean {
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i)
    if (c <= 32 || c === BACKSLASH || c === 127) return true
  }
  return false
}

/**
 * Подсвечивать ли пункт навигации на этом адресе.
 *
 * Живёт здесь, а не в компоненте, потому что навигаций две — шапка на
 * десктопе и нижняя панель на телефоне, — и расходиться в том, где ты сейчас,
 * они не имеют права. До появления функции разъезд был максимальный:
 * aria-current стоял только в панели, а панель скрыта на десктопе через
 * md:hidden. То есть с клавиатуры и со скринридером текущий раздел не
 * назывался вообще нигде, кроме телефона.
 *
 * `also` — адреса, которые пункт обязан подсвечивать, но по которым сам не
 * ведёт: выдача живёт на /play, а не на /quiz, комната на /room/<код>, а не
 * на /rooms.
 *
 * Корень сравнивается точно и только точно: иначе «/» подсвечивался бы
 * везде, потому что с него начинается любой путь.
 */
export function isNavActive(pathname: string, href: string, also: readonly string[] = []): boolean {
  return [href, ...also].some((p) => (p === '/' ? pathname === '/' : pathname === p || pathname.startsWith(`${p}/`)))
}

/**
 * С чем человек пришёл на главную.
 *
 * Отдельно от компонента, потому что главная перестала читать параметры
 * через useSearchParams. Причина замерена: этот хук в статически
 * пререндеренном маршруте роняет ВЕСЬ маршрут в клиентский рендер
 * (BAILOUT_TO_CLIENT_SIDE_RENDERING), и прод отдавал по адресу imbored.cc
 * 20 879 байт разметки, в которых 232 символа видимого текста — шапка и
 * подвал. Ни заголовка, ни формы, ни кнопки «Войти через Steam»: до
 * разбора ~186 КБ сжатого JS на главной странице сайта не было НИЧЕГО.
 *
 * Теперь разметка пререндерится с вариантом «человек пришёл сам», а
 * параметры прибытия применяются сразу после гидратации. Это осознанный
 * размен: подзаголовок и подпись кнопки у пришедшего по приглашению
 * меняются на кадр позже, зато страница существует до того, как приедет JS.
 */
export type Arrival = {
  /** код пати из приглашения, в верхнем регистре */
  join: string | null
  /** steamid, с кем сравниваться */
  compat: string | null
  /** куда вернуть после подключения; уже пропущен через safeNext */
  next: string | null
  /** код ошибки предыдущего шага; смысл кодов знает app/page.tsx */
  error: string | null
}

/** Пришёл сам, ниоткуда. Он же — вариант, который уходит в пререндер. */
export const NO_ARRIVAL: Arrival = { join: null, compat: null, next: null, error: null }

export function parseArrival(search: string | URLSearchParams): Arrival {
  const q = typeof search === 'string' ? new URLSearchParams(search) : search
  const join = q.get('join')
  const compat = q.get('compat')
  // Форма join и compat не оставляет места для адреса, поэтому им хватает
  // проверки формы; свободному next нужен белый список, см. safeNext.
  return {
    join: join && /^[A-Za-z0-9]{6}$/.test(join) ? join.toUpperCase() : null,
    compat: compat && /^\d{17}$/.test(compat) ? compat : null,
    next: safeNext(q.get('next')),
    error: q.get('error'),
  }
}

export function safeNext(raw: string | null | undefined): string | null {
  if (typeof raw !== 'string') return null
  if (!raw.length || raw.length > MAX_LEN) return null

  /*
   * Форма адреса. Ловим три разных способа увести человека на чужой хост.
   *
   * '//evil.com' — протокол-относительный адрес: браузер уходит на чужой хост,
   * хотя строка начинается со слэша и «выглядит своей».
   *
   * Бэкслэш — тот же приём в обход наивной проверки на '//': часть браузеров
   * нормализует '/\evil.com' в '//evil.com' уже ПОСЛЕ неё. Отдельной ветки под
   * него здесь нет намеренно — hasForbiddenChar режет бэкслэш в любой позиции,
   * и дублировать проверку значило бы завести второе место, которое надо
   * помнить при правке.
   *
   * Управляющие символы (в первую очередь CR и LF) — расщепление ответа:
   * перевод строки в значении Location дописывает свой заголовок.
   */
  if (raw[0] !== '/') return null
  if (raw.startsWith('//')) return null
  if (hasForbiddenChar(raw)) return null

  // Сравниваем ПУТЬ, а не всю строку: '/play?time=short' обязан пройти, а
  // '/playground' — нет, иначе префикс '/play' открывает всё, что с него
  // начинается.
  const path = raw.split(/[?#]/)[0] ?? ''
  const ok = ALLOWED_PREFIXES.some((p) =>
    p.endsWith('/') ? path.startsWith(p) : path === p || path.startsWith(`${p}/`),
  )
  return ok ? raw : null
}
