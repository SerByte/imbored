import type { GameMeta } from './types'

/**
 * Кубические (воксельные) игры.
 *
 * Нужен для пасхалки на герое /play: по нажатию на арт кубической игры от точки
 * нажатия расходится волна кубов. Смысл эффекта именно в совпадении с конкретной
 * игрой, поэтому детект СТРОГИЙ — точное совпадение тега плюс явный список.
 * Расширять его до Sandbox/Building/Crafting нельзя: тогда кубы получат Factorio
 * и RimWorld, игры про стройку, но совершенно не кубические, и шутка развалится.
 *
 * Живёт на сервере: до клиента доезжают только четыре тега с наибольшим весом,
 * а Voxel попадает в эту четвёрку лишь у каждой шестой воксельной игры.
 * Поэтому /api/recommend считает признак здесь, по полной карте тегов, и
 * отдаёт его булевым флагом.
 */

export const VOXEL_TAG = 'Voxel'

/**
 * Игры, у которых тега Voxel нет, но кубические они безоговорочно.
 * Целостность списка проверяется тестом: каждый appid должен резолвиться
 * в известных наборах, иначе опечатка останется незамеченной навсегда.
 */
export const VOXEL_APPIDS: ReadonlySet<number> = new Set([
  -111, // Minecraft — курируемая не-Steam запись, lib/otherstores.ts
])

export function isVoxelGame(
  meta: Pick<GameMeta, 'appid' | 'tags'> | null | undefined,
): boolean {
  if (!meta) return false
  if (VOXEL_APPIDS.has(meta.appid)) return true
  // Именно проверка ключа, а не поиск без учёта регистра: теги Steam приходят
  // из словаря с фиксированным написанием, и вольность тут только добавила бы
  // ложных срабатываний.
  return VOXEL_TAG in (meta.tags ?? {})
}
