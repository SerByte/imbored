/**
 * Кто становится обложкой ленты.
 *
 * В личной ленте это самое свежее: там твои игры, и вопрос звучит как «что
 * случилось, пока меня не было». В общей всё наоборот — посетителю нужен не
 * самый недавний патч, а самый громкий, иначе на весь экран встаёт обновление
 * игры, о которой он не слышал. На живых данных разница красноречивая: самым
 * свежим крупным патчем оказывается SWTOR с весом 52 654, а самым весомым за ту
 * же неделю — PUBG с 639 330.
 *
 * Свежесть при этом остаётся условием, а не пожеланием: кандидаты ограничены
 * окном, а не всей лентой, — иначе обложка застряла бы на одной и той же игре
 * до следующего её патча.
 *
 * Функция чистая и ничего не знает о базе. Тип структурный, без импорта
 * StoredNews: так этот модуль и его тест не тянут за собой lib/db.ts — а
 * тестами покрыт только lib/, см. vitest.config.mts.
 */

/** Насколько давним может быть патч, чтобы претендовать на обложку */
export const HERO_WINDOW_SEC = 7 * 86_400

export type FeedRankable = { publishedAt: number; rank: number }

/**
 * Делит ленту на обложку и остаток, сохраняя хронологию в остатке.
 *
 * @param items отсортированные по убыванию даты — так отдают getMajorFeed и getFeedForApps
 * @param windowSec 0 — обложкой становится самый свежий элемент, как в личной ленте
 */
export function splitFeed<T extends FeedRankable>(
  items: readonly T[],
  nowSec: number,
  windowSec: number = HERO_WINDOW_SEC,
): { hero?: T; rest: T[] } {
  if (!items.length) return { rest: [] }

  let heroAt = 0
  if (windowSec > 0) {
    const cut = nowSec - windowSec
    for (let i = 1; i < items.length; i++) {
      if (items[i].publishedAt < cut) continue
      // Первый кандидат мог сам не попасть в окно — тогда его вытесняет любой,
      // кто в окно попал. Дальше сравниваем строго по весу, и равный вес
      // оставляет предыдущего: список отсортирован по дате, значит он свежее.
      if (items[heroAt].publishedAt < cut || items[i].rank > items[heroAt].rank) heroAt = i
    }
  }

  return { hero: items[heroAt], rest: items.filter((_, i) => i !== heroAt) }
}
