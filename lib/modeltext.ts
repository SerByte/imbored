/**
 * Годится ли текст модели на публичную страницу — проверка после модели, но не
 * про рекламу (её ловит MODEL_SPAM в lib/llm), а про сам русский.
 *
 * «За что любят / За что ругают» на карточке игры и пересказы патчей пишет
 * дешёвая модель, и на проде из семнадцати проверенных карточек битый текст
 * стоял на семи: обломок JSON «…справедливо'],» на /game/317400,
 * «Глубокая и увлекательная геймплей механика» в сниппете CS2,
 * «в каждой матч», «Отличный модификация Quake», «Сложный реалистичный
 * выживание», «космetics-предметами» в пересказе патча. Эти панели — главный
 * ответ страницы на «стоит ли играть», а первый плюс уезжает ещё и в meta
 * description, og-карточку и плитку хаба жанра. Битый текст там читается как
 * машинный мусор, то есть ровно как то, чем сайт быть не хочет.
 *
 * Промпт просит грамотный русский, но просьба — не гарантия. Поэтому здесь —
 * то, что ловится кодом без морфологического словаря и без второй модели:
 *   — обломки JSON и экранирования (debris);
 *   — слово из двух алфавитов (mixed);
 *   — явное несогласование рода у частых слов отзывов и «не», приклеенное к
 *     глаголу (grammar).
 * Чего здесь нет и не будет: падежей вообще, кальки («Террифично страшная»),
 * выдуманных слов («портретизация»). Их ловит только промпт или модель
 * сильнее — правило, которое пыталось бы, бракует и честный текст.
 *
 * Точность важнее охвата: ложное срабатывание выбрасывает честный плюс. На
 * выгрузке прода от 24 сентября (10 493 пункта pros/cons и 2 381 пересказ)
 * проверка забраковала 50 пунктов и 15 пересказов, и все — по делу:
 * «Глубокая геймплей», «Каждый прохождение», «хорошим пacing»,
 * «видеосettings». Плюсов целиком не лишилась ни одна из 1 267 игр.
 *
 * Зовут это и до записи (lib/llm: cleanProsCons, validateDigest), и при
 * чтении (lib/gamepage, getLovedFor в lib/db): уже лежащие в базе битые
 * пункты прячутся сразу, а не через полгода, когда карточку пересоберут.
 * Поэтому модуль чистый и без импортов — читающим незачем тянуть SDK модели.
 */

export type ModelTextFlaw = 'debris' | 'mixed' | 'grammar'

/** Что в тексте не так, или null — публиковать можно. */
export function modelTextFlaw(text: string): ModelTextFlaw | null {
  if (hasDebris(text)) return 'debris'
  if (MIXED_WORD.test(text)) return 'mixed'
  if (GLUED_NE.test(text) || hasAgreementError(text)) return 'grammar'
  return null
}

/* ---------------- обломки JSON ---------------- */

/** Фигурные скобки в русской фразе из двенадцати слов не нужны никогда */
const BRACES = /[{}]/
/** Кавычка вплотную к квадратной скобке — граница элемента массива: «справедливо'],» */
const QUOTE_AT_BRACKET = /["'][[\]]|[[\]]["']/
/** Экранирование из сырого JSON: «\n», «\"», «\uXXXX» */
const ESCAPE = /\\(?:[nrt"'\\/]|u[0-9a-fA-F]{4})/
/**
 * Фраза, оборванная на запятой или двоеточии: модель начала следующий элемент
 * и не закончила этот. Точку с запятой в конце не судим — это огрех стиля, а
 * не обломок, и пункт за неё выбрасывать жалко.
 */
const UNFINISHED = /[,:]\s*$/
function count(text: string, re: RegExp): number {
  return text.match(re)?.length ?? 0
}

const WORD_CHAR = /[\p{L}\d]/u
const CYRILLIC = /[а-яё]/i

/**
 * Непарная апостроф-кавычка у русского слова: «справедливо'» — обломок
 * строки из ответа модели.
 *
 * Кавычка открывает, если слово справа, и закрывает, если слово слева;
 * между двумя буквами апостроф — часть слова («Д'Артаньян», «90's»). Пары
 * ищутся по порядку, как скобки, а не счётом: имя в кавычках бывает с цифрой
 * или латиницей на краю — «'Хэллоуин 2024'», «'PvP арена'», — и счёт только
 * кириллических краёв видел у такой пары одну кавычку. Обломком считается
 * только оставшаяся без пары кавычка у кириллицы: у латиницы непарный
 * апостроф — честная часть английского имени («Tam o' Shanter», «Sic 'Em»,
 * «X-Men '97» в пересказах патчей).
 */
function hasOrphanRuApostrophe(text: string): boolean {
  /** Что стоит внутри у каждой ещё не закрытой кавычки */
  const open: string[] = []
  for (const m of text.matchAll(/'/g)) {
    const before = text[m.index - 1] ?? ''
    const after = text[m.index + 1] ?? ''
    const wordBefore = WORD_CHAR.test(before)
    if (wordBefore === WORD_CHAR.test(after)) continue
    if (!wordBefore) open.push(after)
    else if (open.length) open.pop()
    else if (CYRILLIC.test(before)) return true
  }
  return open.some((c) => CYRILLIC.test(c))
}

/**
 * Обломок структуры ответа в тексте пункта.
 *
 * Не обрезка хвоста, а отказ целиком: пункт с обломком и сам оборван на
 * полумысли («…, справедливо»), чинить там нечего. Парные кавычки
 * («Режим "Королевская битва"») и квадратные скобки по делу («вылет [DX12]» в
 * пересказе патча) проходят: обломком считается только непарное или кавычка
 * вплотную к скобке.
 */
function hasDebris(text: string): boolean {
  return (
    BRACES.test(text) ||
    QUOTE_AT_BRACKET.test(text) ||
    ESCAPE.test(text) ||
    UNFINISHED.test(text) ||
    count(text, /\[/g) !== count(text, /]/g) ||
    count(text, /"/g) % 2 === 1 ||
    hasOrphanRuApostrophe(text)
  )
}

/* ---------------- смесь алфавитов ---------------- */

/**
 * Кириллица и латиница вплотную, внутри одного слова: «космetics»,
 * латинская «o» в «Атмoсфера». Русских слов, написанных так, не бывает, а
 * латинская буква-двойник внутри русского слова — ещё и приём, которым
 * прячут слово от фильтров. Через дефис — можно: «PvE-игра», «3D-графика».
 */
const MIXED_WORD = /[а-яёА-ЯЁ][a-zA-Z]|[a-zA-Z][а-яёА-ЯЁ]/

/* ---------------- битый русский ---------------- */

/**
 * «Не», приклеенное к глаголу: «неработает». Список закрытый и короткий:
 * общее правило «не + глагол» бракует настоящие слова («ненавидит»,
 * «недооценивает»), а здесь — только те, что модель пишет слитно, пересказывая
 * отзывы про вылеты и античит. Причастие («неработающий») пишется слитно
 * правильно и сюда не попадает: окончание другое.
 */
const GLUED_NE =
  /(?<![а-яё])не(?:работа(?:ет|ют|л[аио]?)|запуска(?:ет|ют)ся|загружа(?:ет|ют)ся|грузит(?:ся)?|отвеча(?:ет|ют)|обновля(?:ет|ют)(?:ся)?)(?![а-яё])/i

type Gender = 'm' | 'f' | 'n'

/**
 * Частые существительные отзывов и патчноутов с их родом — в именительном
 * падеже единственного числа (ё записана как е). Только те, у которых эта
 * форма не совпадает с другой частью речи. Нет «онлайн», «хоррор», «шутер»:
 * их ставят перед существительным как несклоняемое определение («онлайн
 * составляющая», «хоррор игра»), и правило ниже приняло бы это за ошибку рода.
 */
const NOUNS: Readonly<Record<string, Gender>> = {
  геймплей: 'm', матч: 'm', сюжет: 'm', мир: 'm', режим: 'm', контент: 'm',
  баланс: 'm', саундтрек: 'm', звук: 'm', дизайн: 'm', интерфейс: 'm',
  мультиплеер: 'm', кооператив: 'm', античит: 'm', донат: 'm', гринд: 'm',
  сеттинг: 'm', лор: 'm', стиль: 'm', визуал: 'm', движок: 'm', прогресс: 'm',
  крафт: 'm', выбор: 'm', юмор: 'm', опыт: 'm', персонаж: 'm', босс: 'm',
  уровень: 'm', сервер: 'm', лут: 'm', финал: 'm', мод: 'm', бой: 'm',
  сезон: 'm', патч: 'm', пинг: 'm',
  игра: 'f', механика: 'f', графика: 'f', атмосфера: 'f', история: 'f',
  система: 'f', музыка: 'f', боевка: 'f', стрельба: 'f', физика: 'f',
  кампания: 'f', карта: 'f', озвучка: 'f', концовка: 'f', экономика: 'f',
  прокачка: 'f', часть: 'f', серия: 'f', версия: 'f', стратегия: 'f',
  головоломка: 'f', команда: 'f', рисовка: 'f', стилистика: 'f', свобода: 'f',
  глубина: 'f', награда: 'f',
  оружие: 'n', время: 'n', разнообразие: 'n',
}

function nounGender(word: string): Gender | null {
  const w = word.replace(/ё/g, 'е')
  const known = NOUNS[w]
  if (known) return known
  // Суффиксы с одним родом: «модификация», «сложность» — женский;
  // «выживание», «развитие», «взаимодействие», «качество» — средний.
  // «-ание/-ение/-яние», а не любое «-ние»: «последние», «ранние» — прилагательные
  if (/ция$/.test(w) || (/ость$/.test(w) && w !== 'гость')) return 'f'
  if (/(?:[аея]ние|тие|вие|ство)$/.test(w)) return 'n'
  return null
}

/**
 * «Каждой», «этой», «одной» — только косвенные падежи женского рода. Перед
 * существительным в именительном они ошибка всегда: «в каждой матч».
 * («Какой», «любой», «большой» сюда не идут: это и мужской именительный.)
 */
const OBLIQUE_F = new Set(['каждой', 'этой', 'той', 'одной', 'всей', 'своей', 'нашей', 'вашей', 'моей', 'твоей'])

/**
 * Слова с окончанием прилагательного, которые прилагательными не работают:
 * «который» (мир, который игра строит…), средний род в роли существительного
 * («остальное игра делает отлично»), деепричастия «зная» и «таская».
 */
const NOT_ADJECTIVE = new Set(['многое', 'другое', 'иное', 'остальное', 'главное', 'основное', 'единственное', 'зная', 'таская'])

/** Женский род, которому деепричастие не тёзка — см. adjectiveGender */
const FEMININE_WORDS = new Set([
  'великая', 'дикая', 'живая', 'боевая', 'ролевая', 'ключевая', 'старая',
  'быстрая', 'добрая', 'свежая', 'чужая', 'горячая', 'плохая', 'тихая',
])

/**
 * Женский род по окончанию — только там, где деепричастие так не кончается.
 *
 * Деепричастие на -ая — это глагол на -ать: «изучая мир», «делая выбор»,
 * «включая сюжет», «запуская режим», «начиная», «убивая». Перед ним стоит
 * существительное в винительном, а у мужского и среднего рода он совпадает с
 * именительным — и правило «женское прилагательное перед мужским
 * существительным» браковало бы честную фразу. Поэтому окончания взяты те,
 * которых у деепричастий нет: -ская (кроме -уская, -аская), -цкая, согласная
 * + -кая, -окая/-ёкая, согласная + -ная (кроме «зная»), -овая, -сивая,
 * -ющая/-ящая/-ущая, -ьшая/-чшая/-дшая/-сшая/-ошая. Остальное — списком
 * (FEMININE_WORDS). Пропустить «красную» ошибку дешевле, чем выбросить
 * правильный плюс.
 *
 * У -ьшая/-чшая/-дшая деепричастия всё же есть — от глаголов, сделанных из
 * сравнительной степени: «улучшая геймплей», «уменьшая пинг», «ухудшая
 * баланс». В патчноутах это одно из самых частых слов, поэтому они вынуты
 * отдельно (COMPARATIVE_GERUND), а «лучшая», «худшая», «меньшая» остаются.
 */
const FEMININE_ENDING =
  /(?:[^уа]ск|цк|[бвгджзйлмнпртфхчшщ]к|[оё]к|[бвгджзйклмнпрстфхцчшщь]н|ов|сив|[юяу]щ|[ьчдсо]ш)ая$/

/** «улучшая», «ухудшая», «уменьшая», «преуменьшая» — деепричастия, см. выше */
const COMPARATIVE_GERUND = /(?:улучш|ухудш|уменьш)ая$/

/**
 * Мужской род: -ый и -ий после к, ж, ш, ч, щ, а -ний — только после
 * согласной («последний», «ранний»). «-ений», «-аний» — это родительный
 * множественного («без обновлений игра надоедает»), не прилагательное.
 * -ой не берём вовсе: «крутой» — мужской именительный, а «каждой» — женский
 * косвенный, и без словаря их не различить.
 *
 * -гий и -хий — тоже родительный множественного, и частый: «любителям
 * стратегий игра понравится», «лучшая из трилогий серия», «магия стихий».
 * Прилагательных на них так мало, что они перечислены целиком («долгий»,
 * «строгий», «убогий», «пологий», «тихий», «лихий», «ветхий») и узнаются
 * только целым словом: «стихий» кончается на «тихий».
 */
const MASCULINE_ENDING =
  /(?:ый|[кжшчщ]ий|[бвгджзйклмнпрстфхцчшщ]ний)$|^(?:не|пре)?(?:долг|строг|убог|полог|отлог|тих|лих|ветх)ий$/

function adjectiveGender(word: string): Gender | 'oblique' | null {
  if (NOT_ADJECTIVE.has(word) || word.startsWith('котор')) return null
  if (OBLIQUE_F.has(word)) return 'oblique'
  if (MASCULINE_ENDING.test(word)) return 'm'
  if (COMPARATIVE_GERUND.test(word)) return null
  if (FEMININE_WORDS.has(word) || FEMININE_ENDING.test(word)) return 'f'
  if (/ое$/.test(word)) return 'n'
  return null
}

/**
 * Действительное причастие: «вызывающий», «затягивающая», «игравший». В
 * отличие от прилагательного оно берёт дополнение — «вызывающий зависимость»,
 * «создающий погружение», «не портящая опыт», — а винительный у мужского и
 * среднего рода и у женского на -ь совпадает с именительным. Такую пару по
 * роду не судим: на текстах из прода это были сплошь честные фразы.
 */
const ACTIVE_PARTICIPLE = /(?:[юяау]щ|вш)(?:ий|ая|ее)$/

/**
 * Винительный совпадает с именительным: неодушевлённый мужской род, средний,
 * женский на -ь. После причастия такое существительное может быть его
 * дополнением, а не определяемым словом.
 */
function accusativeLikeNominative(noun: string, gender: Gender): boolean {
  if (gender === 'f') return noun.endsWith('ь')
  return !(noun === 'персонаж' || noun === 'босс')
}

/**
 * Прилагательное и стоящее вплотную за ним существительное разного рода:
 * «увлекательная геймплей», «отличный модификация», «реалистичный
 * выживание», «в каждой матч», «разочаровывающий концовка».
 *
 * Только соседние слова через пробел: запятая, тире или кавычка между ними —
 * уже другая часть фразы («Главное — атмосфера», «Красивая, но короткая
 * игра»). Прилагательное через дефис («научно-фантастический») судится по
 * последней части.
 *
 * Цена осторожности с причастиями — пропуск: «затягивающая геймплей» по
 * форме неотличима от «механика, дополняющая геймплей», и здесь не ловится.
 * Это работа промпта.
 */
function hasAgreementError(text: string): boolean {
  const words = text.toLowerCase().split(/\s+/)
  for (let i = 0; i + 1 < words.length; i++) {
    const adjective = words[i]
    if (!/^[а-яё]+(?:-[а-яё]+)*$/.test(adjective)) continue
    const noun = words[i + 1].replace(/[.,;:!?…)»"']+$/, '')
    if (!/^[а-яё]+$/.test(noun)) continue
    const nounG = nounGender(noun)
    if (!nounG) continue
    const last = adjective.slice(adjective.lastIndexOf('-') + 1)
    const adjG = adjectiveGender(last)
    if (!adjG || adjG === nounG) continue
    if (ACTIVE_PARTICIPLE.test(last) && accusativeLikeNominative(noun.replace(/ё/g, 'е'), nounG)) continue
    return true
  }
  return false
}

/* ---------------- утверждения, которые проверяются фактами ---------------- */

/**
 * Минус утверждает, что игру не обновляют или бросили.
 *
 * На CS2 модель поставила «Разработчики не обновляют игру и забросили её
 * развитие» рядом с восемью патчами за три недели в «Что нового» на той же
 * странице. Отзывы такое пишут в сердцах, но страница, которая ниже сама
 * перечисляет свежие обновления, с собой спорить не должна. Проверку фактом
 * делает читающий (lib/gamepage), здесь — только узнавание утверждения.
 *
 * «Заброшен» — только про игру или разработчиков: «заброшенные локации» —
 * про карту, а не про поддержку. «Забросили» — только с тем, что бросают
 * разработчики: «сюжет забросили на полпути» — о другом.
 *
 * Поддержка и разработка — только самой игры: дальше либо «игры»/«проекта»,
 * либо конец фразы. «Прекратили поддержку macOS и Linux» и «Windows 7» —
 * честный минус про платформы, и свежий патч ему не противоречит.
 *
 * «Не обновляется» — только когда игра или её авторы стоят при глаголе: до
 * него, через слово-другое («Игра давно не обновлялась», «Разработчики не
 * обновляют»), или после («никогда не обновлялась издателем», «не обновляют
 * игру»). Запятая эту связь рвёт — кроме случая, когда фраза начинается с
 * игры, а следующая часть — с самого глагола, без своего подлежащего: «Игра
 * устарела, не обновляется с 2023 года» (выгрузка прода), но не «Игра
 * хорошая, карты не обновляются». Раньше хватало «игр» где угодно во фразе, и
 * «Карты не обновляются, игрокам скучно» или «Античит не обновляется, читеры
 * в каждой игре» пропадали с CS2 — с той самой страницы, ради которой правило
 * писалось. Формы — закрытым списком, а не корнем: «игры» перед глаголом —
 * это обычно родительный («Карты игры не обновляются» — про карты), а
 * «авторский контент» — не авторы. «Кампания не обновляется вместе с
 * мультиплеером» (Company of Heroes 3) и «графика не обновлялась много лет»
 * свежим патчам не противоречат тоже: они уточняют, что в патчи не попадает.
 */
/** Слово того же предложения: без пробелов и знаков, которые рвут фразу */
const NEAR = String.raw`[^\s,.;:!?…—–()]+\s+`
/** Кто или что не обновляется — перед глаголом */
const GAME_BEFORE = String.raw`(?<![а-яё])(?:игр[ау]|проект|разработчики?|издател[ьи]|авторы?)(?![а-яё])`
/** Что не обновляют или кем — после глагола */
const GAME_AFTER = String.raw`(?<![а-яё])(?:игру|проект|разработчик(?:ом|ами)|издател(?:ем|ями)|автор(?:ом|ами))(?![а-яё])`
/**
 * Что может стоять между запятой и «не обновляется», не будучи подлежащим.
 * Список, а не «любое слово»: в «Игра хорошая, карты не обновляются» слово
 * после запятой — уже другое подлежащее.
 */
const BEFORE_VERB = String.raw`(?:(?:но|и|а)\s+)?(?:(?:давно|никогда|уже|совсем|больше|почти|толком|вообще|практически|годами)\s+){0,2}`
/** За поддержкой или разработкой — сама игра или конец фразы, а не платформа */
const OF_GAME = String.raw`(?:\s+(?:этой\s+|этого\s+)?(?:игры|проекта)(?![а-яё])|(?=\s*(?:[,.;:!?…—–)]|$)|\s+(?:и|а|но)\s))`
const NO_UPDATES = new RegExp(
  [
    String.raw`(?:нет|без)\s+(?:новых\s+|свежих\s+)?обновлений`,
    String.raw`обновлени[йя]\s+(?:нет|не\s+(?:выходят|выходит|было|будет))`,
    String.raw`забросил[аи]?\s+(?:её\s+|ее\s+|эту\s+)?(?:игру|проект)`,
    String.raw`забросил[аи]?\s+(?:её|ее)\s+(?:развитие|разработку|поддержку)`,
    String.raw`забросил[аи]?\s+(?:развитие|разработку|поддержку)${OF_GAME}`,
    String.raw`(?:игр[аеуы]|проект)\s+заброшен`,
    String.raw`заброшен[аоы]?\s+разработчик`,
    String.raw`прекратил[аи]?\s+(?:её\s+|ее\s+)(?:поддержку|разработку)`,
    String.raw`прекратил[аи]?\s+(?:поддержку|разработку)${OF_GAME}`,
    String.raw`поддержк[аи]\s+(?:игры\s+)?прекращен`,
    String.raw`разработка\s+(?:заморожена|остановлена|прекращена)`,
    String.raw`${GAME_BEFORE}\s+(?:${NEAR}){0,3}не\s+обновля`,
    String.raw`^\s*(?:[а-яё]+\s+)?${GAME_BEFORE}[^.;:!?,]*,\s*${BEFORE_VERB}не\s+обновля`,
    String.raw`не\s+обновля[а-яё]*\s+(?:${NEAR}){0,2}${GAME_AFTER}`,
  ].join('|'),
  'i',
)

/*
 * То же утверждение по-английски — для слота en (pros_en/cons_en): /en
 * показывает те же минусы своими словами, и «Developers don't update the
 * game» над восемью свежими патчами спорит со страницей так же, как русский.
 * Язык выбирает сам текст: русские правила латиницу не узнают, английские —
 * кириллицу, поэтому одна функция служит обоим слотам.
 *
 * Те же замки, что у русских правил, но со своей грамматикой. В английском
 * определение стоит ДО слова: «Map updates have stopped», «Controller support
 * was dropped», «Mod development has stopped» — про карты, геймпад и моды,
 * и «updates»/«support»/«development» узнаются только в начале предложения
 * или после служебного слова (CLAUSE_EN). Игра после глагола — только сама,
 * а не определением к другому слову: «don't update the game's maps» и «the
 * game modes» — не про игру (GAME_END_EN). «Dead game» в список не входит:
 * это про пустой онлайн, а свежий патч ему не противоречит.
 */
/** Начало предложения или служебное слово перед «updates», «support», «development» */
const CLAUSE_EN = String.raw`(?:^\s*|[,.;:!?…—–(]\s*|\b(?:and|but|so|the|its|their|all|any|further|active|official)\s+)`
/** «isn't», «hasn't», «no longer», «stopped» — отрицание при «update» */
const NEG_EN = String.raw`\b(?:(?:is|are|was|were|has|have|had|does|do|did|wo)(?:n['’]t|\s+not)|will\s+not|not|never|no\s+longer|stopped|quit)`
const NOT_UPDATED_EN = String.raw`${NEG_EN}\s+(?:(?:been|being|getting|get|gets|got|really|ever|even|received|receiving|seen|had|any|an|bothered\s+to|bother\s+to)\s+){0,2}updat(?:e|es|ed|ing)\b`
/** Кто не обновляет — перед глаголом (зеркало GAME_BEFORE) */
const WHO_EN = String.raw`\b(?:(?:the|its|their)\s+)?(?:game|project|developers?|devs?|publishers?|authors?|studio)\b`
/** Что может стоять между подлежащим и отрицанием, не будучи другим подлежащим */
const ADV_EN = String.raw`(?:(?:has|have|had|is|are|was|were|basically|clearly|apparently|seemingly|just|simply|completely|totally|long\s+since|seems?\s+to)\s+){0,2}`
/** Игра дополнением — сама, а не определение к следующему слову */
const GAME_END_EN = String.raw`(?:game|project)(?=\s*(?:[,.;:!?…—–)]|$)|\s+(?:and|but|or|anymore|any\s+more|at\s+all|in|for|since|after|ever|much|often|regularly|now|lately|properly|either)\b)`
/** За поддержкой или разработкой — сама игра, «it» в конце или конец фразы (зеркало OF_GAME) */
const OF_GAME_EN = String.raw`(?:\s+(?:(?:of|for|on)\s+)?(?:(?:the|this)\s+)?${GAME_END_EN}|\s+it(?=\s*(?:[,.;:!?…—–)]|$))|(?=\s*(?:[,.;:!?…—–)]|$)|\s+(?:and|but)\s))`
/** «…by the developers» — кем не обновляется или брошена (зеркало GAME_AFTER) */
const BY_WHO_EN = String.raw`\s+by\s+(?:(?:the|its)\s+)?(?:devs?|developers?|publishers?|authors?|studio)\b`
const NO_UPDATES_EN = new RegExp(
  [
    String.raw`\b(?:no|without(?:\s+any)?|zero|lack\s+of)\s+(?:(?:new|fresh|recent|any)\s+)?updates?\b`,
    String.raw`${CLAUSE_EN}updates?\s+(?:(?:have|has)\s+)?(?:stopped|ceased|dried\s+up|(?:no\s+longer|never|don['’]t|do\s+not|aren['’]t|are\s+not|won['’]t|will\s+not)\s+(?:come|coming|released|being\s+released|come\s+out|coming\s+out))\b`,
    String.raw`\babandoned\s+(?:(?:the|this|their|its)\s+)?${GAME_END_EN}`,
    String.raw`\babandoned\s+(?:(?:the|its|their)\s+)?(?:development|support)${OF_GAME_EN}`,
    String.raw`\b(?:game|project)\s+(?:(?:is|was|has\s+been|have\s+been|feels|seems|looks|got|basically|essentially|completely|totally|pretty\s+much|kind\s+of|now|clearly|effectively)\s+){0,3}abandoned\b`,
    String.raw`\babandoned${BY_WHO_EN}`,
    String.raw`\b(?:stopped|ended|dropped|discontinued|halted|ceased|quit)\s+(?:(?:the|its|their)\s+)?(?:support(?:ing)?|develop(?:ment|ing))${OF_GAME_EN}`,
    String.raw`${CLAUSE_EN}support\s+(?:(?:for|of)\s+(?:(?:the|this)\s+)?(?:game|project)\s+)?(?:(?:has|have|was|is)\s+)?(?:been\s+)?(?:ended|stopped|dropped|discontinued|ceased|halted|over)\b`,
    String.raw`${CLAUSE_EN}development\s+(?:(?:has|have|was|is|seems\s+to\s+have|appears\s+to\s+have)\s+)?(?:been\s+)?(?:stopped|ended|halted|frozen|discontinued|ceased|abandoned|stalled)\b`,
    String.raw`${WHO_EN}\s+${ADV_EN}${NOT_UPDATED_EN}`,
    String.raw`^\s*(?:[a-z]+\s+)?(?:(?:the|this)\s+)?(?:game|project)\b[^.;:!?,]*,\s*(?:(?:but|and)\s+)?(?:(?:it|it['’]s)\s+)?${ADV_EN}${NOT_UPDATED_EN}`,
    String.raw`${NOT_UPDATED_EN}\s+(?:(?:the|this|their|its)\s+)?${GAME_END_EN}`,
    String.raw`${NOT_UPDATED_EN}${BY_WHO_EN}`,
    String.raw`\b(?:nobody|no\s+one)\s+(?:(?:is|has|ever|really)\s+)?updat(?:e|es|ed|ing)\s+(?:(?:the|this)\s+)?${GAME_END_EN}`,
  ].join('|'),
  'i',
)

/** Минус утверждает, что игру не обновляют или бросили, — на любом из двух языков слота */
export function claimsNoUpdates(text: string): boolean {
  return NO_UPDATES.test(text) || NO_UPDATES_EN.test(text)
}

/* ---------------- пункты как предложения ---------------- */

/** Пункт из pros/cons как предложение: без своей точки в конце, одной строкой */
export function point(text: string): string {
  return text.replace(/\s+/g, ' ').trim().replace(/[.,;:!?…]+$/, '')
}

/**
 * Несколько пунктов одной строкой — каждый своим предложением.
 *
 * Хаб жанра склеивал их через «; », и вторая половина начиналась с
 * заглавной: «…повторяемость; Богатая история». Строчной её не сделать
 * вслепую — пункт может начинаться с «PvP», «FPS» или имени. Предложение с
 * точкой оставляет каждому пункту его регистр и читается правильно.
 */
export function pointsLine(items: readonly string[]): string {
  return items.map((t) => `${point(t)}.`).join(' ')
}
