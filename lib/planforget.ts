/**
 * Забыть игру из отложенных на вечер в выдаче /play на устройстве
 * (lib/playcache, planned), когда её план закрыт не на /play.
 *
 * Отложенного в этом заходе героя «Не то — дальше» листает без вопроса о
 * причине: пропуск закрыл бы план, который человек только что поставил
 * (app/play, planned). Но план закрывают и в других местах: запуск со
 * страницы игры (components/OwnedLaunch, бит plan), из «Твоих вечеров»
 * (components/Evenings) и с «Игры дня» — запуск или «Не сегодня»
 * (app/daily). «Поставь на загрузку» → ⓘ «Подробнее» → «Запустить» →
 * «Назад» возвращал героя отложенным, хотя план на сервере уже закрыт:
 * «Не то — дальше» молча листал, и ответ про игру, которую на деле
 * запустили, терялся — а «не зацепило?» (StopAsk) про запуск со страницы
 * игры не спросит: его там не засекают. И «Сыграю вечером» у такого героя
 * вставала уже нажатой, обещая план, которого нет.
 *
 * ОТДЕЛЬНО ОТ lib/playcache — ради веса, как и выход (lib/playforget):
 * страница игры, /library и /daily не везут разбор выдачи ради одного
 * вызова. Запись правится по ключу, мимо модуля выдачи, — а /play читает её
 * при монтировании из хранилища, а не из памяти вкладки (fresh в run): там
 * модуль, загруженный до ухода на страницу игры, держал бы прежнюю копию.
 * Разбирать запись целиком незачем: правятся список и строка плана, а
 * запись, которую не узнал бы и /play, остаётся как есть.
 *
 * Только эта вкладка: запись выдачи — в sessionStorage, у соседних вкладок
 * своя. План, закрытый в соседней, здесь так и останется отложенным, пока
 * вкладка помнит выдачу. И хранилище, которое не пишется (приватный режим),
 * не исправить: выдачу тогда помнит только память вкладки — до перезагрузки.
 */

/**
 * Ключ записи выдачи /play — один на lib/playcache, выход (lib/playforget) и
 * правку здесь. Живёт здесь, а не в lib/playforget: тот везёт за собой
 * прогрев, а этот модуль грузят страница игры и «Игра дня».
 */
export const PLAY_DEAL_KEY = 'imbored.play.deal'

/**
 * План игры закрыт не на /play: выдача на устройстве больше не держит её
 * отложенной. И строку плана над «Продолжить» (deal.plan) с ней не вернёт —
 * так же её убирает и сам /play, едва закрытие записано (closesPlan): иначе
 * «Ставил «X» на загрузку · Запустить» звал бы в план, которого уже нет.
 * Не бросает.
 */
export function forgetPlanned(appid: number): void {
  try {
    const raw = sessionStorage.getItem(PLAY_DEAL_KEY)
    const rec: unknown = raw === null ? null : JSON.parse(raw)
    if (!rec || typeof rec !== 'object') return
    const { planned, deal } = rec as { planned?: unknown; deal?: { plan?: { appid?: unknown } | null } | null }
    const listed = Array.isArray(planned) && planned.includes(appid)
    const row = deal?.plan?.appid === appid
    // Игры в записи нет — писать нечего: лишняя запись будила бы хранилище
    // ради той же строки
    if (!listed && !row) return
    sessionStorage.setItem(
      PLAY_DEAL_KEY,
      JSON.stringify({
        ...rec,
        ...(listed ? { planned: planned.filter((a) => a !== appid) } : {}),
        ...(row ? { deal: { ...deal, plan: null } } : {}),
      }),
    )
  } catch {
    // приватный режим, битая запись — забывать нечего: такую и /play не узнает
  }
}
