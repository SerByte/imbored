/**
 * РЕШЕНИЕ ОПРОСА КОМНАТЫ: ОСТАНОВИТЬСЯ, ПОДОЖДАТЬ ИЛИ ПРОДОЛЖИТЬ.
 *
 * Вынесено из эффекта в чистую функцию не ради чистоты. Пока решение жило
 * условиями внутри цикла, в нём была ошибка, которую не видел никто:
 *
 *     const next = await refresh()
 *     if (!next) { stopped = true; return }   // комментарий говорил «404»
 *
 * `refresh` возвращал `null` и на 404, и на ЛЮБОЙ другой отказ. Одной
 * пятисотки хватало, чтобы опрос замолчал навсегда.
 *
 * Замерено на живой комнате: три опроса за девять секунд, затем один ответ
 * 500 — и НОЛЬ запросов за следующие шестнадцать секунд. Комната застывала на
 * последнем снимке: ростер, голоса, колода — всё на месте и всё враньё.
 * На экране ни единого признака. Если же 500 приходил на первый запрос,
 * страница оставалась спиннером навсегда.
 *
 * Обрыв сети, для сравнения, всегда работал правильно: он приходит
 * исключением и попадает в catch. Замерено: шесть запросов за те же
 * шестнадцать секунд. То есть неверна была именно ветка ответа, а не ветка
 * сети — и различить их на глаз, читая эффект, практически невозможно.
 */

/** Со скольких отказов подряд признаём связь потерянной. */
export const STALE_AFTER_FAILS = 2

export type PollAnswer =
  /** Ответ пришёл. status — состояние комнаты из тела. */
  | { ok: true; status: string }
  /** Ответа нет. gone — комнаты не существует (404), это терминально. */
  | { ok: false; gone: boolean }

export type PollStep = {
  /** Опрос прекращается навсегда. Только для терминальных исходов. */
  stop: boolean
  /** Отказов подряд после этого шага. */
  fails: number
  /** Показывать ли, что комната на экране устарела. */
  stale: boolean
  /** Следующий тик — замедленный: сервер и так не справляется. */
  slow: boolean
}

/**
 * Терминальных исходов ровно два, и оба означают, что дальше меняться нечему:
 * комнаты не существует и церемония матча состоялась. Всё остальное —
 * временное, каким бы кодом оно ни пришло.
 */
export function nextPollStep(answer: PollAnswer, fails: number): PollStep {
  if (!answer.ok) {
    if (answer.gone) return { stop: true, fails, stale: false, slow: false }
    const next = fails + 1
    return { stop: false, fails: next, stale: next >= STALE_AFTER_FAILS, slow: true }
  }
  if (answer.status === 'matched') return { stop: true, fails: 0, stale: false, slow: false }
  return { stop: false, fails: 0, stale: false, slow: false }
}

/**
 * ЧЕЙ СНИМОК КОМНАТЫ НА ЭКРАНЕ: ПРИШЕДШИЙ ИЛИ УЖЕ ПОКАЗАННЫЙ.
 *
 * Защита опроса от наложения (inFlight) накрывает только его собственные
 * запросы. refresh зовут и мимо него — «Ещё 20 игр», вход, голос, «Берём»,
 * ✕ хоста, переключатель доски, — и такие запросы ничем не упорядочены:
 * ставился ответ, пришедший последним, даже если прочитан он раньше. На
 * холодной базе это и есть обычное дело — счётчики ростера ехали назад.
 *
 * Хуже с матчем. Опрос, увидев 'matched', останавливается навсегда. Снимок
 * «open», прочитанный ДО матча (хост нажал «На доску», пока последний голос
 * друга сводил матч) и пришедший ПОСЛЕ, возвращал хоста в ожидание — и
 * заменить его было уже некому: опрос стоит, отказов нет, плашки нет.
 *
 * Правило:
 *   • матч терминален (setRoomMatched переводит только open → matched), и
 *     никакой снимок без матча его не сменит, с каким бы номером ни пришёл;
 *   • снимок с матчем встаёт всегда, даже со старым номером: иначе запоздалый
 *     «open» с номером новее оставил бы открытую комнату при опросе, который
 *     только что остановился на матче, — та же заморозка;
 *   • прочий снимок старше показанного — 'keep': на экране остаётся новее.
 *
 * seq — номер запроса, взятый ДО fetch: порядок чтения на сервере, а не
 * порядок прихода ответов.
 */
export function snapshotFate(args: {
  seq: number
  status: string
  /** снимок на экране; null — ещё ничего не показано */
  shown: { seq: number; status: string } | null
}): 'apply' | 'keep' {
  const { seq, status, shown } = args
  if (!shown) return 'apply'
  if (shown.status === 'matched') return status === 'matched' ? 'apply' : 'keep'
  if (status === 'matched') return 'apply'
  return seq < shown.seq ? 'keep' : 'apply'
}

/** Шаг опроса скрытой вкладки: не чаще раза в минуту. */
export const HIDDEN_POLL_MS = 60_000
/** Потолок скрытия, после которого вкладка засыпает до возвращения. */
export const HIDDEN_POLL_CAP_MS = 60 * 60_000

/**
 * Опрос скрытой вкладки: через сколько после прошлого запроса спросить
 * сервер, или null — не спрашивать и спать до возвращения на вкладку (её
 * будит onVisibility).
 *
 * Скрытая вкладка раньше не спрашивала никогда, и решение было верным:
 * вкладка, забытая на ночь, стоила бы миллионов прочитанных строк и не
 * показала бы никому ни одной. Исключение одно — человек отсвайпал своё, а
 * комната ещё может сойтись без него (waiting здесь — waitsInBackground в
 * lib/room). Только тогда из фона есть что узнать (матч) и есть кому об этом
 * сказать (заголовок вкладки, уведомление). Свайпающему фон ничего не принесёт:
 * без его голосов единогласия не будет, а «Берём» предлагается, только когда
 * отсвайпали все. В комнате на одного и при пустой колоде — тоже.
 *
 * Раз в минуту, а не 2.5 секунды: новость о матче терпит минуту, а сервер
 * получает 60 GET в час вместо полутора тысяч. Ровно 60: кроме самого опроса
 * скрытая вкладка ничего не догружает — ни лайки с почти-совпадениями, ни
 * колоду нового раунда или состава, ни её самолечение (эффекты лайков и колоды
 * в app/room/[id]/page ждут возвращения; сторож — в roompoll.test.ts).
 * Единственное исключение — самая первая колода, одним запросом, как и первый
 * запрос опроса. Пока колода нового раунда не догружена, ждать человеку
 * нечего (deckBehind в lib/room), и опрос засыпает. «Не чаще», а не
 * «ровно»: Chrome через пять минут скрытия сам выравнивает цепочки таймеров
 * на раз в минуту.
 *
 * Потолок — час скрытия. Ушедший на час уже не ждёт этой комнаты, и вкладка не
 * должна крутить запросы до утра. Вернулся — onVisibility спросит сразу. Матч
 * и 404 останавливают опрос сами (nextPollStep), здесь их нет.
 */
export function hiddenPollDelay(args: { waiting: boolean; hiddenForMs: number }): number | null {
  if (!args.waiting) return null
  if (args.hiddenForMs >= HIDDEN_POLL_CAP_MS) return null
  return HIDDEN_POLL_MS
}
