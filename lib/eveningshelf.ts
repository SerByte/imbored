/*
 * Полка «Твоих вечеров» (components/Evenings) — без пересчёта, выдёргивающего
 * карточку из-под пальца.
 *
 * Какие советы стоят на полке, решает сервер (app/library/page.tsx):
 * двенадцать свежих и, сверх них, те, о которых сейчас можно спросить «как
 * тебе?» (askableNow). Тринадцатый совет без ответа стоит там только поэтому
 * — и перестаёт, едва ответ дан. Сам ответ страницу не пересчитывает, а
 * «Уже прошёл» пересчитывает (router.refresh — ради полки «Пройдено» ниже),
 * и WarmCatalog на /library тоже. Карточка с «Зацепило» уходила с полки
 * вместе с MarkFinished, на строке которого стоял фокус, — и фокус падал в
 * body, а «Пройдено — больше не предложу» и «Ещё в этом духе» исчезали молча.
 *
 * Поэтому карточку, которую тронули на этой странице, полка держит сама до
 * конца захода — снимком на момент нажатия. Свежая версия с сервера, если
 * она пришла, главнее снимка. Модуль без импортов: /library у потолка
 * бюджета первой загрузки (bundle-budget.json).
 */

type Card = { appid: number; shownAt: number }

/** Одна игра может быть посоветована дважды — в разные окна */
export const eveningKey = (i: Card): string => `${i.appid}:${i.shownAt}`

/**
 * Полка после пересчёта: items сервера плюс удержанные карточки, которых он
 * больше не несёт, — на их местах. Порядок — как у listEvenings (lib/db.ts):
 * свежие первыми, при равном времени — по appid, иначе вернувшаяся карточка
 * встала бы в конец ленты, а не туда, откуда её только что видели. Нечего
 * возвращать — тот же массив: ссылка на него не меняется без причины.
 */
export function keepOnShelf<T extends Card>(items: readonly T[], kept: ReadonlyMap<string, T>): readonly T[] {
  const here = new Set(items.map(eveningKey))
  const back = [...kept.values()].filter((i) => !here.has(eveningKey(i)))
  return back.length ? [...items, ...back].sort((a, b) => b.shownAt - a.shownAt || a.appid - b.appid) : items
}
