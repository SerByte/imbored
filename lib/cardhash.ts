/**
 * АДРЕС ФАЙЛОВОЙ КАРТОЧКИ ПРЕВЬЮ — С ТЕМ ЖЕ ХЕШЕМ, ЧТО СТАВИТ NEXT.
 *
 * Адрес opengraph-image.tsx Next пишет в og:image сам и с хвостом из хеша
 * содержимого файла: /ru/opengraph-image?<хеш>. Хвост — сброс
 * кэша: Facebook, X и Telegram помнят превью по адресу картинки, и после
 * правки карточки новый хеш заставляет их сходить за ней заново.
 *
 * Английская страница объявляет ту же карточку своей записью ради
 * английского alt (docs/i18n.md, п. 10). Где карточку можно взять у
 * родителя — ownAddress и rootCard в lib/site.ts, архив обновлений, — адрес
 * с хешем приходит оттуда. Где нельзя — карточка своего же уровня, её
 * родитель ещё не видит (корневой layout и его app/[lang]/opengraph-image.tsx),
 * — хвост приписываем сами, иначе его нет вовсе. Так и было: /en-адрес
 * корневой карточки не менялся при перерисовке, и мессенджеры держали
 * старую картинку, пока русские адреса обновлялись.
 *
 * Хеш считает Turbopack — им собираются и next dev, и next build этой
 * версии: XXH3-64 от байтов файла, шестнадцатеричной строкой
 * (lib/testing/xxh3.ts, там же — где это в Next и как сверено с продом).
 * Посчитать его на рендере нельзя: исходника карточки в функции на Vercel
 * нет, а метадата корня считается и на ISR-рендере карточек игр. Поэтому
 * значение записано здесь, а сторож lib/cardhash.test.ts пересчитывает его
 * по файлу: правка карточки без правки строки валит тест, и он печатает
 * новое значение.
 *
 * Ключ — путь файла от корня репозитория: по нему сторож файл и читает.
 */
export const CARD_HASH = {
  'app/[lang]/opengraph-image.tsx': '91b1f53ea01c02b3',
} as const satisfies Record<string, string>

export type CardFile = keyof typeof CARD_HASH

/**
 * Адрес карточки так, как его пишет Next: путь страницы, /opengraph-image и
 * хеш файла. page — уже с языком: '/en', '/en/game/730'.
 */
export function cardUrl(page: string, file: CardFile): string {
  return `${page}/opengraph-image?${CARD_HASH[file]}`
}
