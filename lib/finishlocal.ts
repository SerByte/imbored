import { forgetLaunch } from './launchmemo'
import { rememberBan } from './playcache'

/**
 * Что сделать на этом устройстве, когда игра отмечена пройденной вне /play —
 * в «Твоих вечерах» или на своей странице (components/MarkFinished).
 *
 * Сервер бан уже записал, а устройство о нём не знает, и обе его памяти про
 * /play соврали бы:
 *
 *   — выдача, сохранённая на пятнадцать минут (lib/playcache), вернула бы
 *     пройденную игру героем или строкой «Продолжить» после «Подробнее» →
 *     «Уже прошёл» → «Назад». Восстановленную выдачу фильтрует список
 *     недавних банов — сюда бан и дописывается, тем же rememberBan, что у
 *     героя;
 *   — запуск с /play (lib/launchmemo) через десять минут спросил бы «не
 *     зацепило?» про игру, о которой человек только что ответил сам.
 *
 * Отдельным модулем, чтобы островок грузил его по нажатию, а не с первой
 * загрузкой: playcache тянет за собой разбор выдачи и прогрев, а на /library
 * и /game они больше ни за чем не нужны.
 */
export function rememberFinished(appid: number, nowMs: number): void {
  rememberBan(appid, nowMs)
  forgetLaunch(appid)
}
