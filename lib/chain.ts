/**
 * Передача звена цепочки крона.
 *
 * Крон новостей и крон страниц устроены одинаково: работа идёт в after(), а
 * пропускная способность берётся из цепочки самовызовов, потому что на Hobby
 * расписание ходит примерно раз в сутки, что бы ни стояло в vercel.json.
 *
 * Обе цепочки передавали звено так:
 *
 *     await fetch(url, { headers }).catch(() => {})
 *
 * — то есть отказ ГЛОТАЛСЯ целиком, и не-2xx у ребёнка не проверялся вовсе.
 * Это стоило вот чего. Замер по проду, 19 августа: цепочка страниц отработала
 * ровно пять звеньев по 52 секунды (05:19:06, 05:19:59, 05:20:50, 05:21:44,
 * 05:22:36), обогатила 49 карточек, все удачно, — и остановилась, хотя в
 * записи последнего звена стоит hasMore: true и stopped: "budget". Значит
 * очередь не кончилась и Steam не блокировал: оборвалась сама передача.
 *
 * Узнать, ЧТО именно случилось с шестым звеном, было нечем: ребёнок ничего не
 * записал (значит до своего finally не дошёл), а родитель отказ проглотил. При
 * 49 карточках в сутки оставшиеся 5198 непройденных займут сто шесть дней.
 *
 * Поэтому здесь: проверка res.ok и ВОЗВРАТ ПРИЧИНЫ. Вызывающий записывает её
 * в catalog_meta поверх своей записи — ребёнка не будет, и эта запись окажется
 * единственным следом обрыва.
 *
 * ПОВТОР ТОЛЬКО НА ОТВЕТЕ, И НИКОГДА НА ОТКАЗЕ СЕТИ. Разница несущая.
 *
 * Пришедший не-2xx доказывает, что ребёнок ответил и работы не начал: after()
 * планируется только на пути, который возвращает 202. Повторить такое
 * безопасно.
 *
 * А отказ сети НИЧЕГО не доказывает: запрос мог дойти, ребёнок мог принять
 * звено и уйти работать, а потеряться мог ответ. Повтор в этом случае поднял
 * бы ВТОРУЮ цепочку — и обе взяли бы аренду, потому что она реентерабельна по
 * holder. Два среза пошли бы к store.steampowered.com одновременно, а pace
 * держит темп в Map уровня модуля, то есть у каждой инвокации свой лимитер:
 * вдвое больше запросов при потолке, который докблок acquireLease называет
 * превышенным уже на 216 за пять минут.
 *
 * По той же причине наружу едет childMayRun: при отказе сети вызывающий не
 * имеет права отдавать аренду досрочно — ребёнок, возможно, работает под ней
 * прямо сейчас. Пусть истечёт сама по TTL.
 */

const RETRY_DELAY_MS = 1500

/** Пауза, вынесена ради теста: он не должен ждать полторы секунды. */
export type PassOpts = {
  fetchFn?: typeof fetch
  delayMs?: number
}

export type PassResult =
  | { ok: true }
  | {
      ok: false
      /** короткая причина для записи в catalog_meta */
      reason: string
      /**
       * Ребёнок, возможно, всё-таки работает: ответ не дошёл, но запрос мог.
       * Вызывающий обязан НЕ отдавать аренду в этом случае.
       */
      childMayRun: boolean
    }

/**
 * Передаёт звено. Не бросает никогда: обрыв цепочки не должен ронять уже
 * сделанную работу среза.
 */
export async function passChain(
  url: string,
  secret: string,
  opts: PassOpts = {},
): Promise<PassResult> {
  const fetchFn = opts.fetchFn ?? fetch
  const delayMs = opts.delayMs ?? RETRY_DELAY_MS

  for (let попытка = 0; попытка < 2; попытка++) {
    if (попытка) await new Promise((r) => setTimeout(r, delayMs))
    try {
      const res = await fetchFn(url, { headers: { 'x-cron-secret': secret } })
      if (res.ok) return { ok: true }
      // Ответ пришёл — работы ребёнок не начал. Второй заход безопасен.
      if (попытка) return { ok: false, reason: `HTTP ${res.status}`, childMayRun: false }
    } catch (err) {
      // Отказ сети: запрос мог дойти. Не повторяем и аренду не трогаем.
      return {
        ok: false,
        reason: err instanceof Error ? err.message.slice(0, 120) : 'сеть',
        childMayRun: true,
      }
    }
  }
  // сюда не доходим: цикл возвращает на обеих итерациях
  return { ok: false, reason: 'неизвестно', childMayRun: true }
}
