import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'vitest'

/**
 * Сторож отступа под нижнюю панель.
 *
 * Панель навигации на телефоне висит `fixed` внизу и перекрывает содержимое.
 * Отступ под неё в разметке БЫЛ — на `<body>`, с пометкой «то, что обязано
 * быть на самом внешнем элементе». И не работал.
 *
 * Механика: ScrollSmoother прокручивает `#smooth-content` трансформом. Padding
 * внешнего элемента в эту прокрутку не входит вовсе — содержимое доезжает до
 * низа экрана как ни в чём не бывало.
 *
 * ЗАМЕРЕНО на 375×812, документ прокручен до самого низа: подвал упирался в
 * 812, панель занимала 767–812, второй ряд ссылок подвала лежал на 772–788 —
 * под панелью целиком. Проверено попаданием через elementFromPoint: нажатие в
 * центр «Совместимость» активировало «Игра дня», в центр «Конфиденциальность»
 * — «Пати». То есть две ссылки подвала были недостижимы на телефоне вообще, и
 * прокрутить их из-под панели было нельзя: /rooms, /quiz и /play показали
 * ровно то же самое.
 *
 * После переноса отступа на `#smooth-content`: подвал 760, ссылка 720, попадание
 * своё. На 768 и 1280 отступ остаётся нулевым — панели там нет.
 *
 * Сторож статический: проверяет, что отступ стоит на прокручиваемом
 * содержимом, а не на внешнем элементе. Родственник lib/smoothfixed.test.ts,
 * который сторожит обратное — что `fixed` живёт СНАРУЖИ смузера.
 */

const LAYOUT = fs.readFileSync(path.join(__dirname, '..', 'app', 'layout.tsx'), 'utf8')

/** Строка отступа: важно и число, и то, что он снимается на широких экранах. */
const PAD = /pb-\[calc\(52px\+env\(safe-area-inset-bottom\)\)\]\s+md:pb-0/

describe('отступ под нижнюю панель', () => {
  test('стоит на прокручиваемом содержимом', () => {
    const at = LAYOUT.indexOf('id="smooth-content"')
    expect(at, 'обёртка #smooth-content не найдена').toBeGreaterThan(-1)
    const tag = LAYOUT.slice(at, LAYOUT.indexOf('>', at))
    expect(
      PAD.test(tag),
      'отступ под панель обязан быть на #smooth-content: смузер прокручивает именно его, ' +
        'и padding внешнего элемента в прокрутку не входит',
    ).toBe(true)
  })

  test('не стоит на body, где он ничего не делает', () => {
    // Именно '<body className=', а не '<body': докблок выше цитирует тег
    // словами, indexOf находил комментарий, и проверка была ВАКУУМНОЙ —
    // поймано пробой, как и три сторожа до неё.
    const at = LAYOUT.indexOf('<body className=')
    expect(at, 'тег <body> с классами не найден').toBeGreaterThan(-1)
    const tag = LAYOUT.slice(at, LAYOUT.indexOf('>', at))
    expect(
      /pb-\[calc\(52px/.test(tag),
      'на <body> этот отступ уже стоял и не работал — смузер прокручивает не его',
    ).toBe(false)
  })
})
