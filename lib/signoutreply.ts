/**
 * Ответ на выход (POST /api/auth/logout) — как его читает кнопка выхода
 * (components/SignOut).
 *
 * Отдельным модулем без импортов, как lib/feedlinkreply: компонент тестом не
 * нажать, а от этого разбора зависит, уведёт ли кнопка на главную, как после
 * удачи, — или скажет, что вышло не всё.
 *
 * «Да, везде» жмут, когда доступ мог утечь, и подтверждение обещает, что
 * погаснут все входы и ссылка на RSS. Сделать меньше сервер может двумя
 * путями, и оба он называет, а не прячет:
 *   • пачка revokeAllSessions упала — { ok: true, revoked: false }: ни одна
 *     сессия и ни одна ссылка не погашены;
 *   • состояние сессии не прочлось (холодный экземпляр, Turso моргнула) —
 *     открытая на отказе сессия не подтверждена (lib/sessions), и роут гасит
 *     одно это устройство: { ok: true, scope: 'this-device' }.
 * Кука в обоих случаях погашена — на ЭТОМ устройстве человек вышел. Кнопка
 * ответа не читала и уводила на главную, как после удачи: человек уходил
 * уверенным, что чужие входы и ссылка мертвы, а повторить «везде» без нового
 * входа уже не мог.
 *
 * Обычному выходу revoked: false не помеха: кука погашена, и строке сессии без
 * отзыва больше нечего пускать — токена нет ни в одном браузере (докблок роута).
 */

export type SignOutReply =
  /** Сделано то, о чём просили */
  | 'done'
  /** Это устройство вышло, а «везде» — нет: остальные входы и ссылка на RSS живы */
  | 'partial'
  /**
   * Ответил не роут — сбой платформы, обрыв, чужая страница. Погашена ли
   * кука, неизвестно, и уходить с экрана, как после выхода, нечестно
   */
  | 'failed'

export async function signOutReply(all: boolean, res: Response): Promise<SignOutReply> {
  if (!res.ok) return 'failed'
  const body: unknown = await res.json().catch(() => null)
  const o = typeof body === 'object' && body !== null ? (body as Record<string, unknown>) : {}
  // Каждый ответ роута — { ok: true, … }: без этого признака ответ не его
  if (o.ok !== true) return 'failed'
  if (all && (o.revoked === false || o.scope === 'this-device')) return 'partial'
  return 'done'
}
