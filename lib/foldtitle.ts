/**
 * Название и запрос в одном виде — для поиска по названию.
 *
 * Жил в lib/forgotten рядом с поиском по стене /library, но понадобился
 * клиенту: «Найти игру» (components/CatalogSearch) ищет по каталогу прямо в
 * браузере. А lib/forgotten тянет за собой весь движок подбора
 * (lib/recommend), и клиентский поиск увёз бы его в бандл. Поэтому здесь —
 * ни одного импорта, и так должно остаться (сторож — lib/foldtitle.test.ts).
 */

/**
 * Строчные, без диакритики, только буквы и цифры через пробел.
 *
 * Не normalizeTitle из lib/series: тот срезает издания («… Game of the Year
 * Edition»), чтобы склеивать серии, а поиску срезанное нужно — человек
 * вправе искать «goty» или «deluxe». Отсюда и другое имя: два экспорта
 * normalizeTitle с разным смыслом путали бы автоимпорт.
 *
 * ё→е и й→и — следствие NFKD: он раскладывает их на базовую букву и знак, а
 * знаки срезаются. Запрос сворачивается тем же путём, так что «елки»
 * находит «Ёлки», а «иога» — «Йогу»: человек набирает по памяти.
 *
 * ПОРЯДОК ВАЖЕН. NFKD раскладывает не только диакритику: ™ становится буквами
 * «TM», № — «No», римская Ⅳ — «IV». Прежде строчные делались ДО разложения, и
 * эти буквы оставались заглавными и приклеенными к слову: «BioShock™» давал
 * «bioshockTM», «HELLDIVERS™ 2» — «helldiversTM 2». В каталоге таких названий
 * 237 из 5816 (замер по локальной копии каталога). Вхождение слова это не
 * ломало, а точное совпадение и совпадение с начала — ломало: «bioshock» не
 * был равен «BioShock™», и поиск каталога ставил выше «BioShock Infinite».
 * Теперь строчные — после разложения, а ™ и ℠ — разделитель, а не буквы.
 *
 * АПОСТРОФ СТИРАЕТСЯ, а не становится разделителем: он стоит внутри слова.
 * Разделителем он резал «Baldur's Gate» на «baldur s gate», и набранное так,
 * как его обычно набирают, — «baldurs gate», «garrys mod», «dont starve», —
 * не находилось ни в каталоге, ни на стене /library. Стёртый, он сводит к
 * одному виду и «baldur's», и «baldur’s», и «baldurs», а «baldur» по-прежнему
 * начало слова. Стирается любой: ' ’ ‘, ` и ´ вместо него и ʼ (U+02BC) — та
 * для \p{L} вообще буква и без этого прилипала бы к слову. ´ — до NFKD: он
 * раскладывает его в пробел со знаком, и пробел остался бы.
 *
 * Точки акронима («S.T.A.L.K.E.R.») и дефис («Half-Life») — по-прежнему
 * разделитель: «half life» должно находить «Half-Life» с начала слов, а
 * «counter strike» — «Counter-Strike». Слитный набор («stalker»,
 * «halflife») ищет поиск каталога сам, по названию слитно (tight и границы
 * слов в lib/catalogsearch), — у свёртки на это одного вида не хватит.
 */
export function foldTitle(s: string): string {
  return s
    .replace(/['‘’ʼ`´]/g, '')
    .replace(/[™℠]/g, ' ')
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
}

/** Подходит ли название: каждое слово запроса — часть названия. Пустой запрос — всё. */
export function matchesTitle(name: string, q: string): boolean {
  const words = foldTitle(q).split(' ').filter(Boolean)
  if (words.length === 0) return true
  const title = foldTitle(name)
  return words.every((w) => title.includes(w))
}
