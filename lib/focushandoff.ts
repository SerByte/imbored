/**
 * ФОКУС, ИЗ-ПОД КОТОРОГО УШЁЛ ЭКРАН.
 *
 * Колода, панель «Колода кончилась», комната под церемонией матча — всё это
 * подменяется целиком, и элемент в фокусе уходит вместе с подменой. Браузер
 * ставит фокус в body: клавиатурного человека молча выкидывает в начало
 * документа, скринридер теряет место, а следующий Tab в Safari идёт по шапке.
 * Новый экран забирает фокус себе — но только потерянный.
 *
 * Оговорка «только потерянный» оплачена матчем. Он приезжает опросом, а не
 * нажатием: чужой последний голос, «Берём» у другого участника. В эту минуту
 * человек может стоять в шапке, и отнять у него это место хуже, чем
 * промолчать, — о матче и так скажет живая строка страницы комнаты.
 *
 * Модуль без DOM-глобалов, как lib/skiplink: документ приходит аргументом, и
 * правило проверяется в node, без браузера.
 */

/**
 * Можно ли забрать фокус на новый экран, ничего у человека не отняв.
 *
 * Да, если фокуса нет вовсе или он в body — туда его роняет браузер, когда
 * элемент в фокусе уходит из DOM. Да и тогда, когда он ещё внутри home — того,
 * что вот-вот уйдёт: выключенная на время запроса кнопка («Собираю…») в части
 * браузеров держит фокус до самого размонтирования. Во всех остальных случаях
 * человек стоит где-то сам, и фокус остаётся при нём.
 */
export function focusAdrift<T>(
  doc: { activeElement: T | null; body: T | null },
  home?: { contains(node: T): boolean } | null,
): boolean {
  const at = doc.activeElement
  if (at === null || at === doc.body) return true
  return home ? home.contains(at) : false
}
