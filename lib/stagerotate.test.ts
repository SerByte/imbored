import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'vitest'

/**
 * Сторож пересборки сцены на повороте экрана.
 *
 * Решение «закреплять сцену или нет» считается из высоты содержимого и высоты
 * окна — один раз, при монтировании. ScrollTrigger сам пересчитывает ГРАНИЦЫ
 * на изменении размера, но флаг `pin` задаётся при создании и живёт вечно.
 *
 * ЗАМЕРЕНО поворотом 390×844 → 844×390 (Emulation.setDeviceMetricsOverride на
 * живой странице):
 *
 *   было  — две сцены остались закреплёнными, не помещаясь: «more» (нужно 526
 *           при экране 390) и «money» (691 при 390). Низ сцены «more» входил в
 *           кадр ТОЛЬКО пока она гасла: видимость 0.26, затем 0.05, затем 0.
 *           На снимке — пустой тёмный экран.
 *   стало — противоречий ноль, низ входит в кадр при видимости 1.
 *
 * КОНТРОЛЬ, без которого это была бы догадка: та же страница, загруженная
 * СРАЗУ в ландшафте. Там сцена не закрепляется и низ виден полностью. Значит
 * виновато устаревшее решение, а не короткий экран сам по себе.
 *
 * Десктоп не изменился: высота документа 10289 и пять закреплённых сцен — те
 * же числа, что на проде до правки.
 *
 * ПОЧЕМУ ОРИЕНТАЦИЯ, А НЕ ВЫСОТА ОКНА — в докблоке над subscribeOrientation:
 * высота на телефоне пляшет от адресной строки при каждой прокрутке.
 */

const STAGE = fs.readFileSync(
  path.join(__dirname, '..', 'components', 'landing', 'Stage.tsx'),
  'utf8',
)

describe('сцена и поворот экрана', () => {
  test('сцена пересобирается при смене ориентации', () => {
    expect(STAGE, 'ориентация не читается вовсе — решение о закреплении останется прежним').toMatch(
      /matchMedia\('\(orientation: landscape\)'\)/,
    )
    expect(
      STAGE,
      'ориентация обязана быть в зависимостях useGSAP: иначе она прочитана и не используется',
    ).toMatch(/dependencies:\s*\[orientation\]/)
  })

  test('прежнее закрепление снимается перед пересборкой', () => {
    expect(
      STAGE,
      'без revertOnUpdate pin-spacer от старой ориентации останется в потоке, ' +
        'и страница получит лишнюю дыру в высоту прежнего экрана',
    ).toMatch(/revertOnUpdate:\s*true/)
  })
})
