import { unstable_cache } from 'next/cache'
import { getMajorFeed, type StoredNews } from './db'
import { getDb } from './server'

/**
 * Кэш общей ленты «Что нового».
 *
 * Зачем. Страница была force-dynamic и отдавала 453 КБ за 1.8 секунды с
 * `x-vercel-cache: MISS` на КАЖДЫЙ заход — при том что два анонимных запроса
 * подряд отличались ровно одним полем (серверный nowSec, который клиент и так
 * пересчитывает через NowProvider). То есть самая тяжёлая страница сайта
 * пересобиралась заново для каждого посетителя ради одинакового результата.
 *
 * Что кэшируется и что НЕТ. Только общая лента — она одна на всех. Личная
 * (getFeedForApps) и снапшот библиотеки остаются живыми: их содержимое
 * персонально, и место им в кэше только под ключом пользователя, чего мы здесь
 * специально не делаем. Разрез проходит ровно по этому шву, поэтому
 * залогиненный получает свою ленту без изменений, а добивку из общей — из
 * кэша.
 *
 * Ключ включает limit. Соблазн был обратный: закэшировать один максимум и
 * резать в памяти, ключей стало бы меньше. Но getMajorFeed читает
 * limit × OVERFETCH строк и схлопывает их onePerGame ДО limit, так что
 * major(60).slice(0, 30) и major(30) расходятся, когда игр в выборке меньше,
 * чем строк. А состав ленты обязан совпадать с тем, что считает
 * /api/whatsnew/head, иначе плашка «N новых обновлений» обещает то, чего
 * после обновления страницы не появится (см. докблок роута). Лишние записи в
 * кэше дешевле этого риска: горячих limit'ов на практике два-три.
 *
 * По той же причине голова ленты читает ЭТУ ЖЕ функцию, а не базу и не свой
 * отдельный кэш: совпадать со страницей ей нужно и во времени. Две записи
 * stale-while-revalidate перегенерируются независимо, и плашка снова обещала
 * бы патч, которого router.refresh() ещё не покажет. Одна функция — ещё не
 * одна запись: голова и страница собираются в разных слоях, и запись у них
 * общая только потому, что колбэк связан через bind (см. cachedMajorFeed).
 *
 * unstable_cache, а не "use cache". Директива требует либо
 * experimental.useCache (само помечено устаревшим), либо cacheComponents,
 * который включает PPR на всё приложение — а у нас восемь сегментов
 * force-dynamic, и трогать их ради одной функции не за что. unstable_cache
 * не требует ни строчки в next.config и меняется на директиву в один приём,
 * когда придёт время.
 */

/** Тег инвалидации. Дёргается из кронов новостей и пересказов. */
export const NEWS_MAJOR_TAG = 'news:major'

/**
 * Сутки — это потолок задержки на случай, если инвалидация по тегу не
 * доехала (запуск крона, снятый по сроку до своего конца, — revalidateTag там
 * раз на запуск, в конце; ручной прогон скрипта мимо роутов) или перемену
 * тег не сообщает вовсе (игра перешла порог FEED_RANK_FLOOR одним весом — см.
 * feedTouched в lib/newsjob). Нормальный путь обновления — revalidateTag, а
 * не истечение.
 *
 * Стояло десять минут, и число это не только про запись кэша. unstable_cache
 * с числовым revalidate, прочитанный при статической генерации, опускает
 * revalidate ВСЕЙ объемлющей записи ISR до своего, если тот меньше
 * (next/dist/server/web/spec-extension/unstable-cache.js: workUnitStore.revalidate
 * для 'prerender-legacy'; app-route берёт его в collectedRevalidate). Так
 * /whatsnew/feed.xml с любым своим revalidate перегенерировался раз в десять
 * минут в обоих языках — по опросу любого ридера. Поэтому число здесь и
 * revalidate ленты (app/[lang]/whatsnew/feed.xml) меняются только вместе:
 * лента со своим сроком больше этого всё равно жила бы этим. Сторожит
 * route.test.ts ленты. false здесь тоже не капкан (Next не опускает срок
 * записи из-за бесконечного), но оставил бы ленту без страховки вовсе.
 *
 * Голове (/api/whatsnew/head) и странице /whatsnew сутки ничего не меняют:
 * обе force-dynamic, читают эту же запись и получают новое по тегу, как и
 * раньше.
 */
export const MAJOR_TTL_SEC = 86_400

async function loadMajorFeed(limit: number, minRank: number): Promise<StoredNews[]> {
  // getDb внутри кэшируемой функции — можно: она не читает ни cookies, ни
  // headers. Передать db аргументом было бы нельзя: аргументы участвуют в
  // ключе, а объект соединения в ключ не сериализуется.
  const db = await getDb()
  return getMajorFeed(db, limit, { minRank })
}

/**
 * Колбэк — связанная копия (bind), а не стрелка на месте. Это и держит
 * «одну запись» из докблока выше.
 *
 * unstable_cache строит ключ из ТЕКСТА функции: `${cb.toString()}-${keyParts}`
 * плюс аргументы (next/dist/server/web/spec-extension/unstable-cache.js;
 * docs 04-functions/unstable_cache.md: «the stringified version of your
 * function»). А текст у одной и той же стрелки разный в разных слоях сборки.
 * Turbopack собирает модуль отдельно для app-route (голова, feed.xml) и для
 * app-rsc (страница) и подставляет в тело слой-зависимые имена импортов:
 * в dev `…$5b$app$2d$route$5d$…["getDb"]` против `…$5b$app$2d$rsc$5d$…`, а два
 * чанка app-rsc расходятся ещё и между собой. В проде минификатор называет
 * параметры как придётся: `async(e,t)=>{let a=await (0,l.getDb)()…` в одном
 * чанке и `async(a,b)=>{let c=await (0,f.getDb)()…` в другом. Итог —
 * два независимых ключа под одним тегом: голова и страница жили в разных
 * записях stale-while-revalidate, и плашка «N новых» снова обгоняла клик.
 *
 * У связанной функции toString() — `function () { [native code] }` в любом
 * слое и чанке, так что ключ держится только на keyParts и аргументах.
 * Отсюда два обязательства. keyParts уникальны на весь проект: текст функции
 * больше не разводит два кэша с одинаковыми keyParts. И версию в keyParts
 * (`:v1`) поднимать руками, когда меняется форма результата: раньше ключ
 * сам менялся вместе с текстом колбэка на каждой сборке, теперь он стабилен
 * между деплоями, и запись старой формы прожила бы до своего TTL.
 * Стрелку сюда не возвращать — это сторожит lib/whatsnewcache.test.ts.
 *
 * v2 — строки ленты несут английские слоты (tldrEn, titleEn), и одна запись
 * кэша служит обоим языкам: /whatsnew и /en/whatsnew читают её же, а язык
 * выбирает страница. Запись v1 таких полей не знает, и /en до конца её TTL
 * молчал бы о пересказах, которые в базе уже есть.
 */
export const cachedMajorFeed = unstable_cache(
  loadMajorFeed.bind(null),
  ['whatsnew:major:v2'],
  { tags: [NEWS_MAJOR_TAG], revalidate: MAJOR_TTL_SEC },
)
