import { discountOf, discountTrustedUntil, trustedPrice } from './discount'
import { newsPath, type PostRef } from './newspage'
import { patchArchivePath } from './patcharchive'

/**
 * Кэш карточки игры: сколько она живёт, что пререндерится и когда её сбросить.
 *
 * Всё это про ISR Writes. На Hobby их двести тысяч блоков по 8 КБ за окно, а
 * окно перед паузой проекта выбрало 2.2 миллиона. Карточка — на каждую игру и
 * каждый язык, около двенадцати тысяч адресов (шесть тысяч игр на ru и /en), и
 * запись карточки — не только HTML. Замер продовой сборки: HTML ~108 КБ, .rsc
 * ~56 КБ, и Next 16 кладёт рядом копии RSC по сегментам для префетча —
 * _full.segment.rsc того же размера и мелкие куски, — всего ~224 КБ, около
 * тридцати блоков (не семнадцати, как считалось по HTML и .rsc). Один обход
 * всех карточек краулером — 12 тысяч × 30 ≈ 360 тысяч блоков, почти два
 * месячных лимита. Пишет Vercel в трёх случаях: пререндер на сборке, первый
 * рендер адреса и перегенерация, вывод которой РАЗОШЁЛСЯ с прошлым («When
 * revalidation runs and the content hasn't changed from the previous
 * version, no ISR write units are incurred», документация Vercel).
 *
 * Отсюда три рычага, и все три здесь:
 *   • пререндер — только на продовой сборке и только верх каталога;
 *   • месяц жизни вместо суток — при стабильном выводе (см. докблок
 *     app/[lang]/game/[appid]/page.tsx) это месяц без единой лишней записи;
 *   • точечный сброс, когда кроны поменяли данные карточки: так свежие
 *     pros/cons, патчи и конец скидки не ждут месяца, а неизменённые карточки
 *     не перерисовываются.
 */

/**
 * Жизнь карточки в кэше, секунды: тридцать дней. Литерал `revalidate` в
 * page.tsx обязан быть тем же числом — Next читает его только литералом,
 * импорт он не разберёт. Совпадение сверяет сторож рядом со страницей
 * (app/[lang]/game/[appid]/page.test.ts). Тот же срок — у архива обновлений
 * и страниц патчей (news/page.tsx, news/[gid]/page.tsx): их тоже сбрасывают
 * кроны, когда меняют (resetSliceCards).
 *
 * Было семь дней, и неделя не действовала ни дня. Next берёт для страницы
 * наименьший срок из всего, что отрендерено в её дереве, unstable_cache
 * включительно, а граница 404 app/[lang]/not-found.tsx рендерится в RSC
 * каждой страницы под [lang] и держала свою полку в unstable_cache на сутки.
 * Карточка отвечала s-maxage=86400 при экспорте 604_800 и перерисовывалась на
 * первом заходе краулера через сутки после прошлого; prerender-manifest давал
 * 86400 даже /privacy, у которой своего revalidate нет. Число здесь значит
 * что-то, только пока ни один кусок дерева страницы не просит меньше.
 *
 * Почему месяц. Свежесть держат не часы, а события: кроны карточек, новостей
 * и пересказов сбрасывают адрес сами, когда поменяли его данные
 * (revalidateGamePages, resetSliceCards), конец скидки — revalidateEndedDeals.
 * По часам доезжает только то, что меряет недельная сверка (lib/catalogsignals):
 * счёт и доля отзывов, онлайн, пульс месяца. Их сдвиг виден на карточке почти
 * каждой живой игры каждую неделю, и сбрасывать её ради него — та же запись в
 * тридцать блоков на каждую из двенадцати тысяч. Месяц — размен: эти числа на
 * карточке бывают старше недели, до месяца, если её не сбросил ни один крон,
 * а перегенераций от одних часов вчетверо меньше, чем у недели. Не
 * «навсегда» (false) — чтобы и они когда-то доезжали без деплоя.
 */
export const GAME_PAGE_REVALIDATE_SEC = 2_592_000

/**
 * Сколько карточек пререндерится на сборке — верх каталога по sitemapGames.
 *
 * Было пятьсот, и это пять сотен записей по тридцать блоков на КАЖДУЮ
 * сборку — около пятнадцати тысяч блоков, придёт на карточку хоть кто-нибудь
 * или нет. При деплое раз в день это больше, чем весь месячный лимит.
 *
 * Пререндер окупается там, где адрес и так посетят: тогда запись всё равно
 * случилась бы, просто позже и холодным рендером. Для верхней сотни это
 * почти наверняка — на неё больше всего внешних ссылок, её первой обходят
 * краулеры. Хвост дешевле досоздать по требованию (dynamicParams по
 * умолчанию true): первый заход платит холодным рендером, который и так
 * укладывается в «хорошо» (perf-11 аудита), а запись случается, только если
 * адрес кому-то понадобился.
 *
 * Сотня — на все языки, а не на каждый: пререндерится только русская ветка,
 * /en/game/<appid> досоздаётся по требованию (generateStaticParams страницы,
 * app/[lang]/game/[appid]/page.tsx). Иначе язык удвоил бы и записи сборки.
 */
export const PRERENDER_TOP = 100

/**
 * Пререндерить ли карточки на этой сборке. Только прод: превью делили с
 * продом базу (TURSO_* заведены на Production и Preview) и за три дня 45 раз
 * пререндерили те же пятьсот карточек — ради деплоев, которые никто не
 * открывал. Локальной сборке пререндер тоже ни к чему, а базы у неё может не
 * быть вовсе.
 */
export function prerenderAtBuild(env: Record<string, string | undefined> = process.env): boolean {
  return env.VERCEL_ENV === 'production'
}

/** Адрес карточки — тот, под которым её кэширует ISR и сбрасывает revalidatePath */
export function gamePagePath(appid: number): string {
  return `/game/${appid}`
}

/**
 * Пометить карточки к перегенерации — каждую один раз.
 *
 * revalidate — revalidatePath из next/cache; аргументом, а не импортом, по
 * тому же доводу, что у announceFreshPatches (lib/indexnow): вне сервера Next
 * настоящий revalidatePath бросает, а здесь важно только, какие адреса.
 *
 * Что это стоит: revalidatePath ничего не рендерит сам (docs Next,
 * revalidatePath.md: из Route Handler путь помечается, перегенерация — при
 * следующем заходе). Незаходимая карточка не стоит ничего, а зашедшая
 * пишется, только если её вывод и правда поменялся. «Заход» здесь — и
 * префетч ссылки в кадре тоже: поэтому полки карточек ведут на них через
 * GameLink, без префетча (components/GameLink).
 *
 * Возвращает, сколько адресов помечено.
 */
export function revalidateGamePages(
  appids: Iterable<number>,
  revalidate: (path: string) => void,
): number {
  const seen = new Set<number>()
  // Отрицательные appid — тоже карточки (кураторский пул других магазинов)
  for (const appid of appids) if (Number.isInteger(appid) && appid !== 0) seen.add(appid)
  for (const appid of seen) revalidate(gamePagePath(appid))
  return seen.size
}

/**
 * Отпечаток строки карточки: не поменялся он — не поменялось и всё, что
 * карточка берёт из этой строки. Им крон карточек (lib/pagejob) решает,
 * какие адреса сбросить. Обратное не обязано быть точным: лишний сброс
 * стоит перегенерации при заходе, но не записи, если вывод тот же.
 *
 * Строка берётся целиком (getGamePageRows): мета с семантикой, сводка отзывов,
 * pros/cons. Узкие проверки «что записал срез» не годятся — срез пишет всё
 * безусловно (кадры пачкой, семантику всегда, сводку при каждом ответе), и
 * «записал» у него значит «трогал», а не «поменял».
 *
 * Единственное исключение — priceAt. Срез датирует им каждый ответ
 * appdetails, а карточка берёт из метки только выводы: верить ли цене и
 * скидке (trustedPrice, discountOf) и до какого момента — discountTrustedUntil,
 * по которому страница гасит строку цены (ShownUntil). В отпечатке стоят эти
 * выводы, а не сама метка. У цены без скидки и у скидки со сроком от Steam
 * замер не виден вовсе, и новая метка не должна делать карточку изменённой.
 * У скидки без срока виден: свежий замер отодвигает момент, когда страница
 * спрячет цену, — и карточку, собранную по старому замеру, надо сбросить,
 * иначе она погасит ещё живую скидку.
 */
export function cardRowPrint(row: GamePageRow, nowSec: number): string {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { priceAt, ...meta } = row.meta
  return JSON.stringify({
    meta,
    price: trustedPrice(row.meta, nowSec),
    deal: discountOf(row.meta, nowSec),
    until: discountTrustedUntil(row.meta, nowSec),
    reviewsSummary: row.reviewsSummary,
    prosCons: row.prosCons,
    // второй ряд под заголовком: снятое или новое русское название — другая страница
    nameRu: row.nameRu,
  })
}

/**
 * Итог звена крона — в отметку, карточки из него — в сброс.
 *
 * Список карточек нужен роуту, а не отметке: runChain кладёт итог звена в
 * *_last_slice целиком, и у новостей там лежали бы десятки appid на звено —
 * шум в catalog_meta и в выводе /api/cron/health. Отметке остаётся число
 * помеченных адресов; роут складывает его и в «итого» запуска.
 *
 * archives — заодно архивы обновлений тех же игр (/game/<appid>/news,
 * lib/patcharchive). Его передают кроны новостей и пересказов: их cards — это
 * ровно игры, у которых поменялся список патчей или появился пересказ, то
 * есть строки архива. revalidatePath сбрасывает только названный адрес, не
 * вложенные, — без второго вызова архив ждал бы своего месяца ISR. Крон
 * карточек его не передаёт: патчей и пересказов он не пишет. Архивы — только
 * у игр Steam: у чужих магазинов новостей нет.
 *
 * posts — по той же причине страницы самих патчей (newsPath), которые звено
 * поменяло: опрос переписал пост — тело, заголовок, вид (shown из
 * writeNewsItems в lib/db), — или пересказ дописал «Коротко» и английский
 * заголовок. Страница
 * патча живёт столько же, сколько карточка, и без сброса правка издателя или
 * свежий пересказ ждали бы её конца. Новый пост соседей не меняет: внизу
 * страницы — только патчи, вышедшие раньше неё («Предыдущие патчи»), так что
 * сбрасывать старые страницы игры из-за нового патча незачем. Правка
 * заголовка поста меняет ещё строку в списках тех, что вышли после него, —
 * их здесь нет намеренно: это строка в списке, и она доедет с их сроком.
 *
 * В «сброшено» — по-прежнему число игр; posts, как и cards, в отметку не идут.
 */
export function resetSliceCards<T extends { cards: number[]; posts?: PostRef[] }>(
  slice: T,
  revalidate: (path: string) => void,
  opts: { archives?: boolean } = {},
): Omit<T, 'cards' | 'posts'> & { сброшено: number } {
  const { cards, posts = [], ...rest } = slice
  if (opts.archives) {
    for (const appid of new Set(cards)) {
      if (Number.isInteger(appid) && appid > 0) revalidate(patchArchivePath(appid))
    }
  }
  const pages = new Set(posts.filter((p) => Number.isInteger(p.appid) && p.appid > 0).map((p) => newsPath(p.appid, p.gid)))
  for (const page of pages) revalidate(page)
  return { ...rest, сброшено: revalidateGamePages(cards, revalidate) }
}

/** Ключ в catalog_meta: докуда крон карточек прошёл погасшие скидки (unix-секунды) */
export const DEALS_SWEPT_KEY = 'pages_deals_swept_through'

/**
 * Сбросить карточки, чья скидка погасла с прошлого прохода.
 *
 * Карточку собирают со скидкой и держат месяц (GAME_PAGE_REVALIDATE_SEC).
 * Людям строку цены гасит клиент в срок (ShownUntil), а разметка остаётся
 * HTML как есть: Offer с акционной ценой — у скидки без срока от Steam ещё и
 * без priceValidUntil — висел бы в выдаче до перегенерации по сроку, хотя
 * видимая страница уже молчит. Правило lib/jsonld «разметка говорит то же,
 * что видно» держится, только если карточку перегенерируют вскоре после конца
 * скидки. Это и делает проход: окно расхождения — от конца скидки до
 * ближайшего запуска крона карточек, то есть в пределах суток, а не месяца.
 *
 * Окно — (прошлый проход, сейчас], и отметка двигается только после сброса:
 * упало чтение — окно целиком достанется следующему запуску. Длиннее срока
 * жизни карточки окно не бывает: карточка старше него перегенерируется сама,
 * и после долгой паузы крона (килл-свитч) скидки, погасшие ещё раньше,
 * сбрасывать незачем. Короче — нельзя: карточка, собранная накануне конца
 * скидки, держит её в разметке весь свой срок.
 *
 * Что стоит: пометка ничего не рендерит (revalidateGamePages), запись
 * случается у карточки, на которую зашли, и она оправдана — скидка с
 * карточки пропадает.
 *
 * Скидки, погасшие в базе раньше срока (свежий ответ Steam без скидки), сюда
 * не попадают — в строке скидки уже нет. Такую карточку сбрасывает срез
 * карточек по отпечатку (cardRowPrint), если ответ записал он. Ценовой
 * прогрев по заходам (lib/deals) карточек не сбрасывает: такая карточка
 * держит старую скидку в разметке до своего срока, а людям её гасит клиент
 * в прежний срок.
 *
 * Возвращает, сколько адресов помечено.
 */
export async function revalidateEndedDeals(
  db: Db,
  revalidate: (path: string) => void,
  nowSec: number,
): Promise<number> {
  const prev = Number(await getCatalogMeta(db, DEALS_SWEPT_KEY))
  const after = Math.max(Number.isFinite(prev) ? prev : 0, nowSec - GAME_PAGE_REVALIDATE_SEC)
  if (after >= nowSec) return 0
  const n = revalidateGamePages(await dealsEndedBetween(db, after, nowSec), revalidate)
  await setCatalogMeta(db, DEALS_SWEPT_KEY, String(nowSec))
  return n
}
