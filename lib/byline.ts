/**
 * Подпись студии: «Valve · 2013». Любая половина может отсутствовать.
 *
 * Жила в components/whatsnew/format.ts, пока принадлежала одной ленте. Со
 * страницей игры разделов стало два, и импортировать формат чужого сегмента
 * значило бы связать /game с внутренностями /whatsnew — ровно то, из-за чего
 * когда-то переехали шрифты карточек в lib/og.ts.
 *
 * Разработчик и год заполнены у ВСЕХ игр каталога (проверено запросом: 1000
 * из 1000), поэтому подпись показывается практически всегда — но
 * необязательность обеих половин сохранена: каталог пополняется, и запись без
 * издателя однажды появится.
 */
export function byline(developer?: string, releaseYear?: number): string | null {
  const parts = [developer, releaseYear ? String(releaseYear) : undefined].filter(Boolean)
  return parts.length ? parts.join(' · ') : null
}
