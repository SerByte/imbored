/**
 * Есть ли в тексте русская буква — одно правило на весь каталог.
 *
 * Описание игры приезжает тремя дорогами: прогрев (GetItems с language
 * english, lib/catalog), обогащение карточки (appdetails с l=russian,
 * lib/pagejob) и заливка каталога из локальной базы (scripts/publish-catalog).
 * Русское кладут только две последние, а английское — все три, и каждая
 * следующая запись переписывала предыдущую. Правило «русское не заменяется
 * нерусским» поэтому обязано стоять на всех трёх дорогах, и стояло оно
 * только на заливке, со своим классом букв; у доливки описаний был третий,
 * [Ѐ-ӿ]. Три копии одного правила разъезжаются при первой же правке.
 *
 * Здесь класс один, и он же уходит в SQL: GLOB, а не LIKE, потому что LIKE в
 * SQLite регистронезависим только для ASCII, а квадратные скобки для него не
 * метасимволы — '%[а-я]%' не сработал бы вовсе. Диапазон «а-я» в GLOB тоже не
 * годится: ё стоит вне его.
 *
 * Это НЕ isRussianText из lib/gamepage. Там вопрос «показывать ли текст в
 * сниппете», и нужна доля кириллицы; здесь вопрос «есть ли что беречь», и
 * хватает одной буквы — так же, как SQL способен проверить это без счёта.
 */

export const CYRILLIC_LETTERS =
  'абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ'

const CYRILLIC = new RegExp(`[${CYRILLIC_LETTERS}]`)

export function hasCyrillic(text: string | null | undefined): boolean {
  return Boolean(text) && CYRILLIC.test(text as string)
}

/** SQL-литерал для GLOB: строка содержит хоть одну букву из CYRILLIC_LETTERS */
export const CYRILLIC_GLOB = `'*[${CYRILLIC_LETTERS}]*'`
