import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'vitest'

/**
 * Сторож склонений в разметке.
 *
 * Функция plural существует давно и в половине мест честно зовётся. В другой
 * половине число просто приклеивали к слову — и продукт показывал человеку его
 * собственные цифры с чужой грамматикой: на странице библиотеки стояло
 * «22 игр · 4 404 часов» вместо «22 игры · 4 404 часа». Это ровно та мелочь,
 * по которой видно, доделан продукт или нет.
 *
 * Разъехалось не по злому умыслу: строку пишут один раз, глядя на своё тестовое
 * число, и на нём она верна. Ошибка вылезает у чужого числа, которого автор
 * никогда не видел. Поэтому здесь тест, а не внимательность.
 */

const ROOT = path.join(__dirname, '..')

/**
 * Существительные, которые в интерфейсе стоят после числа. От длинных к
 * коротким: иначе «игр» съедает начало «игрока» и совпадение обрывается.
 */
const NOUNS = [
  'игр', 'игра', 'игры', 'игре', 'играх', 'игрок', 'игрока', 'игроков',
  'час', 'часа', 'часов', 'минут', 'минута', 'минуты', 'минуту',
  'день', 'дня', 'дней', 'неделя', 'недели', 'недель',
  'месяц', 'месяца', 'месяцев', 'лет',
  'человек', 'человека', 'голос', 'голоса', 'голосов', 'друг', 'друга', 'друзей',
  'очко', 'очка', 'очков', 'балл', 'балла', 'баллов',
  'комната', 'комнаты', 'комнат', 'сессия', 'сессии', 'сессий',
  'устройство', 'устройства', 'устройств',
  'пицца', 'пиццы', 'пицц', 'бургер', 'бургера', 'бургеров',
  'правка', 'правки', 'правок', 'патч', 'патча', 'патчей',
]
  .sort((a, b) => b.length - a.length)
  .join('|')

/**
 * Конец слова описан явным просмотром вперёд, а НЕ через \b.
 *
 * Это не стилистика. В JavaScript \b знает только ASCII, поэтому между «игр» и
 * пробелом границы слова нет вовсе, и правило `игр\b` не совпадает никогда.
 * Первая версия этой проверки была написана с \b, показала «нарушений нет» —
 * и пропустила все до единого. Тест, который всегда зелёный, хуже отсутствия
 * теста: он ещё и успокаивает.
 */
const END = '(?![а-яёА-ЯЁa-zA-Z])'
const COUNTED = new RegExp('[}](?:\\s|&nbsp;| )*(?:</span>)?\\s*(?:·\\s*)?(' + NOUNS + ')' + END, 'g')

/** Исходник без комментариев: иначе сторож ловит объяснение, зачем его завели. */
function withoutComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' ')).replace(/\/\/[^\n]*/g, '')
}

function sourceFiles(): [string, string][] {
  const out: [string, string][] = []
  const walk = (dir: string) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name)
      if (e.isDirectory()) walk(p)
      else if (/\.tsx?$/.test(e.name) && !/\.test\./.test(e.name)) {
        out.push([path.relative(ROOT, p), fs.readFileSync(p, 'utf8')])
      }
    }
  }
  for (const dir of ['app', 'components']) walk(path.join(ROOT, dir))
  return out
}

describe('склонения при числах', () => {
  test('число и существительное рядом — только через plural()', () => {
    const offenders: string[] = []
    for (const [file, src] of sourceFiles()) {
      const lines = withoutComments(src).split('\n')
      lines.forEach((ln, i) => {
        if (ln.includes('plural(')) return
        COUNTED.lastIndex = 0
        let m: RegExpExecArray | null
        while ((m = COUNTED.exec(ln))) {
          offenders.push(`${file}:${i + 1} — «…${m[1]}»`)
        }
      })
    }
    expect(offenders, 'подставь plural(n, ...) из lib/plural').toEqual([])
  })

  /**
   * Сам сторож обязан ловить. Проверка ниже кормит ему ту самую строку, ради
   * которой он заведён: если однажды правило снова начнёт молчать (как это
   * было с \b), падение случится здесь, а не через полгода на чужом экране.
   */
  test('сторож ловит настоящее нарушение', () => {
    const bad = `<span className="font-mono">{games.length}</span> игр ·{' '}`
    COUNTED.lastIndex = 0
    expect(COUNTED.test(bad)).toBe(true)
  })

  /*
   * Вторая форма той же ошибки, которую правило выше поймать не может.
   *
   * В ленте стояло `{changes === 1 ? 'правка в патче' : 'правок в патче'}` —
   * существительное здесь не идёт следом за `}`, оно спрятано внутри строковых
   * литералов, и COUNTED про него ничего не знает. А неверно оно ровно там,
   * где русский требует третью форму: «33 правок» вместо «33 правки» жило в
   * проде.
   *
   * Веток две, а форм три — этого достаточно, чтобы утверждать ошибку, не
   * читая слов. Числовые тернарники (n === 1 ? 0 : …) под правило не попадают:
   * ищем именно пару строковых литералов с кириллицей.
   */
  const TWO_WAY = /(?:===|!==)\s*1\s*\?\s*'[^']*[а-яё][^']*'\s*:\s*'[^']*[а-яё][^']*'/i

  test('склонение не собирают тернарником из двух веток', () => {
    const offenders: string[] = []
    for (const [file, src] of sourceFiles()) {
      withoutComments(src)
        .split('\n')
        .forEach((ln, i) => {
          if (TWO_WAY.test(ln)) offenders.push(`${file}:${i + 1}`)
        })
    }
    expect(offenders, 'форм в русском три — возьми plural(n, ...) из lib/plural').toEqual([])
  })

  test('сторож двух веток ловит настоящее нарушение', () => {
    expect(TWO_WAY.test(`{changes === 1 ? 'правка в патче' : 'правок в патче'}`)).toBe(true)
    // Числовой выбор — не склонение, трогать его нечего.
    expect(TWO_WAY.test('const t = n === 1 ? 0 : (i / (n - 1)) * 2 - 1')).toBe(false)
  })

  test('год после числа — не счёт, и трогать его не надо', () => {
    const year = `<span className="font-mono">{wrapped.era.oldest.year}</span> года.`
    COUNTED.lastIndex = 0
    expect(COUNTED.test(year)).toBe(false)
  })
})
