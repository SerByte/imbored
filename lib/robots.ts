/**
 * Правила для краулеров — одно место на robots.txt и заголовки ответа.
 *
 * Модуль без Next и без базы: его читает next.config.ts ещё до сборки (как
 * lib/csp.ts), а app/robots.ts только раскладывает список в ответ.
 */

/**
 * Личные страницы: портрет, совместимость, комната. В поиске им не место —
 * портрет подставляет в заголовок настоящий ник Steam и строится по снапшоту
 * без всякой авторизации, — а в переписке место есть: ради пересылки у них и
 * нарисованы карточки.
 *
 * РАНЬШЕ ОНИ БЫЛИ ЗАКРЫТЫ В robots.txt, И ЭТО ЛОМАЛО ОБЕ ЗАДАЧИ СРАЗУ.
 *
 * Поиск: noindex работает, только если краулер страницу ОТКРЫЛ. Закрытую он
 * не читает, метатега не видит и по внешней ссылке может проиндексировать
 * голый адрес с чужим ником из текста ссылки («Indexed, though blocked by
 * robots.txt» в документации Google о noindex). То есть Disallow делал ровно
 * то, от чего должен был защищать.
 *
 * Превью: краулер X соблюдает robots.txt по спецификации Google, и картинку
 * под закрытым префиксом не берёт. og:image этих страниц лежит под тем же
 * префиксом (/portrait/<id>/opengraph-image, /room/<код>/opengraph-image), так
 * что ссылка на портрет или пати в X разворачивалась без карточки. В Telegram
 * и Discord превью при этом работали — поэтому поломку и не было видно.
 *
 * Теперь префиксы открыты, а из поиска их убирает заголовок X-Robots-Tag на
 * всём под префиксом: и на страницах (там noindex стоит ещё и метатегом), и
 * на PNG-карточках, которые метатега иметь не могут, — иначе они уехали бы в
 * поиск по картинкам. Заголовок не зависит от того, успел ли стриминг
 * метаданных дописать метатег в <head>.
 */
export const PERSONAL_PREFIXES = ['/portrait', '/compat', '/room', '/pick'] as const

/**
 * Открыты краулеру, но не выдаче: noindex заголовком X-Robots-Tag, ТОЧНЫМ
 * адресом.
 *
 * Обе — ссылки шапки, то есть стоят на каждой из шести тысяч страниц сайта.
 * Пока они были в Disallow, это работало против цели по той же механике,
 * что у личных страниц выше: закрытый адрес с такой перелинковкой Google
 * индексирует голым, по тексту ссылки, а noindex не видит.
 *
 *   • /daily гостю — заглушка: 249 символов видимого текста, содержательного
 *     «Изучаю твою библиотеку…» (замер на деплое без куки). Игра дня
 *     считается по личной библиотеке, искать тут нечего.
 *   • /rooms — объяснение пати и доска открытых комнат. Доска приезжает из
 *     /api (он закрыт), так что краулер видит объяснение и пустую доску, а
 *     показывать в выдаче чужие живые комнаты незачем и тем более.
 *
 * Бюджет обхода это не ест: обе — один адрес, без вариантов в серверной
 * разметке. Заголовком, а не метатегом — по той же причине, что у личных:
 * он не зависит от того, успел ли стриминг метаданных дописать <head>.
 */
export const NOINDEX_PAGES = ['/daily', '/rooms'] as const

/**
 * Секретные адреса: личная RSS-лента по ключу (app/whatsnew/feed/[token]).
 *
 * Отдельно от PERSONAL_PREFIXES, потому что обещание другое. Личные страницы
 * сделаны, чтобы их пересылали, — у них карточки для превью. Секретная
 * лента — чтобы её НЕ пересылали: адрес и есть пропуск к ленте патчей твоих
 * игр. Ссылок на неё нет нигде, но утечь адрес может, и тогда выдаче
 * нельзя показывать ни ленту, ни голый адрес с ключом.
 *
 * Механика та же, что у личных: в robots.txt открыто, noindex — заголовком
 * на всём под префиксом. Disallow был бы хуже ровно здесь: закрытый адрес
 * Google индексирует голым, по тексту внешней ссылки, — вместе с ключом.
 * Роут ставит тот же заголовок и сам, на ленте и на отказе.
 *
 * Правило /whatsnew/feed/:path* не задевает /whatsnew/feed.xml — общая
 * лента в соседнем сегменте и остаётся в выдаче (lib/robots.test.ts).
 */
export const SECRET_PREFIXES = ['/whatsnew/feed'] as const

/**
 * Что закрыто в robots.txt.
 *
 *   • /api/ — работа, а не контент. /api/prepare и /api/recommend вдобавок
 *     дёргают Steam и платную модель.
 *   • /play, /explore, /library — состояние сессии, а не страница. /play —
 *     экран ожидания со строкой настроения в адресе (?time=…&vibe=…):
 *     вариантов столько, сколько настроений, и каждый — та же заглушка, то
 *     есть открыть его значило бы скормить краулеру бюджет обхода впустую.
 *     /explore — тоже заглушка без куки. Ни один из двух не стоит в шапке.
 *     /library в шапке стоит (как и хаб /compat ниже), но гостю там отвечает
 *     не страница, а настоящий 307 на лендинг (proxy.ts): noindex показать
 *     негде. Для этих двух Disallow — прежнее решение, этой правкой не
 *     пересмотренное.
 *   • Хабы /portrait и /compat — ТОЧНЫМ адресом, через $: правило держит сам
 *     хаб (гостя proxy.ts разворачивает на лендинг, индексировать нечего) и не
 *     задевает личные страницы под ним. Раньше здесь стояли /portrait и
 *     /compat без слэша — они накрывали и хаб, и всё под ним; хаб закрыт
 *     по-прежнему, а личные страницы открыты ради noindex и карточек (см.
 *     PERSONAL_PREFIXES). $ понимают Google, Яндекс, Bing и краулер X.
 *
 * /quiz, /daily и /rooms ЗДЕСЬ БЫЛИ, с тем же доводом «без куки выбрасывают
 * на лендинг». Для /quiz он давно неправда: гость видит первый вопрос
 * целиком, с вариантами и пресетами (539 символов, коммит 5ea6ad8), и именно
 * туда ведут гостя карточка игры, страницы жанров и /pick — «квиз работает
 * обоим». А ссылка на него — самая частая на сайте: шапка, нижняя панель и
 * единственная кнопка в продукт на каждой карточке игры. Закрытый, он
 * попадал в выдачу голым адресом без заголовка и сниппета. Теперь он открыт
 * и идёт в выдачу со своим canonical (app/quiz/layout.tsx) и в карте сайта;
 * /daily и /rooms открыты, но с noindex — см. NOINDEX_PAGES.
 *
 * /room/new ЗДЕСЬ ТОЖЕ БЫЛ — «кнопка „создать комнату“ адресом, в шапке не
 * стоит». Довод кончился с «Позвать в эту игру»: карточка каждой сетевой игры
 * (seedable в lib/roomseed) ставит /room/new?game=<appid> обычной ссылкой, и
 * так же /pick, /compat и подборки про компанию /games/coop и
 * /games/split-screen (HubFacet.party, до сорока таких ссылок на странице).
 * Это тысячи разных закрытых адресов, и каждый — со страницы из карты
 * сайта, то есть ровно механика /quiz: Search Console копит «Заблокировано
 * в robots.txt», часть уходит в «Проиндексировано, несмотря на блокировку»
 * и встаёт в выдачу голым /room/new?game=730 рядом с карточкой той же игры.
 * Теперь адрес открыт, а из поиска его убирает заголовок X-Robots-Tag
 * правила /room/:path* (PERSONAL_PREFIXES) — он накрывает и /room/new с
 * любой строкой запроса. Обход ничего не создаёт: комната
 * появляется от тапа по настроению, сам заход только рисует выбор.
 * Автосоздание по ?preset= бывает лишь у вернувшегося со входа — и всё равно
 * через POST в /api/, который закрыт. Цена — до нескольких тысяч обходов
 * статической заглушки из кэша CDN, без вызова функции.
 *
 * Открытыми остаются разделы с собственным содержанием: лендинг, /game/*,
 * /games, /whatsnew, /quiz и статические страницы.
 */
export const ROBOTS_DISALLOW = [
  '/api/',
  '/portrait$',
  '/compat$',
  '/play',
  '/explore',
  '/library',
] as const

/**
 * Заголовки для next.config.ts: noindex на всём под личными и секретными
 * префиксами и на открытых заглушках шапки (NOINDEX_PAGES).
 *
 * Источник /<префикс>/:path* в Next покрывает и сам префикс, и всё под ним,
 * но не соседей: /room/:path* не задевает /rooms. Заглушки — точным адресом,
 * без :path*. Это проверяет lib/robots.test.ts на сопоставителе самого Next.
 */
export function noindexHeaders(): Array<{
  source: string
  headers: Array<{ key: string; value: string }>
}> {
  const noindex = () => [{ key: 'X-Robots-Tag', value: 'noindex' }]
  return [
    ...[...PERSONAL_PREFIXES, ...SECRET_PREFIXES].map((prefix) => ({
      source: `${prefix}/:path*`,
      headers: noindex(),
    })),
    ...NOINDEX_PAGES.map((source) => ({ source, headers: noindex() })),
  ]
}
