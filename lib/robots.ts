/**
 * Правила для краулеров — одно место на robots.txt и заголовки ответа.
 *
 * Модуль без Next и без базы: его читает next.config.ts ещё до сборки (как
 * lib/csp.ts), а app/robots.ts только раскладывает список в ответ.
 */

/**
 * Личные страницы: портрет, совместимость, комната. В поиске им не место —
 * портрет подставляет в заголовок настоящий ник Steam и строится по снапшоту
 * без всякой авторизации, — а в переписке место есть: ради пересылки у них и
 * нарисованы карточки.
 *
 * РАНЬШЕ ОНИ БЫЛИ ЗАКРЫТЫ В robots.txt, И ЭТО ЛОМАЛО ОБЕ ЗАДАЧИ СРАЗУ.
 *
 * Поиск: noindex работает, только если краулер страницу ОТКРЫЛ. Закрытую он
 * не читает, метатега не видит и по внешней ссылке может проиндексировать
 * голый адрес с чужим ником из текста ссылки («Indexed, though blocked by
 * robots.txt» в документации Google о noindex). То есть Disallow делал ровно
 * то, от чего должен был защищать.
 *
 * Превью: краулер X соблюдает robots.txt по спецификации Google, и картинку
 * под закрытым префиксом не берёт. og:image этих страниц лежит под тем же
 * префиксом (/portrait/<id>/opengraph-image, /room/<код>/opengraph-image), так
 * что ссылка на портрет или пати в X разворачивалась без карточки. В Telegram
 * и Discord превью при этом работали — поэтому поломку и не было видно.
 *
 * Теперь префиксы открыты, а из поиска их убирает заголовок X-Robots-Tag на
 * всём под префиксом: и на страницах (там noindex стоит ещё и метатегом), и
 * на PNG-карточках, которые метатега иметь не могут, — иначе они уехали бы в
 * поиск по картинкам. Заголовок не зависит от того, успел ли стриминг
 * метаданных дописать метатег в <head>.
 */
export const PERSONAL_PREFIXES = ['/portrait', '/compat', '/room'] as const

/**
 * Что закрыто в robots.txt.
 *
 *   • /api/ — работа, а не контент. /api/prepare и /api/recommend вдобавок
 *     дёргают Steam и платную модель.
 *   • /play, /quiz, /library, /daily, /rooms, /room/new — состояние сессии, а
 *     не страница. Без куки они выбрасывают на лендинг, то есть краулер
 *     индексировал бы редирект. /daily на деплое без куки отдавал 249 символов
 *     видимого текста, содержательного — «Изучаю твою библиотеку…».
 *   • Хабы /portrait и /compat — ТОЧНЫМ адресом, через $: правило держит сам
 *     хаб (гостя proxy.ts разворачивает на лендинг, индексировать нечего) и не
 *     задевает личные страницы под ним. Раньше здесь стояли /portrait и
 *     /compat без слэша — они накрывали и хаб, и всё под ним; хаб закрыт
 *     по-прежнему, а личные страницы открыты ради noindex и карточек (см.
 *     PERSONAL_PREFIXES). $ понимают Google, Яндекс, Bing и краулер X.
 *
 * /rooms держится своей строкой, а не заодно с /room: правило /room снято, а
 * оно накрывало и /rooms — robots.txt сравнивает префиксы, а не сегменты.
 *
 * Открытыми остаются разделы с собственным содержанием: лендинг, /game/*,
 * /whatsnew и статические страницы.
 */
export const ROBOTS_DISALLOW = [
  '/api/',
  '/portrait$',
  '/compat$',
  '/room/new',
  '/rooms',
  '/play',
  '/quiz',
  '/library',
  '/daily',
] as const

/**
 * Заголовки для next.config.ts: noindex на всём под личными префиксами.
 *
 * Источник /<префикс>/:path* в Next покрывает и сам префикс, и всё под ним,
 * но не соседей: /room/:path* не задевает /rooms. Это проверяет
 * lib/robots.test.ts на сопоставителе самого Next.
 */
export function noindexHeaders(): Array<{
  source: string
  headers: Array<{ key: string; value: string }>
}> {
  return PERSONAL_PREFIXES.map((prefix) => ({
    source: `${prefix}/:path*`,
    headers: [{ key: 'X-Robots-Tag', value: 'noindex' }],
  }))
}
