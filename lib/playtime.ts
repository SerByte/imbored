import { createLocalStore } from './localstore'
import type { LibraryGame } from './types'

/**
 * СКРЫТОЕ В STEAM ВРЕМЯ ИГРЫ — ОДИН ПРИЗНАК НА ВЕСЬ ПРОДУКТ.
 *
 * В настройках приватности Steam есть отдельная галочка «Всегда скрывать общее
 * время игры». С ней GetOwnedGames отдаёт библиотеку целиком, но
 * playtime_forever у каждой игры — ноль. Ошибки нет, ответ выглядит как
 * настоящий, и продукт принимал ноль за факт: вкус выходил пустым (log1p(0) —
 * игра не весит ничего), вся библиотека становилась «ни разу не запускал», а
 * причина на главном экране говорила «ноль минут» про игру, где у человека
 * пятьсот часов.
 *
 * Считается здесь и только здесь — на лету из снимка, без флага в базе:
 * пересчитать дешевле, чем мигрировать и держать флаг в согласии со снимком, и
 * признак уходит сам, как только человек снимет галочку и библиотека обновится.
 * Модуль без серверных импортов: его читают и /play, и экран ожидания.
 *
 *   — от десяти игр: у библиотеки из трёх подаренных и ни разу не запущенных
 *     нули — правда, и назвать её «время скрыто» было бы новой неправдой.
 *     Порог не исключает ложного срабатывания совсем (десять игр без единого
 *     запуска бывают), поэтому тексты при признаке условные — «похоже, Steam
 *     скрывает»;
 *   — нулевые минуты за две недели не требуются: при нуле за всё время
 *     ненулевые две недели — само противоречие, и говорит оно о скрытом
 *     времени, а не против него.
 *
 * Демо-библиотека (lib/demo.ts) под признак не попадает — часы там есть, и
 * это держит тест рядом.
 */
export const HIDDEN_PLAYTIME_MIN_GAMES = 10

export function playtimeHidden(
  games: ReadonlyArray<Pick<LibraryGame, 'playtimeForever'>>,
): boolean {
  return games.length >= HIDDEN_PLAYTIME_MIN_GAMES && games.every((g) => !g.playtimeForever)
}

/**
 * То же правило по минутам по appid — в этой форме живут прежние снимки
 * (minutesByApp в lib/libdelta, getOlderSnapshotMinutes в lib/db). Снимок со
 * скрытым временем не годится в точку отсчёта: разница с ним приписала бы
 * «после» всё время человека, наигранное за жизнь.
 */
export function minutesHidden(minutes: ReadonlyMap<number, number>): boolean {
  if (minutes.size < HIDDEN_PLAYTIME_MIN_GAMES) return false
  for (const m of minutes.values()) if (m) return false
  return true
}

/**
 * Признак на устройстве — для того, что рисуется раньше ответа сервера:
 * пилюля «Ни разу не запускал» на /quiz и строка ожидания /play в этом
 * режиме. Нетронутого при скрытом времени не узнать, сервер отдаёт тогда всё
 * своё (applyFocus) — а подпись до ответа обещала бы «ни разу не запускал».
 *
 * Пишет /play: факты прогрева (свежий снимок) и каждая выдача
 * (Deal.playtimeHidden); гасит выход (components/SignOut). Это последнее, что
 * известно, а не правда о сейчас: ошибка стоит подписи на один заход, а что
 * отдать, решает сервер по снимку. Хранится только true — «не скрыто» и «не
 * знаем» подписи не различают.
 */
export const timeHiddenStore = createLocalStore('imbored.time-hidden', (raw) =>
  raw === true ? true : null,
)
