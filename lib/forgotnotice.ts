/**
 * Строка «всё удалено» над заголовком главной (components/landing/HeroNotice)
 * — одна на удаление, а не на адрес.
 *
 * Раньше «Удалить всё обо мне» (components/ForgetMe) уводило на /?forgot=1, и
 * строку зажигал адрес. А адрес живёт дольше удаления: он оставался в истории
 * и в подсказках адресной строки, и вернувшийся через месяц — уже снова
 * вошедший — читал «всё удалено, входы погашены» рядом со своим «С
 * возвращением», и так на каждой перезагрузке. Тот же адрес можно было и
 * прислать кому угодно.
 *
 * Теперь метку ставит само удаление — в sessionStorage этой вкладки, — а
 * главная забирает её один раз: прочитала и стёрла. Перезагрузка, история,
 * чужая ссылка её уже не найдут. Забранное помнится в памяти вкладки, пока
 * главная на экране: снимок useSyncExternalStore обязан отвечать одно и то
 * же, сколько React его ни спросит, — поэтому и стирать метку можно прямо в
 * снимке, первым же чтением.
 *
 * ОДИН ЗАХОД НА ГЛАВНУЮ, А НЕ ВЕСЬ ДОКУМЕНТ. Раньше забранное помнилось до
 * перезагрузки, и каждый следующий клиентский заход на главную той же
 * вкладки снова говорил «всё удалено»: гость, прошедший после удаления квиз,
 * вместо своего «Пара часов · Расслабиться · Один — запомнили» читал опять
 * «удалено», а демо-вход и «Выйти» после него — «входы погашены» про выход,
 * которого не было. Теперь заход кончается, когда главная отписалась
 * (subscribeForgot) и в тот же проход не подписалась снова, — и строка
 * гаснет. «Тот же проход» — микрозадача: StrictMode в разработке
 * отписывает и подписывает эффекты синхронно, в одном коммите, и
 * router.refresh() главную не размонтирует, — строка переживает и то, и
 * другое. Гасить её в уборке эффекта HeroNotice напрямую нельзя ровно
 * поэтому: двойной эффект StrictMode погасил бы её на первом же показе.
 *
 * Хранилище бросает в приватном режиме и при выключенных куках — тогда метка
 * живёт только в памяти вкладки. Этого хватает: переход на главную после
 * удаления клиентский (router.replace), и модуль тот же.
 */

const KEY = 'imbored.forgot'

/** undefined — метку ещё не забирали; дальше — что забрали */
let taken: boolean | undefined

/** Сколько главных слушают метку сейчас: ноль после отписки — заход кончился */
let subs = 0

/** Номер удаления в этой вкладке: уборка ушедшего захода не гасит новое */
let marks = 0

/** Удаление прошло: строку покажет ближайшая главная этой вкладки */
export function markForgot(): void {
  // Второе удаление в той же вкладке (вернулся, вошёл, удалил снова) —
  // новая метка, а не ответ, забранный в прошлый раз
  marks++
  taken = undefined
  try {
    sessionStorage.setItem(KEY, '1')
  } catch {
    taken = true
  }
}

/** Снимок для useSyncExternalStore: забрать метку — прочитать и стереть */
export function takeForgot(): boolean {
  if (taken === undefined) {
    let found = false
    try {
      found = sessionStorage.getItem(KEY) === '1'
      sessionStorage.removeItem(KEY)
    } catch {
      // хранилища нет — и метки в нём нет
    }
    taken = found
  }
  return taken
}

/** На сервере вкладки нет: разметка сервера обязана совпасть с гидратацией */
export function forgotServer(): boolean {
  return false
}

/**
 * Подписка главной. Метку меняет только удаление, а его на главной не нажать,
 * — уведомлять некого. Подписка нужна ради отписки: она и есть уход с
 * главной (см. шапку), после которого забранная строка гаснет.
 */
export function subscribeForgot(): () => void {
  subs++
  return () => {
    subs--
    const at = marks
    // Отписка и подписка в одном проходе (StrictMode, перемонтирование в том
    // же коммите) — не уход: к микрозадаче главная подписана снова
    queueMicrotask(() => {
      if (subs === 0 && marks === at) taken = false
    })
  }
}
