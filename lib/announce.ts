/**
 * Что /play говорит скринридеру.
 *
 * Выдача меняется целиком и без перезагрузки: «Не то — дальше», причина
 * пропуска, выбор из «Ещё вариантов», бан, пересборка по «Только моё». Глазу
 * это видно — герой уезжает, приезжает другой. Скринридеру не было сказано
 * ничего: замер показал ноль живых областей на всём экране после выдачи, а
 * заголовок сменился League of Legends → Deep Rock Galactic молча.
 *
 * Строки собраны здесь, а не в разметке, чтобы их можно было проверить без
 * браузера: одна на событие, и в каждой — название игры, ради которого она
 * и звучит.
 */

export type PlayEvent =
  /** Первая выдача после прогрева (в рулетке молчим — барабан скажет сам) */
  | { kind: 'reveal'; name: string }
  /** Возврат на /play: выдача с прошлого захода, без прогрева (lib/playcache.ts) */
  | { kind: 'restore'; name: string }
  /** «Не то — дальше», причина пропуска, «не зацепило» у игры на экране */
  | { kind: 'next'; name: string }
  /** Выбор из «Ещё вариантов», экран выгорания */
  | { kind: 'pick'; name: string }
  /** Переключатели «Любые игры / Только моё» и «хочется …» */
  | { kind: 'reshape'; name: string }
  /** «Как «X», но…»: выдача из соседей X */
  | { kind: 'seed'; name: string; seed: string }
  /** «Обновить выдачу» после догрева */
  | { kind: 'refresh'; name: string }
  /**
   * Бан или «Уже прошёл»: карточка ушла навсегда, на её месте следующая.
   *
   * next — только когда забаненная и была героем на виду. Бан ждёт сервера, и
   * за это время человек успевал выбрать другую карточку, открыть экран
   * выгорания или «Подобрать заново»: на экране тогда не она, и «Следующая
   * игра: …» назвала бы не то, что видно. Но и молчать там нельзя — бан
   * необратим, и что он записан, человек обязан услышать (докблок sendFeedback
   * в app/play/page.tsx). Без next строка говорит только это.
   */
  | { kind: 'ban'; name: string; done: boolean; next?: string }
  /** Появился ряд причин «Почему не то?» */
  | { kind: 'ask' }
  /**
   * Экран ошибки: выдача не собралась. Он подменяет экран ожидания целиком, и
   * говорившая там строка прогресса уходит вместе с ним — без этой строки отказ
   * рисовался молча. Заголовок и абзац вместе: одно «Библиотека не доехала»
   * не говорит, что с этим делать.
   */
  | { kind: 'fail'; title: string; text: string }

export function playLine(e: PlayEvent): string {
  switch (e.kind) {
    case 'reveal':
      return `Подобрал игру: «${e.name}»`
    case 'restore':
      return `Выдача с прошлого захода. На экране «${e.name}»`
    case 'next':
      return `Следующая игра: «${e.name}»`
    case 'pick':
      return `На экране «${e.name}»`
    case 'reshape':
      return `Выдача пересобрана. Первая игра: «${e.name}»`
    case 'seed':
      return `Похожие на «${e.seed}». Первая игра: «${e.name}»`
    case 'refresh':
      return `Выдача обновлена. Первая игра: «${e.name}»`
    case 'ban': {
      const gone = e.done ? `«${e.name}» отмечена пройденной` : `«${e.name}» больше не покажу`
      return e.next ? `${gone}. Следующая игра: «${e.next}»` : gone
    }
    case 'ask':
      return 'Почему не то? Выбери причину или пропусти'
    case 'fail':
      return `${e.title}. ${e.text}`
  }
}

/**
 * Строка для живой области, которая точно прозвучит.
 *
 * Живая область объявляет ИЗМЕНЕНИЕ текста. Та же строка второй раз подряд —
 * не изменение, и скринридер промолчит: у выдачи из одной карточки «Не то —
 * дальше» возвращает ту же игру, и «Следующая игра: «X»» звучала бы один раз
 * из двух. Неразрывный пробел в конце меняет узел, не меняя слов; следующий
 * повтор его снимает.
 */
export function freshLine(prev: string, next: string): string {
  return prev === next ? `${next} ` : next
}
