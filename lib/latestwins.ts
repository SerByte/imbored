/**
 * ОДИН ЗАПРОС НА КЛЮЧ ЗА РАЗ, ПОСЛЕДНЕЕ НАЖАТИЕ — ПОСЛЕДНИМ.
 *
 * «Твои вечера» (components/Evenings.tsx) меняют ответ на «как тебе?»
 * оптимистично, и два быстрых нажатия «Зацепило» → «Так себе» уходили двумя
 * POST разом. Ответ и «зашло» роут пишет одной пачкой (app/api/outcome), так
 * что между собой они согласны при любом порядке — но не с последним
 * нажатием. Запросы попадают на разные инстансы и доезжают как придётся:
 * база оставалась на «Зацепило» с лайком, экран показывал «Так себе», и
 * перезагрузка возвращала ответ, который человек уже сменил.
 *
 * Поэтому: пока запрос по ключу в пути, новое нажатие не шлётся, а ждёт за
 * ним, и ждёт только последнее — промежуточные никому не нужны. Удачный ответ
 * отпускает ждущего. Неудача очередь сбрасывает: экран откатится к принятому
 * сервером, и ждущее нажатие, уехавшее поверх отказа, было бы новой
 * рассинхронизацией — человек видит «не вышло» и нажмёт ещё раз.
 *
 * Кнопки на время полёта не гаснут: нажатие в пути — законное «нет, всё-таки
 * так», оно сразу видно (aria-pressed) и просто уезжает следом. Гасить
 * пришлось бы через aria-disabled (disabled ловит lib/disabledfocus.test.ts),
 * а погашенная кнопка съела бы именно последнее нажатие — то, ради которого
 * всё это.
 */
export function latestWins<R>(ok: (result: R) => boolean) {
  // Ключ есть — запрос по нему в пути; значение — ждущий за ним, null — никого
  const waiting = new Map<string, (() => Promise<R>) | null>()

  /**
   * null — по ключу уже летит запрос, этот встал за ним, и итог скажет тот
   * вызов, что начал полёт. Иначе — итог последнего отправленного: удачный,
   * только если удачны все, что ушли по очереди.
   */
  return async function run(key: string, send: () => Promise<R>): Promise<R | null> {
    if (waiting.has(key)) {
      waiting.set(key, send)
      return null
    }
    waiting.set(key, null)
    try {
      let result = await send()
      for (let next = waiting.get(key); next && ok(result); next = waiting.get(key)) {
        waiting.set(key, null)
        result = await next()
      }
      return result
    } finally {
      waiting.delete(key)
    }
  }
}
