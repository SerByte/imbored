/**
 * Кегль h1 героя по длине названия игры: /game/[appid] и /pick/[id].
 *
 * Оба героя набирали название display-lg при любой длине, а колонка у них
 * узкая — 556 px на карточке игры при 1440 (984 − 380 − зазор 48). Display-lg
 * там — 68 px, это 13–15 знаков в строке, и у длинных имён каталога h1 вырастал
 * в стену: замер на проде при 1440×900 — /game/3191050 (108 знаков) 8 строк и
 * 544 px, кнопка «Страница в Steam» на y=1063; /game/2348100 (83 знака)
 * 6 строк, кнопка на 875. Первый экран показывал одно название — без оценки,
 * цены и кнопок.
 *
 * ПОРОГ — ПЯТАЯ СТРОКА. Четыре строки display-lg (272 px) колонка ещё
 * выдерживает: на /game/730 с подставленным именем кнопка Steam стоит на 813
 * при четырёх, на 881 при пяти и на 949 при шести — то есть с пятой строки
 * она уходит за край 900. Прогон в настоящем h1 (1440, Manrope 800) всех
 * 5920 имён прода из индекса поиска — с русскими, у которых слова длиннее, —
 * и 6000 имён каталога: пятая строка в обоих впервые появляется у имени в 49
 * знаков, среди 45–48 их нет ни одной. Отсюда 48 — с запасом в знак до
 * первой.
 *
 * ДЛИННЫМ — display-md, «титул экрана», а не новая ступень между ними. Шкала
 * кеглей нарочно короткая (app/globals.css, @theme), и этот кегль уже держит
 * длинные заголовки: им набран h1 страницы патча. На нём те же имена
 * занимают при 1440 две-три строки, 108-знаковые — четыре-пять; на телефоне
 * 390 имена от 80 знаков — четыре-шесть строк вместо пяти-восьми.
 *
 * ВТОРОЙ ПОВОД ДЛЯ display-md — ОДНО ДЛИННОЕ СЛОВО, при любой длине имени.
 * Слово браузер сам не переносит, и в display-lg самые длинные шире
 * колонки: «TROUBLESHOOTER:» 611 px при 1440, «Gaokao.Love.100Days» 668, на
 * 360 они же — 359 и 393 при колонке 320. Запас колонки в em почти один на
 * обоих краях: на 360 display-lg стоит на нижней границе clamp, 40 px, и
 * колонка 320 — 8.0 em; на 1440 карточки игры 556 / 68 — 8.18 em, у /pick
 * колонка max-w-xl, 576 / 68 — 8.47. Строже всех телефон, и порог считается
 * по нему: слово шире LONG_WORD_EM — ступень ниже.
 *
 * Ширину слова оцениваем, а не считаем знаки. Знаки врут в обе стороны:
 * «BATTLEGROUNDS» — 13 заглавных и 322 px на 360 (за колонку), а
 * «S.T.A.L.K.E.R.» — 14 знаков, но на точках, и 237 px. Правило «слово от
 * 14 знаков» прошло бы мимо PUBG и без нужды уменьшило бы 26 имён, которым
 * display-lg впору: «NieR:Automata™», «Thronebreaker:», «Civilization®:».
 * Оценка — четыре класса знаков по замеру Manrope 800 с трекингом display-lg
 * (−0.045 em): узкие 0.16–0.40 → 0.3, широкие 0.69–0.94 → 0.85, прочие
 * строчные 0.44–0.62 → 0.55, заглавные, цифры и знаки 0.41–0.73 → 0.64. На
 * 229 латинских именах шире 6 em она недооценивает слово самое большее на
 * 0.42 em (медиана ошибки 0.17), отсюда порог 8.0 − 0.4 = 7.6. Прогон 6011
 * имён (каталог и база) через h1 с тем же шрифтом, кеглем и трекингом в
 * Chromium — «TROUBLESHOOTER:» там те же 611 px, что колонка на проде: из 11
 * имён короче 48 знаков, которые в display-lg шире колонки на 360 или на
 * 1440, ступень ниже получают все 11 и ещё три впритык (Microcivilization —
 * 297 из 320); в display-md при 1440 все помещаются с запасом (самое
 * широкое — 434 из 556).
 *
 * Где браузер переносит сам — там слово кончается: пробел, дефис перед
 * буквой («Counter-» и «Strike» — два слова, дефис остаётся с первым), любой
 * знак иероглифов и хангыля. Неразрывный пробел — не перенос: «Touhou Hero of
 * Ice Fairy» в каталоге набран через U+00A0 и в display-lg занимает 722 px
 * одним куском. Дефис перед знаком — тоже: «9-nine-:Episode» браузер рвёт
 * только после «9-», а «nine-:Episode» держит целиком.
 *
 * [overflow-wrap:anywhere] — последний рубеж, а не мера. Разрыв внутри слова
 * выключает слово из min-content, и колонка 1fr героя карточки перестаёт
 * под него расти: на 1440 «TROUBLESHOOTER:» в display-lg рвалось в
 * «TROUBLESHOOTE / R», хотя без разрыва колонка расступалась до 611 и
 * слово стояло целым. Теперь до разрыва доходит только то, что не влезло и
 * ступенью ниже: из всех имён — тот же «Touhou» на 360 (326 из 320), и
 * лучше перенос, чем h1 за краем экрана. /pick ставил его и раньше; правило
 * одно на оба героя.
 *
 * Считаются UTF-16-единицы (String.length), а не графемы: эмодзи в именах
 * каталога единичны, а порог — оценка строк, не точный счёт.
 */
export const LONG_TITLE_CHARS = 48

/**
 * Слово шире стольких em display-lg — ступень ниже. Запас колонки на 360 —
 * 8.0 em, недооценка до 0.42: см. докблок выше.
 */
export const LONG_WORD_EM = 7.6

/**
 * Места переноса: пробелы, дефис перед буквой (дефис остаётся с левым
 * куском) и знаки CJK — каждый сам себе место переноса, и куском их не
 * считаем. U+00A0 сюда нарочно не входит.
 */
const BREAKS =
  /[ \t\n\r\u3000]+|(?<=[-\u2010\u2013])(?=\p{L})|[\u2e80-\u9fff\uac00-\ud7af\uf900-\ufaff\uff00-\uffef]+/u

// Классы знаков Manrope 800 по замеру — значения и разбросы в докблоке выше
const NARROW = /[ijlfrtI.,:;'’!|\u00a0]/
const WIDE = /[mwMW%#@©МЖШЩЫЮмжшщыюф]/
const LOWER = /\p{Ll}/u

function glyphEm(c: string): number {
  if (NARROW.test(c)) return 0.3
  if (WIDE.test(c)) return 0.85
  if (LOWER.test(c)) return 0.55
  return 0.64
}

/** Оценка ширины самого длинного неразрывного куска имени, в em display-lg */
export function longestWordEm(name: string): number {
  let max = 0
  for (const word of name.split(BREAKS)) {
    let em = 0
    for (const c of word) em += glyphEm(c)
    if (em > max) max = em
  }
  return max
}

export function heroTitleClass(name: string): string {
  const long = name.length >= LONG_TITLE_CHARS || longestWordEm(name) >= LONG_WORD_EM
  return `font-display ${long ? 'text-display-md' : 'text-display-lg'} [overflow-wrap:anywhere]`
}
