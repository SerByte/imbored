/**
 * Кегль h1 героя по длине названия игры: /game/[appid] и /pick/[id].
 *
 * Оба героя набирали название display-lg при любой длине, а колонка у них
 * узкая — 572 px на карточке игры при 1440. Display-lg там — 68 px, это 13–15
 * знаков в строке, и у длинных имён каталога h1 вырастал в стену: замер на
 * проде при 1440×900 — /game/3191050 (108 знаков) 8 строк и 544 px, кнопка
 * «Страница в Steam» на y=1063; /game/2348100 (83 знака) 6 строк, кнопка на
 * 875. Первый экран показывал одно название — без оценки, цены и кнопок.
 *
 * ПОРОГ — ПЯТАЯ СТРОКА. Четыре строки display-lg (272 px) колонка ещё
 * выдерживает: на /game/730 с подставленным именем кнопка Steam стоит на 813
 * при четырёх, на 881 при пяти и на 949 при шести — то есть с пятой строки
 * она уходит за край 900. Прогон в настоящем h1 (1440, Manrope 800) всех
 * 5920 имён прода из индекса поиска — с русскими, у которых слова длиннее, —
 * и 6000 имён каталога: пятая строка в обоих впервые появляется у имени в 49
 * знаков, среди 45–48 их нет ни одной. Отсюда 48 — с запасом в знак до
 * первой.
 *
 * ДЛИННЫМ — display-md, «титул экрана», а не новая ступень между ними. Шкала
 * кеглей нарочно короткая (app/globals.css, @theme), и этот кегль уже держит
 * длинные заголовки: им набран h1 страницы патча. На нём те же имена
 * занимают при 1440 две-три строки, 108-знаковые — четыре-пять; на телефоне
 * 390 имена от 80 знаков — четыре-шесть строк вместо пяти-восьми.
 *
 * [overflow-wrap:anywhere] — не про длину, а про одно длинное СЛОВО: на 360
 * «(DRIFT/DRAG/RACING)», «Gaokao.Love.100Days» и «TROUBLESHOOTER:» в
 * display-lg шире колонки на 39–96 px, и без разрыва внутри слова h1 уезжал
 * за край экрана. /pick ставил его и раньше; теперь одно правило на оба героя.
 *
 * Считаются UTF-16-единицы (String.length), а не графемы: эмодзи в именах
 * каталога единичны, а порог — оценка строк, не точный счёт.
 */
export const LONG_TITLE_CHARS = 48

export function heroTitleClass(name: string): string {
  const size = name.length >= LONG_TITLE_CHARS ? 'text-display-md' : 'text-display-lg'
  return `font-display ${size} [overflow-wrap:anywhere]`
}
