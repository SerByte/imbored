/**
 * Русские куски английской строки, собранной сервером из данных, — для
 * withForeignRuns (lib/textlang).
 *
 * withForeignRuns ищет ники и названия в фразе дословно. Строки экрана
 * приглашения (inviteDoor в lib/roominvite) приходят в комнату готовыми, и
 * имён ростера в них дословно нет: ник обрезан до DOOR_NAME_MAX с
 * многоточием, а на /en пробелы внутри меток «Already here» неразрывные
 * (app/api/room/[id]/route.ts). Искать по именам нечего — поэтому куски
 * берутся из самой строки, как liveLineOn (lib/announce) берёт названия из
 * “…”.
 *
 * Кириллицы в английских шаблонах нет, так что кусок от русской буквы до
 * русской буквы — данные. Латинская буква его обрывает: слова шаблона
 * («and», «wants») в кусок не попадают, и «Вася, Петя and 2 more» даёт один
 * кусок «Вася, Петя» — запятая между двумя русскими никами русскому голосу
 * не мешает. Многоточие обрезки — с куском: это хвост ника. Латинская часть
 * смешанного ника («Вася_Pro») остаётся английской: каждая буква звучит
 * своим голосом.
 *
 * Буквы — те же, что у textlang: на русской странице withForeignRuns куски
 * отбрасывает сам, и строка остаётся строкой.
 */
export function cyrillicRuns(text: string): string[] {
  return text.match(/[А-Яа-яЁё](?:[^A-Za-z]*[А-Яа-яЁё])?…?/g) ?? []
}
