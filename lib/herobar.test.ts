import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'vitest'

/**
 * Сторож: первый экран не считает полосу нижней панели своей.
 *
 * На телефоне снизу висит fixed-панель навигации высотой 45 px. Она
 * непрозрачна и забирает нажатия себе. Первый экран центровал содержимое в
 * высоту, нижние 45 px которой закрыты, и на отскоке (`/?next=…`, когда сверху
 * появляется плашка обещания) в эту полосу попадали кнопки карточки.
 *
 * ЗАМЕРЕНО, шесть адресов назначения × две высоты экрана, признак ловушки —
 * часть кнопки видна НАД полосой, а её центр под полосой:
 *
 *   было  — 5 ловушек из 12; худшая: «Войти через Steam» на 375×667 с
 *           21 видимым пикселем, нажатие открывало «Пати»;
 *   стало — 1 из 12: «Попробовать демо» с 6 видимыми пикселями.
 *
 * Оставшийся случай честно того же класса. Убрать его сдвигом нельзя:
 * содержимое на 375×667 выше экрана, и что-нибудь всегда попадает в полосу —
 * первая попытка «подвинуть на 20 px» просто перенесла ловушку на соседнюю
 * кнопку, это тоже замерено.
 *
 * Сторож статический: проверяет, что правило есть и что высота панели в нём
 * учтена. Без него правило снимается одной строкой, а обратно замечается
 * только попаданием пальцем.
 */

const CSS = fs.readFileSync(path.join(__dirname, '..', 'app', 'globals.css'), 'utf8')

describe('первый экран и нижняя панель', () => {
  test('на телефоне первый экран резервирует высоту панели', () => {
    /*
     * Перебираются ВСЕ блоки @media с max-width, а не берётся первый: в
     * globals.css их много, и первая версия сторожа падала не потому, что
     * правило отсутствует, а потому что читала чужой блок.
     */
    const blocks: string[] = []
    for (const m of CSS.matchAll(/@media \(max-width: \d+px\)\s*\{/g)) {
      let depth = 1
      let i = m.index! + m[0].length
      while (i < CSS.length && depth > 0) {
        if (CSS[i] === '{') depth++
        else if (CSS[i] === '}') depth--
        i++
      }
      blocks.push(CSS.slice(m.index!, i))
    }
    const heroBlocks = blocks.filter((b) => /\.hero\s*\{/.test(b))
    expect(heroBlocks.length, 'мобильного правила для .hero нет вовсе').toBeGreaterThan(0)
    expect(
      // [\s\S]*? , а не [^)]* : значение — calc(clamp(...) + 52px), и запрет
      // на скобку обрывал совпадение на закрывающей скобке clamp. Сторож при
      // этом был красным на верной разметке — поймано сразу, но потерей минуты.
      heroBlocks.some((b) => /padding-bottom:\s*calc\([\s\S]*?\+\s*52px\)/.test(b)),
      'нижний отступ первого экрана обязан включать высоту панели: иначе кнопки карточки ' +
        'ложатся в полосу, где нажатие достаётся навигации',
    ).toBe(true)
  })

  /**
   * Обратная половина: панель и отступ обязаны совпадать по числу. Разъехались
   * бы — и полоса снова стала бы чужой, а тест выше остался бы зелёным.
   */
  test('число совпадает с отступом под панель в разметке', () => {
    const layout = fs.readFileSync(path.join(__dirname, '..', 'app', 'layout.tsx'), 'utf8')
    expect(layout, 'в разметке нет отступа под панель — сравнивать не с чем').toContain('52px')
  })
})
