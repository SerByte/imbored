/**
 * Демо-личность узнаётся по самому steamid — без базы, секрета и next/server.
 *
 * Правило жило в lib/server, рядом с тем, кто демо-личности выдаёт
 * (demoSteamId), и браузеру оттуда его не прочесть: lib/server тянет за собой
 * базу и next/headers. А браузеру оно понадобилось — подсказка о входе
 * (lib/sessionhint) сверяется с ответом touch, где steamid есть, а признака
 * демо нет: его touch считает только для карточки главной. Вторая копия
 * регулярки разъехалась бы с этой, и полоса демо (components/DemoBar)
 * назвала бы чужой библиотекой ту, с которой человек вошёл сам.
 *
 * lib/server реэкспортирует функцию, так что роуты по-прежнему берут всё
 * серверное из одного места. Формат и почему префикс безопасен — там же, над
 * реэкспортом.
 */

export const DEMO_PREFIX = '000'
const DEMO_ID_RE = /^000\d{14}$/

export function isDemoId(steamid: string): boolean {
  return DEMO_ID_RE.test(steamid)
}
