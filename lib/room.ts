import { hashString } from './daily'

/**
 * Общие типы комнаты для API-роутов и компонентов ожидания.
 *
 * Живут отдельно от lib/db.ts, потому что это форма ОТВЕТА, а не форма строки:
 * steamid наружу не уходит вовсе — в открытую комнату с доски «Пати»
 * подсаживаются незнакомые, и раздавать им SteamID64 всех присутствующих
 * незачем. Наружу идёт ключ с серверным секретом, стабильный в пределах
 * комнаты (lib/roomkey).
 */

/**
 * Потолок участников комнаты.
 *
 * Матч засчитывается, когда карту лайкнули ВСЕ участники, и с каждым новым
 * человеком шанс сойтись падает. Восемь — это большая компания в голосовом
 * чате, а не толпа с доски «Пати». Без потолка код комнаты, попавший в
 * открытый канал, превращал её в бесконечный ростер, где матча не будет
 * никогда. Свой участник, зашедший повторно, в потолок не упирается.
 */
export const ROOM_MAX_MEMBERS = 8

export type RoomMemberView = {
  /** стабильный ключ для React и удаления участника; memberKey, не сам steamid */
  id: string
  name: string
  me: boolean
  /** сколько карт отсвайпал */
  votes: number
  /** дошёл до конца колоды */
  done: boolean
}

/**
 * Дошёл ли участник до конца колоды: голосов не меньше, чем карт в ней.
 *
 * Одно определение на ростер (опрос комнаты, app/api/room/[id]) и на лидера
 * голосов (pickLeader в lib/roomlikes): лидер предлагается ровно тогда, когда
 * ростер показывает всех готовыми, и разъехаться этим двум «все отсвайпали»
 * нельзя — экран говорил бы «берём X?», пока в ростере кто-то ещё свайпает.
 *
 * deckSize === 0 — вырожденный случай (колода схлопнулась), и отмечать им
 * всех «готов» бессмысленно: никто ничего не свайпал. null — колоду ещё никто
 * не запрашивал.
 */
export function memberDone(votes: number, deckSize: number | null): boolean {
  return deckSize !== null && deckSize > 0 && votes >= deckSize
}

/**
 * Что за состояние ожидания перед нами.
 *
 * Три разных факта, которые прежде показывались одним и тем же текстом
 * «Ждём остальных» — притом что в двух случаях из трёх это была неправда.
 */
export type WaitingMode =
  /** в комнате только ты: матч требует минимум двоих, ждать буквально некого */
  | 'alone'
  /** ты закончил, кто-то ещё свайпает */
  | 'others'
  /** колоды не было вовсе — нечего было свайпать */
  | 'empty'

/**
 * «Ты один» побеждает пустую колоду намеренно: библиотеки участников и есть
 * сырьё для колоды, поэтому второй человек снимает разом и запрет на матч,
 * и пустоту. Предлагать «позови кого-нибудь» полезнее, чем разводить руками.
 *
 * myVotes отделяет «колоды не было» от «колода кончилась». Пустая колода — не
 * только стартовое состояние: она пересобирается при входе нового участника и
 * может схлопнуться в ноль (у новичка нет библиотеки — значит, нет и игр,
 * которые «есть у всех»). Без этой проверки человеку, отсвайпавшему десять
 * карт, показывалось «в ваших библиотеках не нашлось ничего» прямо над
 * ростером с его же «10 из 10».
 */
export function waitingMode(args: {
  memberCount: number
  deckTotal: number
  myVotes: number
}): WaitingMode {
  if (args.memberCount <= 1) return 'alone'
  return args.deckTotal === 0 && args.myVotes === 0 ? 'empty' : 'others'
}

/**
 * Как назвать участника, у которого нет persona_name.
 *
 * Шапка этого файла объявляет инвариант: «steamid наружу не уходит вовсе». Он
 * нарушался ровно здесь — запасное имя строилось как `Игрок ${steamid.slice(-4)}`
 * и раздавалось всем в комнате, а через доску «Пати» и вовсе анонимам. То есть
 * идентификатор, ради сокрытия которого строкой выше считается хеш, уезжал
 * наружу четырьмя младшими цифрами в поле рядом.
 *
 * Пусто persona_name бывает штатно: первый вход до того, как приедет профиль
 * Steam, осечка Steam Web API, вход по вставленной ссылке.
 *
 * Метка — четыре знака хеша от (код комнаты + steamid): стабильна в пределах
 * комнаты, различает участников и ничего о них не говорит. Соль — код комнаты,
 * поэтому один человек в двух комнатах получает разные метки.
 *
 * Хеш здесь без секрета, в отличие от id в ростере (lib/roomkey), и этого
 * хватает: четыре знака base36 — около 21 бита из 32, на одну метку
 * приходятся сотни настоящих аккаунтов, так что steamid по ней не восстановить.
 * Полный хеш был бы другим делом — его перебор и обращал id в steamid.
 * Секрет сюда не тянется потому, что метку строит и lib/db (доска «Пати»),
 * которому lib/server не импортировать.
 */
export function memberLabel(
  roomId: string,
  steamid: string,
  personaName: string | null | undefined,
): string {
  if (personaName) return personaName
  return `Игрок ${hashString(roomId + steamid).toString(36).slice(0, 4)}`
}

const ROOM_CODE_RE = /^[A-Z0-9]{6}$/

/**
 * Код комнаты из того, что человек ввёл руками, либо null.
 *
 * Код предлагают диктовать: кнопка копирования при отказе буфера так и
 * пишет — «продиктуй код», а экран «ты тут один» делает его героем. Вводить
 * же его было негде: ?join= принимался только из адреса, а в установленном
 * приложении адресной строки нет вовсе.
 *
 * Надиктованное приходит как угодно: «fcp k8g», «FCP-K8G», с пробелом в
 * конце от клавиатуры телефона. Регистр, пробелы и дефисы — не часть кода.
 * Прилетевшую целиком ссылку тоже принимаем: её вставляют в первое же поле,
 * которое видят. Формат тот же, что у роутов комнаты, — иначе форма пускала
 * бы туда, где API ответит 404 на сам адрес.
 */
export function parseRoomCode(raw: string): string | null {
  const link = /\/room\/([^/?#\s]+)/i.exec(raw)
  const code = (link ? link[1] : raw).replace(/[\s-]/g, '').toUpperCase()
  return ROOM_CODE_RE.test(code) ? code : null
}

/**
 * Строка под ростером: чего ждать дальше. null — обещать нечего.
 *
 * Ростер всегда печатал «Матч появится сам — обновлять не надо», в том числе
 * под заголовком «Все отсвайпали — и ни разу не совпали». Люди ждали, хотя
 * матч без новых карт невозможен: голоса всех уже записаны и не сошлись.
 * AloneInvite когда-то назвал ту же фразу враньём для комнаты на одного —
 * здесь то же враньё, только для комнаты, где все закончили.
 *
 * swiping — сколько участников ещё не дошли до конца колоды, включая себя:
 * свой голос может быть ещё в пути, и тогда матч и правда появится сам.
 * hasMore — есть ли кнопка «Ещё 20 игр»; без неё совет взять ещё — тупик.
 */
export function rosterHint(args: { swiping: number; hasMore: boolean }): string | null {
  if (args.swiping > 0) return 'Матч появится сам — обновлять не надо.'
  if (args.hasMore) return 'Совпадения нет — возьмите ещё игр кнопкой ниже.'
  return null
}

/**
 * Что комната говорит скринридеру, когда сошлась. null — сказать нечего.
 *
 * Матч приезжает опросом, а не нажатием: чужой последний голос, «Берём» у
 * другого участника. Церемония подменяет страницу целиком — кнопки колоды
 * уходят, фокус падает в body, — и тот, кто не смотрит на экран, о главном
 * событии продукта не узнавал ничего. Строка стоит на уровне страницы, а не
 * в церемонии: там она родилась бы вместе с текстом, а такую область
 * скринридер объявляет не везде (components/StatusLine).
 *
 * sawOpen — комната была открыта на глазах у этого экрана. Открыл ссылку на
 * уже сошедшуюся комнату — новости нет: церемония и есть страница, её читают
 * как страницу. Условия на комнату — те же, при которых рисуется церемония:
 * только своим и только с игрой.
 */
export function matchLine(args: {
  sawOpen: boolean
  status: 'open' | 'matched'
  isMember: boolean
  game: { name: string } | null
}): string | null {
  if (!args.sawOpen || args.status !== 'matched' || !args.isMember || !args.game) return null
  return `Матч: «${args.game.name}»`
}

/**
 * Матч взят лидером голосов, а не единогласием (app/api/room/[id]/leader):
 * за игру не все. «Это матч!» и «все хотят одного и того же» тогда неправда —
 * и церемония (components/MatchCeremony), и её запасной экран
 * (components/room/CeremonyBoundary) говорят «Договорились» и честный счёт.
 * Одно правило на оба экрана: запасной показывается ровно тогда, когда
 * церемония не пришла, и разъехаться в заголовке им нельзя.
 *
 * forCount null — счёта нет (смотрит не участник): единогласия не утверждаем
 * и не отрицаем, остаётся обычный матч.
 */
export function matchByLeader(forCount: number | null | undefined, memberCount: number): boolean {
  return forCount !== null && forCount !== undefined && forCount < memberCount
}

/**
 * Отказ кнопки комнаты — «Выйти из пати», ✕ хоста или переключателя доски —
 * вместе с тем, при чём он случился.
 */
export type RoomMiss = {
  text: string
  /** ключ колоды «состав:раунд» в минуту отказа (deckKeyOf в app/room/[id]) */
  deck: string
  /** ✕ хоста: кого убирали */
  memberId?: string
  /** доска: какой была комната, когда нажимали */
  wasPublic?: boolean
}

/**
 * Строка отказа, пока она ещё правда; null — гаснет.
 *
 * Отказ гас только со следующей попыткой, и строка переживала то, о чём
 * говорила. «Убрать из пати не получилось — нажми ✕ ещё раз» оставалась, когда
 * того участника уже нет: ушёл сам, или POST прошёл, а ответ потерялся, —
 * строка звала нажать ✕, которой на экране нет. «Доска не переключилась»
 * стояла под переключателем, который опрос уже показал переключённым.
 *
 * И отказ живёт один экран ожидания, а не всё лобби: строки стоят внутри
 * RoomWaiting и AloneInvite, а те уходят с новым раундом или новым гостем и
 * возвращаются, когда колода снова кончится. Монтировались они тогда сразу со
 * старым текстом — видимым и непроизнесённым (components/StatusLine). Новый
 * раунд и новый гость сдвигают ключ колоды, и строка гаснет вместе с ним.
 *
 * Выводится на рендере, а не стирается эффектом: опрос, сменивший ростер или
 * доску, гасит строку тем же кадром.
 */
export function roomMissText(
  miss: RoomMiss | null,
  now: { deck: string; members: Array<{ id: string }>; isPublic: boolean },
): string | null {
  if (!miss || miss.deck !== now.deck) return null
  if (miss.memberId !== undefined && !now.members.some((m) => m.id === miss.memberId)) return null
  if (miss.wasPublic !== undefined && miss.wasPublic !== now.isPublic) return null
  return miss.text
}

/**
 * Есть ли ждущему что узнать из фона — условие фонового опроса комнаты
 * (hiddenPollDelay в lib/roompoll): своя колода кончилась (waiting — загружена
 * и пуста) и режим ожидания 'others'.
 *
 * Шире, чем awaitingOthers, намеренно. Когда отсвайпали все и не сошлись,
 * «ждём остальных» было бы неправдой, но матч прийти ещё может: лидера голосов
 * берёт любой участник, и «Берём» соседа сводит комнату без этого человека.
 * А вот 'alone' и 'empty' фону ничего не принесут: в комнате на одного матча
 * нет, при пустой колоде — не из чего, и час запросов раз в минуту там был бы
 * платой ни за что.
 *
 * И не тогда, когда колода на руках отстала от комнаты (deckBehind): сосед
 * поднял раунд, сервер уже раздал больше карт (deckSize), а своя колода
 * этого раунда ещё не догружена — скрытая вкладка её не грузит (app/room/[id],
 * эффект колоды). Пусто на руках тогда не потому, что всё отсвайпано, а
 * потому, что новые карты ждут возвращения на вкладку: человеку есть что
 * свайпать, и ни «ждём остальных», ни минутный фоновый опрос ему не положены.
 * Иначе двое ждущих в скрытых вкладках видели бы друг друга «ещё свайпает» —
 * и оба висели бы на «ждём остальных».
 */
export function waitsInBackground(args: {
  waiting: boolean
  memberCount: number
  deckTotal: number
  myVotes: number
  /** rooms.deck_size из опроса; null — колоду ещё никто не запрашивал */
  deckSize?: number | null
}): boolean {
  return args.waiting && waitingMode(args) === 'others' && !deckBehind(args)
}

/**
 * Отстала ли загруженная колода от комнаты: сервер раздал больше карт
 * (deckSize — последняя выданная колода, её же считает memberDone), чем
 * пришло на руки (deckTotal), и сам человек до конца серверной колоды не
 * дошёл. Последнее отделяет «новые карты ждут загрузки» от расхождений, где
 * свайпать уже нечего.
 *
 * Не путать с deckStuck (lib/deckvote): там колода на руках актуальна, а голос
 * потерялся — сразу после последнего свайпа, пока опрос не принёс done, это
 * штатное состояние, и фоновый опрос ровно его и лечит. Здесь же deckTotal
 * отстаёт, пока колоду не перечитали.
 */
export function deckBehind(args: { deckTotal: number; myVotes: number; deckSize?: number | null }): boolean {
  const size = args.deckSize ?? null
  return size !== null && args.deckTotal < size && !memberDone(args.myVotes, size)
}

/**
 * Ждёт ли человек ДРУГИХ: своя колода кончилась (waiting — загружена и пуста),
 * режим ожидания 'others', и хоть кто-то, кроме него, ещё свайпает. Ровно то
 * состояние, в котором экран говорит «Колода пройдена — ждём ещё…», и только
 * в нём заголовок вкладки говорит «Ждём остальных» (roomTabTitle).
 *
 * othersSwiping — участники, кроме себя, не дошедшие до конца колоды (pending
 * в components/room/RoomWaiting).
 */
export function awaitingOthers(args: {
  waiting: boolean
  memberCount: number
  deckTotal: number
  myVotes: number
  othersSwiping: number
}): boolean {
  return waitsInBackground(args) && args.othersSwiping > 0
}

/**
 * Заголовок вкладки комнаты. null — заголовок не трогаем, стоит серверный
 * (generateMetadata в app/room/[id]/layout.tsx).
 *
 * Сценарий один: человек отсвайпал своё и ушёл в соседнюю вкладку, а пати
 * досвайпывает без него. Полоса вкладок — всё, что он при этом видит от
 * комнаты, и сказать она обязана ровно две вещи: «ты ждёшь» и «дождался».
 *
 * Только два состояния, и это решение, а не недоделка. Прогресс на каждый
 * голос дёргал бы заголовок каждые пару секунд — шум, который приучает не
 * смотреть. «Берём X?» в заголовке — подталкивание к решению из фона, а решают
 * в комнате, глядя на ростер.
 *
 *   «Ждём остальных · Пати ABC123» — своя колода кончилась, а кто-то ещё
 *     свайпает (awaitingOthers). Только так: эту же фразу страница уже
 *     однажды убрала, потому что в двух режимах ожидания из трёх она врала
 *     (WaitingMode), и полоса вкладок не должна вернуть её туда. В комнате на
 *     одного ждать некого, при пустой колоде — нечего, а когда отсвайпали все
 *     и не сошлись, решение («Берём», «Ещё 20 игр») за самими людьми — у
 *     каждого висело бы «ждём остальных», и все ждали бы друг друга;
 *   «● Сошлись: X» — матч пришёл на глазах у этого экрана (sawOpen, как у
 *     matchLine), а вкладку с тех пор не открывали. Точка — метка
 *     непрочитанного: вернулся — она снимается, остаётся «Сошлись: X».
 *
 * Не участнику — null: приглашение называется так, как назвал его сервер, а
 * чужой матч — не его новость. Открыл ссылку на уже сошедшуюся комнату — тоже
 * null: новости нет, церемония и есть страница.
 */
export function roomTabTitle(args: {
  roomId: string
  status: 'open' | 'matched'
  isMember: boolean
  /** ждёт ли человек других — awaitingOthers */
  awaiting: boolean
  sawOpen: boolean
  /** матч пришёл, пока вкладка была скрыта, и её с тех пор не открывали */
  unseen: boolean
  matchedName: string | null
}): string | null {
  if (!args.isMember) return null
  if (args.status === 'matched') {
    if (!args.sawOpen || !args.matchedName) return null
    return `${args.unseen ? '● ' : ''}Сошлись: ${args.matchedName}`
  }
  if (args.awaiting) return `Ждём остальных · Пати ${args.roomId}`
  return null
}

/**
 * Работает ли здесь уведомление со страницы — new Notification() без
 * сервис-воркера (его нет и не будет, см. app/manifest.ts).
 *
 * Наличия window.Notification мало, и в этом главный подвох. В Chrome на
 * Android оно определено, разрешение спрашивается и выдаётся — а конструктор
 * бросает TypeError и требует ServiceWorkerRegistration.showNotification. На
 * iOS уведомления бывают только у установленного PWA через push. На телефоне
 * переключатель выпросил бы разрешение и молча не сработал — обещание,
 * которое мы не выполним. Поэтому телефоны исключаются явно: по
 * userAgentData.mobile там, где он есть (Chromium), и по грубому указателю
 * (pointer: coarse) везде — это палец, а не мышь. Планшет отсеется тоже:
 * лучше не показать работающее, чем показать неработающее.
 */
export function pageNotices(args: {
  hasNotification: boolean
  /** navigator.userAgentData?.mobile; undefined — браузер не сообщает */
  uaMobile: boolean | undefined
  coarsePointer: boolean
}): boolean {
  return args.hasNotification && args.uaMobile !== true && !args.coarsePointer
}

/**
 * Показать ли уведомление о матче. «Одно на комнату» держит вызывающий.
 *
 * Только из скрытой вкладки: видимую уже заняли церемония и строка
 * matchStatus, второй сигнал поверх — шум. И только чужой матч: свой последний
 * голос или своё «Берём» человек сделал сам, и сообщать ему о его же нажатии
 * незачем (selfCaused в app/room/[id]/page).
 */
export function matchNoticeDue(args: {
  /** переключатель «Сообщить, когда сойдёмся» включён на этом устройстве */
  enabled: boolean
  permission: NotificationPermission
  visible: boolean
  selfCaused: boolean
}): boolean {
  return args.enabled && args.permission === 'granted' && !args.visible && !args.selfCaused
}
