import { hashString } from './daily'

/**
 * Общие типы комнаты для API-роутов и компонентов ожидания.
 *
 * Живут отдельно от lib/db.ts, потому что это форма ОТВЕТА, а не форма строки:
 * steamid наружу не уходит вовсе — в открытую комнату с доски «Пати»
 * подсаживаются незнакомые, и раздавать им SteamID64 всех присутствующих
 * незачем. Наружу идёт ключ с серверным секретом, стабильный в пределах
 * комнаты (lib/roomkey).
 */

export type RoomMemberView = {
  /** стабильный ключ для React и удаления участника; memberKey, не сам steamid */
  id: string
  name: string
  me: boolean
  /** сколько карт отсвайпал */
  votes: number
  /** дошёл до конца колоды */
  done: boolean
}

/**
 * Дошёл ли участник до конца колоды: голосов не меньше, чем карт в ней.
 *
 * Одно определение на ростер (опрос комнаты, app/api/room/[id]) и на лидера
 * голосов (pickLeader в lib/roomlikes): лидер предлагается ровно тогда, когда
 * ростер показывает всех готовыми, и разъехаться этим двум «все отсвайпали»
 * нельзя — экран говорил бы «берём X?», пока в ростере кто-то ещё свайпает.
 *
 * deckSize === 0 — вырожденный случай (колода схлопнулась), и отмечать им
 * всех «готов» бессмысленно: никто ничего не свайпал. null — колоду ещё никто
 * не запрашивал.
 */
export function memberDone(votes: number, deckSize: number | null): boolean {
  return deckSize !== null && deckSize > 0 && votes >= deckSize
}

/**
 * Что за состояние ожидания перед нами.
 *
 * Три разных факта, которые прежде показывались одним и тем же текстом
 * «Ждём остальных» — притом что в двух случаях из трёх это была неправда.
 */
export type WaitingMode =
  /** в комнате только ты: матч требует минимум двоих, ждать буквально некого */
  | 'alone'
  /** ты закончил, кто-то ещё свайпает */
  | 'others'
  /** колоды не было вовсе — нечего было свайпать */
  | 'empty'

/**
 * «Ты один» побеждает пустую колоду намеренно: библиотеки участников и есть
 * сырьё для колоды, поэтому второй человек снимает разом и запрет на матч,
 * и пустоту. Предлагать «позови кого-нибудь» полезнее, чем разводить руками.
 *
 * myVotes отделяет «колоды не было» от «колода кончилась». Пустая колода — не
 * только стартовое состояние: она пересобирается при входе нового участника и
 * может схлопнуться в ноль (у новичка нет библиотеки — значит, нет и игр,
 * которые «есть у всех»). Без этой проверки человеку, отсвайпавшему десять
 * карт, показывалось «в ваших библиотеках не нашлось ничего» прямо над
 * ростером с его же «10 из 10».
 */
export function waitingMode(args: {
  memberCount: number
  deckTotal: number
  myVotes: number
}): WaitingMode {
  if (args.memberCount <= 1) return 'alone'
  return args.deckTotal === 0 && args.myVotes === 0 ? 'empty' : 'others'
}

/**
 * Как назвать участника, у которого нет persona_name.
 *
 * Шапка этого файла объявляет инвариант: «steamid наружу не уходит вовсе». Он
 * нарушался ровно здесь — запасное имя строилось как `Игрок ${steamid.slice(-4)}`
 * и раздавалось всем в комнате, а через доску «Пати» и вовсе анонимам. То есть
 * идентификатор, ради сокрытия которого строкой выше считается хеш, уезжал
 * наружу четырьмя младшими цифрами в поле рядом.
 *
 * Пусто persona_name бывает штатно: первый вход до того, как приедет профиль
 * Steam, осечка Steam Web API, вход по вставленной ссылке.
 *
 * Метка — четыре знака хеша от (код комнаты + steamid): стабильна в пределах
 * комнаты, различает участников и ничего о них не говорит. Соль — код комнаты,
 * поэтому один человек в двух комнатах получает разные метки.
 *
 * Хеш здесь без секрета, в отличие от id в ростере (lib/roomkey), и этого
 * хватает: четыре знака base36 — около 21 бита из 32, на одну метку
 * приходятся сотни настоящих аккаунтов, так что steamid по ней не восстановить.
 * Полный хеш был бы другим делом — его перебор и обращал id в steamid.
 * Секрет сюда не тянется потому, что метку строит и lib/db (доска «Пати»),
 * которому lib/server не импортировать.
 */
export function memberLabel(
  roomId: string,
  steamid: string,
  personaName: string | null | undefined,
): string {
  if (personaName) return personaName
  return `Игрок ${hashString(roomId + steamid).toString(36).slice(0, 4)}`
}

const ROOM_CODE_RE = /^[A-Z0-9]{6}$/

/**
 * Код комнаты из того, что человек ввёл руками, либо null.
 *
 * Код предлагают диктовать: кнопка копирования при отказе буфера так и
 * пишет — «продиктуй код», а экран «ты тут один» делает его героем. Вводить
 * же его было негде: ?join= принимался только из адреса, а в установленном
 * приложении адресной строки нет вовсе.
 *
 * Надиктованное приходит как угодно: «fcp k8g», «FCP-K8G», с пробелом в
 * конце от клавиатуры телефона. Регистр, пробелы и дефисы — не часть кода.
 * Прилетевшую целиком ссылку тоже принимаем: её вставляют в первое же поле,
 * которое видят. Формат тот же, что у роутов комнаты, — иначе форма пускала
 * бы туда, где API ответит 404 на сам адрес.
 */
export function parseRoomCode(raw: string): string | null {
  const link = /\/room\/([^/?#\s]+)/i.exec(raw)
  const code = (link ? link[1] : raw).replace(/[\s-]/g, '').toUpperCase()
  return ROOM_CODE_RE.test(code) ? code : null
}

/**
 * Строка под ростером: чего ждать дальше. null — обещать нечего.
 *
 * Ростер всегда печатал «Матч появится сам — обновлять не надо», в том числе
 * под заголовком «Все отсвайпали — и ни разу не совпали». Люди ждали, хотя
 * матч без новых карт невозможен: голоса всех уже записаны и не сошлись.
 * AloneInvite когда-то назвал ту же фразу враньём для комнаты на одного —
 * здесь то же враньё, только для комнаты, где все закончили.
 *
 * swiping — сколько участников ещё не дошли до конца колоды, включая себя:
 * свой голос может быть ещё в пути, и тогда матч и правда появится сам.
 * hasMore — есть ли кнопка «Ещё 20 игр»; без неё совет взять ещё — тупик.
 */
export function rosterHint(args: { swiping: number; hasMore: boolean }): string | null {
  if (args.swiping > 0) return 'Матч появится сам — обновлять не надо.'
  if (args.hasMore) return 'Совпадения нет — возьмите ещё игр кнопкой ниже.'
  return null
}
