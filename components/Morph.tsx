import { ViewTransition, type ReactNode } from 'react'

/**
 * ОБЩИЙ ЭЛЕМЕНТ ПЕРЕХОДА: обложка игры перелетает со страницы на страницу.
 *
 * Капсула на полке и обложка в герое страницы игры — одна и та же картинка
 * (header), и без перехода человек видит, как одна исчезает, а другая
 * появляется, — две вещи вместо одной. С общим именем React и браузер
 * (View Transitions) ведут её из клетки полки в слот героя: это продолжение
 * одного предмета, как у стриминга, когда постер раскрывается в страницу.
 *
 * share="morph" + default="none": пара морфится, а каждая обложка по
 * отдельности НЕ играет свой кроссфейд на любом другом переходе страницы.
 * Без share пара с default="none" молча перестаёт морфиться — см.
 * руководство Next (01-app/02-guides/view-transitions.md).
 *
 * Морф получается, когда страница назначения приходит одним коммитом — без
 * фолбэка Suspense между старой и новой. Над /game такой границы нет (ни
 * loading.tsx, ни Suspense): без префетча старая страница просто стоит, пока
 * не придёт ответ, и пара собирается так же, только после ожидания сервера.
 * Проверено в next dev, где префетча нет вовсе: «Похожие» → герой даёт
 * ::view-transition-group(game-…). Поэтому сетка «Похожие» живёт без
 * префетча (components/GameLink), а морф у неё остался. Появись у /game
 * loading.tsx — пара останется только у предзагруженных ссылок.
 * Браузер без поддержки View Transitions ничего не анимирует.
 */
export function GameMorph({ appid, children }: { appid: number; children: ReactNode }) {
  return (
    <ViewTransition name={`game-${appid}`} share="morph" default="none">
      {children}
    </ViewTransition>
  )
}
