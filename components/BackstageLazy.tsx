'use client'

import type { ComponentType } from 'react'
import { lazyIsland, reportIslandFailure } from '@/components/lazyIsland'
import { isChunkLoadError } from '@/lib/clienterr'

/**
 * Закулисье (components/Backstage) — отдельным чанком, в простое после
 * гидратации.
 *
 * ЗАЧЕМ. Всё, что статически стоит в корневом лэйауте, едет в первую загрузку
 * КАЖДОЙ страницы. Аналитика с Web Vitals — 6.7 КБ, продление входа с
 * подсказкой о входе и признаком записи — ещё 2.6, и ни то, ни другое не
 * рисует ни пикселя. А /room/[id] и /play стояли ровно на своих потолках
 * bundle-budget.json (650 из 650, 680 из 680): любые лишние полкилобайта в
 * общем фундаменте валили бюджет обоим. Что этим модулям не вернуться в
 * лэйаут, сторожит lib/sharedchunk.test.ts.
 *
 * В ПРОСТОЕ, а не сразу после гидратации: разбор чанка и вставка скриптов
 * аналитики не должны спорить с гидратацией и первым кадром за главный
 * поток. Без requestIdleCallback (Safari) — таймером, как у
 * components/SmoothScroll. Потолок ожидания — на занятой странице простоя
 * может не быть долго.
 *
 * ЧЕМ ПЛАТИМ — и это осознанно:
 *  - визит, закрытый раньше, чем закулисье приехало, не оставляет просмотра;
 *    обычно это доли секунды после гидратации, в худшем случае — потолок
 *    ниже и один круг до сервера за чанком;
 *  - кто успел уйти клиентским переходом до его прихода, засчитает просмотр
 *    той страницы, где оно его застало, а не первой;
 *  - Web Vitals приехавшего визита при этом не теряются: Speed Insights
 *    читает их буферами PerformanceObserver (buffered) — LCP, FCP, CLS и
 *    TTFB целиком, а из взаимодействий до его прихода — те, что браузер
 *    успел положить в буфер Event Timing (длинные, то есть важные для INP);
 *  - продление входа уходит на ту же долю секунды позже, и на столько же
 *    позже приходит признак записи (lib/writer). Кнопкам, которые видны и при
 *    «не знаем», это безвредно (почему — в components/SessionKeeper). Но
 *    часть кнопок ждёт признака спрятанной: «Запустить» и «Уже прошёл» на
 *    странице игры (components/OwnedLaunch, writer !== null), «Сыграю
 *    вечером на ПК» на /play и /daily (components/TonightButton, writer ===
 *    true), — они встают на простой и круг за чанком позже, чем вставали.
 *    Так же позже /room/new показывает сессии по ссылке «войди через Steam»
 *    до выбора настроения. «Сыграю вечером» на /daily и прежде вставала после
 *    ответа и сдвигала на телефоне строку «Хочу выбрать сам» под собой —
 *    теперь сдвигает позже;
 *  - отметка возврата (lib/retention) ставится тем же запросом продления:
 *    вернувшийся, который закрыл страницу раньше, чем закулисье приехало,
 *    возвратом в этот день не посчитан. Главная зовёт продление сама и
 *    считает всех.
 * Сами байты не исчезают — они уезжают из первого кадра за гидратацию.
 *
 * Островком (components/lazyIsland), а не next/dynamic: рантайм того —
 * ~4 КБ к первой загрузке, то есть почти половина выигрыша.
 *
 * ОТКАЗ ДОСТАВКИ — МОЛЧА, ОТКАЗ КОДА — В ОТЧЁТ. Островки продукта просят
 * чанк по намерению человека, а этот — на каждом документе: кусок, не
 * пришедший на моргнувшей сети или после деплоя, превращал бы в отчёт каждый
 * просмотр в это окно и топил бы в логе настоящие отказы, а чинить там
 * нечего. Но без закулисья человек теряет до перезагрузки и видимое — всё
 * выше, что ждёт признака записи, и прогрев квиза у вернувшегося из Steam, —
 * а мы — отметку возврата. Поэтому код, который доехал и упал при
 * вычислении модуля (Backstage, SessionKeeper, их lib, сами пакеты аналитики
 * после обновления), молчать не может: такая поломка повторяется у каждого
 * с тем же браузером, а до переезда сюда её ловил instrumentation-client —
 * она стояла в чанке лэйаута. Одно от другого отличает isChunkLoadError
 * (lib/clienterr); отчёт — тем же путём и с тегом островка
 * (reportIslandFailure), повторы гасит отсечка lib/clienterr. В обоих
 * случаях загрузчик ловит отказ сам и отдаёт пустой компонент (тот же
 * приём, что у components/TonightLazy): страница цела, а сам островок
 * отказа не видит и второй раз о нём не отчитывается.
 */

/** Сколько ждать простоя браузера, прежде чем грузить всё равно */
const IDLE_TIMEOUT_MS = 2000

function idle(): Promise<void> {
  return new Promise((done) => {
    if (typeof window.requestIdleCallback === 'function') {
      window.requestIdleCallback(() => done(), { timeout: IDLE_TIMEOUT_MS })
    } else {
      window.setTimeout(done, 200)
    }
  })
}

/** Чанк не пришёл или упал: закулисья нет до перезагрузки, а страница цела */
function NoBackstage() {
  return null
}

const loadBackstage = (): Promise<ComponentType<object>> =>
  idle()
    .then(() => import('./Backstage'))
    .then(
      (m) => m.Backstage,
      (err: unknown) => {
        if (!isChunkLoadError(err)) reportIslandFailure('backstage', err)
        return NoBackstage
      },
    )

export const Backstage = lazyIsland(loadBackstage, 'backstage')
