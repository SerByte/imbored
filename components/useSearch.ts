'use client'

import { useSyncExternalStore } from 'react'

/**
 * Строка запроса как внешний источник — вместо useSearchParams.
 *
 * Разница не стилистическая. useSearchParams в статически пререндеренном
 * маршруте роняет ВЕСЬ маршрут в клиентский рендер: Next помечает границу
 * маркером BAILOUT_TO_CLIENT_SIDE_RENDERING и не рисует поддерево вовсе.
 * Замер по проду до этой правки:
 *
 *   /       20 879 байт разметки, 232 символа видимого текста
 *   /quiz   тот же результат
 *   /play   тот же результат
 *
 * Двести тридцать два символа — это шапка и подвал. Всё остальное, включая
 * заголовок, форму и кнопки, появлялось только после разбора ~186 КБ сжатого
 * JS: ни поисковику, ни человеку на медленной сети страницы не существовало.
 *
 * Отдельный серверный снимок — ровно то, ради чего у useSyncExternalStore три
 * аргумента. На пререндере строка пуста, то есть в разметку уходит вариант
 * «человек пришёл сам»; после гидратации React перерисовывает с настоящим
 * адресом, и расхождения разметки не возникает — в отличие от чтения
 * window.location прямо в рендере.
 *
 * Цена размена: значения, зависящие от параметров, применяются кадром позже.
 * Для параметров прибытия (приглашение в пати, код ошибки, «откуда пришёл»)
 * это верный размен — страница и без них полностью работоспособна.
 *
 * popstate обязателен: «назад» на адрес с другими параметрами компонент не
 * перемонтирует, и без подписки страница осталась бы со старым разбором.
 */
function subscribe(onChange: () => void): () => void {
  window.addEventListener('popstate', onChange)
  return () => window.removeEventListener('popstate', onChange)
}

const EMPTY = ''

export function useSearch(): string {
  return useSyncExternalStore(subscribe, () => window.location.search, () => EMPTY)
}
