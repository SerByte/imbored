import Link from 'next/link'

/**
 * Дверь, которая работает без единой строчки скрипта.
 *
 * ConnectCard читает адрес через useSearchParams, а на предрендеренном
 * маршруте всё дерево до ближайшей границы Suspense уходит в клиентский
 * рендер: в статический HTML попадает именно фолбэк. Раньше карточка стояла
 * внизу страницы, и пустая коробка на её месте стоила «всего лишь» пустого
 * места под сгибом. Теперь карточка — первый экран, и фолбэк это буквально
 * первое, что видит человек и краулер. Заглушкой он быть не может.
 *
 * Поэтому здесь лежит то, что работает без JS: обычная ссылка в Steam и та же
 * сноска про доступ. Поля ввода нет намеренно — оно без скрипта не работает, а
 * второй <input id="steam-profile"> в разметке сломал бы и label for, и
 * уникальность id, когда приедет настоящая карточка.
 */

/**
 * Высота коробки, общая для фолбэка и настоящей карточки.
 *
 * Замерено в браузере на живой странице: гостевая карточка без потолка —
 * 391.5 px, сам фолбэк заметно ниже. То есть без общего минимума подмена
 * фолбэка на карточку при гидратации двигала бы первый экран почти на двести
 * пикселей — ровно там, куда человек в этот момент смотрит и целится пальцем.
 *
 * Число одно на все ширины, и это проверено, а не предположено: замер даёт те
 * же 391.5 и на 416 px колонки, и на 335 px телефона — сноска про доступ
 * занимает три строки в обоих случаях. Появится там четвёртая строка — потолок
 * придётся разложить по брейкпоинтам.
 *
 * ЧИСЛО ПЕРЕМЕРЯЕТСЯ ПРИ КАЖДОЙ ПРАВКЕ СОДЕРЖИМОГО КАРТОЧКИ, И ДАЖЕ ПРАВКЕ
 * ТОКЕНА. Прежние 357 протухли, когда карточка получила надзаголовок; 389
 * протухли на следующем же проходе — сквозная правка типографики подняла кегль
 * подписей с 10 px до общего --text-label, и карточка выросла ещё на три
 * пикселя. Оба раза потолок оказывался НИЖЕ настоящей высоты, то есть
 * переставал держать хоть что-нибудь.
 *
 * Живёт в одном месте и импортируется обеими сторонами: две одинаковые
 * константы в двух файлах разъехались бы на первой же правке карточки.
 */
export const CONNECT_CARD_MIN_H = 'min-h-[392px]'

export function ConnectFallback() {
  return (
    <div className="flex w-full max-w-md flex-col gap-4">
      <div className={`connect-card flex ${CONNECT_CARD_MIN_H} flex-col justify-center gap-3 p-6`}>
        {/* Надзаголовок тот же, что у настоящей карточки: подмена одного вида
            другим на первом экране читается как моргание, а фолбэк — это
            буквально то, что человек видит до гидратации. */}
        <p className="card-eyebrow">Доступ к библиотеке</p>
        <a href="/api/auth/steam" className="btn-ember is-block">
          Войти через Steam
        </a>
        <p className="text-xs leading-relaxed text-dim">
          Пароль не спрашиваем — вход идёт на стороне Steam. Читаем только список игр и наигранные
          часы, ничего не публикуем.{' '}
          <Link href="/privacy" className="tap tap-tight underline decoration-edge hover:text-ink">
            Подробнее
          </Link>
        </p>
      </div>
    </div>
  )
}
