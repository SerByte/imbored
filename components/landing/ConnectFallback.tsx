import Link from 'next/link'

/**
 * Дверь, которая работает без единой строчки скрипта.
 *
 * ConnectCard читает адрес через useSearchParams, а на предрендеренном
 * маршруте всё дерево до ближайшей границы Suspense уходит в клиентский
 * рендер: в статический HTML попадает именно фолбэк. Раньше карточка стояла
 * внизу страницы, и пустая коробка на её месте стоила «всего лишь» пустого
 * места под сгибом. Теперь карточка — первый экран, и фолбэк это буквально
 * первое, что видит человек и краулер. Заглушкой он быть не может.
 *
 * Поэтому здесь лежит то, что работает без JS: обычная ссылка в Steam и та же
 * сноска про доступ. Поля ввода нет намеренно — оно без скрипта не работает, а
 * второй <input id="steam-profile"> в разметке сломал бы и label for, и
 * уникальность id, когда приедет настоящая карточка.
 */

/**
 * Высота коробки, общая для фолбэка и настоящей карточки.
 *
 * Замерено в браузере на живой странице: гостевая карточка без потолка — 357 px
 * (24 + форма 110 + 12 + разделитель 16 + 12 + Steam 46 + 12 + демо 28 + 12 +
 * сноска 59 + 24), сам фолбэк — 169. То есть без общего минимума подмена
 * фолбэка на карточку при гидратации двигала бы первый экран на 188 px — ровно
 * там, куда человек в этот момент смотрит и целится пальцем.
 *
 * Число одно на все ширины, и это проверено, а не предположено: сноска про
 * доступ занимает три строки и на 416 px колонки, и на 335 px телефона, так что
 * карточка выходит теми же 357 в обоих случаях. Появится там четвёртая строка —
 * потолок придётся разложить по брейкпоинтам.
 *
 * Живёт в одном месте и импортируется обеими сторонами: две одинаковые
 * константы в двух файлах разъехались бы на первой же правке карточки.
 */
export const CONNECT_CARD_MIN_H = 'min-h-[357px]'

export function ConnectFallback() {
  return (
    <div className="flex w-full max-w-md flex-col gap-4">
      <div
        className={`glass flex ${CONNECT_CARD_MIN_H} flex-col justify-center gap-3 rounded-[20px] p-6`}
      >
        <a
          href="/api/auth/steam"
          className="rounded-[14px] bg-ember py-3 text-center font-semibold text-on-ember transition hover:brightness-110"
        >
          Войти через Steam
        </a>
        <p className="text-xs leading-relaxed text-dim">
          Пароль не спрашиваем — вход идёт на стороне Steam. Читаем только список игр и наигранные
          часы, ничего не публикуем.{' '}
          <Link href="/privacy" className="tap tap-tight underline decoration-edge hover:text-ink">
            Подробнее
          </Link>
        </p>
      </div>
    </div>
  )
}
