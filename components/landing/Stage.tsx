'use client'

import { useGSAP } from '@gsap/react'
import gsap from 'gsap'
import { ScrollTrigger } from 'gsap/ScrollTrigger'
import { useRef } from 'react'

gsap.registerPlugin(ScrollTrigger, useGSAP)

/**
 * ЗАКРЕПЛЁННАЯ СЦЕНА.
 *
 * Секция прилипает к экрану, и прокрутка проигрывает внутри неё таймлайн.
 * Одна обёртка на все пять сцен: длина закрепления и партитура у каждой свои,
 * а механика одна, и второй её экземпляр разъехался бы с первым при первой же
 * правке.
 *
 * ГЛАВНОЕ ПРАВИЛО, КОТОРОЕ ЭТА ОБЁРТКА ОБЕСПЕЧИВАЕТ:
 * начальные состояния прячутся ТОЛЬКО внутри `build`, никогда в CSS.
 *
 * Отсюда следует всё остальное. При «уменьшить движение» `build` не
 * вызывается вовсе — и сцена остаётся обычной секцией, где всё видно сразу.
 * Если бы `opacity: 0` стоял в стилях, тот же человек получил бы пустой экран,
 * и заметили бы это только у него. Правило проекта звучит так: анимация может
 * добавить появление, но не может спрятать контент (см. .anim-page-in в
 * globals.css и сторож lib/firstpaint.test.ts).
 *
 * ПОЛНАЯ ПРОЗРАЧНОСТЬ СТАВИТСЯ ЧЕРЕЗ autoAlpha, А НЕ opacity.
 *
 * Разница не косметическая. `opacity: 0` гасит пиксели и оставляет элемент в
 * обходе с клавиатуры и под курсором: он невидим, но фокусируем и нажимаем.
 * `autoAlpha` — это та же прозрачность плюс `visibility`, и на нуле GSAP
 * снимает элемент с обхода целиком.
 *
 * Замерено настоящим Tab через протокол на проде: из 34 остановок фокуса
 * ПЯТЬ приходились на невидимое — четыре переключателя сцены подбора и
 * парадная кнопка сцены денег. Прежний обход это пропускал, потому что мерил
 * рамку и объявленное кольцо; и то и другое честно отвечает «да» на
 * `opacity: 0`. Кадр при этом показывал пустую половину экрана.
 *
 * Это та же красная линия, только с другой стороны: анимация не может прятать
 * контент — а фокус, приехавший в спрятанное, ровно это и обнаруживает.
 * Сторож — lib/hiddenfocus.test.ts.
 *
 * На «уменьшить движение» и без скрипта ничего не меняется: `build` не
 * вызывается, `visibility` остаётся значением из стилей.
 *
 * id секции — `scene-<key>`: по нему лента находит границы закрепления и
 * строит по ним шкалу света (см. lib/ribbonlight.ts). Второго источника этих
 * чисел в проекте нет намеренно.
 */

export type SceneBuild = (tl: gsap.core.Timeline, root: HTMLElement) => void

export function Stage({
  id,
  label,
  end = '+=110%',
  exit = true,
  className = '',
  children,
  enter,
  build,
}: {
  /** Ключ сцены: `pain`, `engine`, `compat`, `more`, `money`. */
  id: string
  /** Человеческое имя — им подписывается сцена для отладки и для ленты. */
  label: string
  /** Длина закрепления в долях экрана. */
  end?: string
  /** Уход кадра в конце закрепления. Выключается там, где сцена закрывает страницу. */
  exit?: boolean
  className?: string
  children: React.ReactNode
  /** Въезд: что показать, пока сцена ещё поднимается в кадр. */
  enter?: SceneBuild
  build?: SceneBuild
}) {
  const ref = useRef<HTMLElement>(null)

  useGSAP(
    () => {
      const root = ref.current
      if (!root || (!build && !enter)) return
      if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return

      /*
       * ДВЕ ФАЗЫ, А НЕ ОДНА. Это лечит системную дыру.
       *
       * Между концом закрепления предыдущей сцены и началом своего у каждой
       * сцены есть ЦЕЛЫЙ ЭКРАН прокрутки: она уже поднялась в кадр, но
       * закрепление ещё не началось, а всё её содержимое спрятано внутри
       * build. Замерено на живой странице — сцена «Как это работает»
       * показывала в этот момент только номер и два надзаголовка, то есть
       * выглядела сломанной.
       *
       * Теперь фаза въезда (start: top bottom → top top) ставит КАДР: то, что
       * делает сцену узнаваемой, пока она поднимается. Закрепление играет
       * сцену. Правило прежнее: прятать можно только внутри этих двух
       * колбэков, и при «уменьшить движение» не вызывается ни один.
       */
      if (enter) {
        const intro = gsap.timeline({
          scrollTrigger: { trigger: root, start: 'top bottom', end: 'top top', scrub: 0.6 },
        })
        enter(intro, root)
      }

      if (!build) return

      /*
       * ЗАКРЕПЛЯЕМ ТОЛЬКО ТО, ЧТО ПОМЕЩАЕТСЯ В ЭКРАН.
       *
       * Закрепление намертво фиксирует секцию у верхнего края, и прокрутка
       * после этого крутит не страницу, а таймлайн. Значит всё, что не влезло
       * в первый экран сцены, не станет видно НИКОГДА — не «надо домотать», а
       * недостижимо в принципе.
       *
       * На телефоне это ровно то, что и происходило. Замерено на 375×812:
       * содержимое сцены подбора — 981 px при рабочей высоте 767 (за вычетом
       * шапки и нижней навигации), и из пяти рекомендаций было видно ДВЕ. Не
       * в какой-то момент — вообще, на любой позиции внутри закрепления, от
       * 2600 до 4400. Три карточки из пяти на самой главной сцене продукта
       * просто не существовали для человека с телефоном.
       *
       * Условие поэтому не «узкий экран», а «не помещается»: то же самое
       * случится на коротком окне ноутбука или при крупном системном шрифте, и
       * лечиться должно тем же правилом, а не вторым брейкпоинтом.
       *
       * Когда не помещается — таймлайн играет обычным скрубом, пока секция
       * проходит через экран. Хореография остаётся, кадр не залипает, и всё
       * содержимое доступно обычной прокруткой.
       *
       * Порог пересчитывается только на монтировании: смена ориентации прямо
       * посреди сцены оставит прежнее решение. Это осознанный размен —
       * закрепление структурно, его нельзя включить и выключить на лету.
       */
      /*
       * Меряем СОДЕРЖИМОЕ, а не секцию.
       *
       * Первая версия смотрела на root.scrollHeight и объявила «не помещается»
       * даже на десктопе, где всё помещается с запасом: у сцен есть слои света
       * с отрицательным inset (.engine-glow, .pain-key, .money-glow), они
       * вылезают за padding-box и честно попадают в scrollHeight. То есть
       * ДЕКОРАЦИЯ отменяла закрепление на всей странице разом — замерено,
       * высота документа упала с 10286 до 8369.
       *
       * getBoundingClientRect у .scene-inner возвращает его собственный бокс и
       * выпирающих потомков не считает — а padding секции добавляем сами.
       */
      const innerEl = root.querySelector('.scene-inner')
      const pad = (() => {
        const cs = getComputedStyle(root)
        return parseFloat(cs.paddingTop) + parseFloat(cs.paddingBottom)
      })()
      const need = (innerEl?.getBoundingClientRect().height ?? 0) + pad
      const fits = need <= window.innerHeight + 2

      const tl = gsap.timeline({
        scrollTrigger: fits
          ? {
              trigger: root,
              start: 'top top',
              end,
              pin: true,
              scrub: 0.6,
              // Без anticipatePin закрепление на быстрой прокрутке успевает
              // мигнуть незакреплённым кадром.
              anticipatePin: 1,
            }
          : {
              trigger: root,
              start: 'top 80%',
              end: 'bottom 60%',
              scrub: 0.6,
            },
      })
      build(tl, root)

      /*
       * УХОД КАДРА.
       *
       * Хвостом того же таймлайна, а не отдельным триггером: скруб обязан
       * отыгрывать уход назад ровно так же, как вперёд, а два источника
       * движения на одном элементе за это не отвечают — этот урок уже стоил
       * ленты, которая вспыхивала на стыке сцен.
       *
       * Без него сцена доигрывала и обрывалась: содержимое просто уезжало
       * вверх обычной прокруткой. Теперь кадр закрывается — и следующая сцена
       * поднимается не поверх остатка предыдущей, а в освободившийся кадр.
       */
      /*
       * ПОЗИЦИЯ УХОДА — tl.duration(), А НЕ '>'. Это не придирка, это дефект,
       * который уже съел половину сцены.
       *
       * '>' в gsap означает «конец ПОСЛЕДНЕГО ДОБАВЛЕННОГО твина», а не «конец
       * таймлайна». Пока каждая сцена добавляла твины по возрастанию времени,
       * разницы не было. Стоило «Совместимости» дописать счётчики циклом ПОСЛЕ
       * длинной волны шкал — и уход встал на конец счётчиков, то есть в
       * середину сцены: кадр гас на 48% закрепления и последнюю треть человек
       * прокручивал по пустому экрану. Замерено: прозрачность .scene-inner
       * падала в ноль уже к 71% диапазона.
       *
       * tl.duration() — это конец ВСЕГО, что в таймлайне есть, в каком бы
       * порядке оно ни добавлялось. Для сцен, где порядок и так был верным,
       * значение совпадает с прежним '>', так что правка ничего не сдвигает —
       * она только убирает зависимость от порядка вызовов внутри build.
       */
      /*
       * Уход кадра только у закреплённой сцены. Без закрепления секция и так
       * уезжает вверх обычной прокруткой, и гасить её вдобавок значило бы
       * стирать текст прямо под глазами у того, кто его в этот момент читает.
       */
      if (exit && fits) {
        tl.to(
          root.querySelector('.scene-inner'),
          { y: -48, opacity: 0, duration: 0.3, ease: 'power2.in' },
          tl.duration(),
        )
      }
    },
    { scope: ref },
  )

  return (
    <section
      ref={ref}
      id={`scene-${id}`}
      data-scene={label}
      className={`scene ${className}`.trim()}
    >
      <div className="scene-inner">{children}</div>
    </section>
  )
}
