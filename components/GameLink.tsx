import Link from 'next/link'
import type { ComponentProps } from 'react'

/**
 * Ссылка на карточку игры там, где карточек на экране много. Без префетча.
 *
 * /game/[appid] — ISR, а не динамическая страница, и Next в проде префетчит
 * статический маршрут ЦЕЛИКОМ, как только ссылка въезжает в кадр
 * (node_modules/next/dist/docs/01-app/02-guides/prefetching.md: «Static page —
 * Yes, full route»). Заранее собрана только верхняя сотня (PRERENDER_TOP), всё
 * остальное рендерится на первом запросе — и первым запросом становится
 * префетч: холодный вызов функции, чтения базы loadGamePage и новая запись ISR
 * в ~17 блоков (lib/gamecache — лимит Hobby уже выбран). Портрет с
 * «Чистилищем» — до сорока восьми таких ссылок за один скролл, сетка «Похожие»
 * — шесть соседей на каждой из пяти тысяч карточек, и в основном это хвост
 * каталога, который никто не открывал. Переходят же по одной.
 *
 * Правило в проекте не новое: стена /library, хаб /games, жанры, «Вечера» и
 * «Из желаемого» выключили префетч ровно по этой причине, каждый своей
 * строкой. Здесь оно собрано в одно место — для полок, которые его пропустили
 * (портрет, итоги года, совместимость, «Приглянулось», «Скрытое», «Похожие»,
 * строки /whatsnew), и чтобы следующая полка брала его готовым. Сторож —
 * lib/gameprefetch.test.ts: ссылка на карточку без решения о префетче там
 * не проходит.
 *
 * Цена — клик ждёт сервер: у /game нет loading.tsx. Это та же сделка, что на
 * стене /library. Перелёт обложки (components/Morph) при этом не теряется:
 * морф собирается, когда страница назначения приходит одним коммитом, а
 * границы Suspense над /game нет — старая страница стоит до ответа, и
 * переход идёт так же, только позже.
 *
 * Где префетч оставлен: одиночная ссылка, по которой скорее всего и пойдут —
 * герой «Игры дня», карточка выбора комнаты, обложка ленты. Там один
 * предзагруженный адрес окупается кликом.
 *
 * Не 'use client': компонент без хуков, и серверная страница, и клиентская
 * полка зовут его одинаково, лишней клиентской границы он не заводит. Адрес
 * собран здесь, а не через gamePagePath из lib/gamecache: тот модуль тянет за
 * собой lib/db, и клиентская полка увезла бы его в бандл.
 */
export function GameLink({
  appid,
  ...rest
}: Omit<ComponentProps<typeof Link>, 'href' | 'prefetch'> & { appid: number }) {
  return <Link href={`/game/${appid}`} prefetch={false} {...rest} />
}
