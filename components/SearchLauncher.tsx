'use client'

import { useRef, useState } from 'react'
import { Icon } from '@/components/Icon'
import { useLocale } from '@/components/LocaleProvider'
import { clientErrorCode, reportClientError } from '@/lib/clienterr'
import type { Locale } from '@/lib/i18n'

/**
 * Кнопка «Найти игру» — лёгкий вход в поиск по каталогу.
 *
 * Стоит в шапке, то есть на КАЖДОЙ странице, и поэтому весит одну кнопку.
 * Само окно поиска (components/CatalogSearch) — поле, список, клавиатура,
 * свёртка названий — едет отдельным чанком по динамическому import(), а
 * индекс каталога — ещё позже, когда окно открылось (lib/catalogindex). В
 * первую загрузку страницы не попадает ни то, ни другое: /room/[id], /quiz,
 * /library, /daily и /explore стоят у самого потолка bundle-budget.json, и
 * окно (8.8 КБ) их бы через него перевело. Сама кнопка — 1.0 КБ к первой
 * загрузке каждой страницы (замер сборкой, без сжатия), и ещё ~0.4 КБ —
 * подставка клавиатуры (holdKeyboard: ~0.35 КБ сама и 52 байта — её имя и
 * роль для скринридера; замер esbuild --minify до и после) и ~0.37 КБ —
 * ответ на отказ чанка (строка, отчёт, живая область, видимая строка под
 * значком классом и сброс отказа прогревом; тот же замер, сам lib/clienterr
 * уже в первой загрузке через instrumentation-client). Самый тесный
 * маршрут — /room/[id], 648 КБ из 650 (замер сборкой после e6d275f). Что
 * статический импорт окна сюда не вернётся, сторожит lib/searchlazy.test.ts —
 * граф импортов от этого файла.
 *
 * Чанк начинают грузить по намерению — наведение, касание, фокус, — а не
 * при загрузке страницы: тот, кто поиск не открывал, не платит и его.
 *
 * ОКНО МОНТИРУЕТСЯ В ТОМ ЖЕ НАЖАТИИ, ЕСЛИ ЧАНК УЖЕ ЗДЕСЬ. Поэтому компонент
 * окна лежит в состоянии, а не за React.lazy: lazy при первом показе
 * приостанавливается даже на готовом модуле, и окно вставало бы кадром позже,
 * вне жеста. А iPhone открывает клавиатуру, только если фокус в поле пришёл
 * внутри жеста пользователя: без этого человек тапал по «Найти игру», видел
 * поле — и тапал второй раз, чтобы набрать.
 *
 * НА КАСАНИИ ЧАНК ОБЫЧНО НЕ УСПЕВАЕТ. pointerenter у пальца приходит вместе с
 * pointerdown, в начале касания, а click — на отрыве, через 50–150 мс; чанку
 * нужен хотя бы один круг до сервера, и на мобильной связи это дольше тапа.
 * Так что первое открытие после загрузки страницы на телефоне — почти всегда
 * ветка «чанк в пути». Для неё клавиатуру поднимает подставка (holdKeyboard):
 * невидимое поле получает фокус внутри жеста, а окно, приехав, переводит фокус
 * в своё поле — из поля в поле iOS клавиатуру не опускает.
 *
 * Два вида: значок в шапке (как переключатель темы рядом) и строка-поле на
 * /games и 404 — там поиск по названию и есть главный ответ на «где игра».
 * Один компонент, а не два, и это про вес: 404 корневого лэйаута входит в
 * первую загрузку КАЖДОЙ страницы (граница not-found), и отдельный файл
 * строки ехал бы туда своим чанком. Замер сборкой: два файла — +1.6 КБ на
 * маршрут, один с утилитами — +1.25, один с видом строки классом
 * .search-field в globals.css — +1.0: строка утилит тоже ехала бы в этот JS.
 *
 * Значка в шапке нет на 768–1023 px: там у шапки нет на него места (замеры —
 * в components/HeaderNav.tsx). На телефоне меню уезжает в нижнюю панель и
 * места хватает, с lg — тоже.
 *
 * ЧАНК НЕ ПРИШЁЛ — НЕ ТИШИНА. Чаще всего это деплой: старая вкладка просит
 * кусок прежней сборки, и 404 повторяется на каждое нажатие, пока страницу не
 * перезагрузят (тот же довод у components/TonightLazy). Нажатие при этом не
 * делало ничего — клавиатура моргала и опускалась, скринридер молчал, а в
 * логе не было ни строки. Теперь отказ нажатия уходит в отчёт тем же путём и
 * с тем же видом, что у островков (components/lazyIsland, тег search), а
 * кнопка говорит «Поиск не загрузился — обнови страницу»: строка-поле —
 * своей подписью, значок — цветом, подсказкой и строкой под собой,
 * скринридер — живой областью рядом. Строка под значком — потому что title
 * телефон не показывает, а в шапке телефона значок и есть вход в поиск:
 * зрячий видел только моргнувшую клавиатуру и покрасневшую лупу. Отчёт — от
 * lib/clienterr напрямую, а не через reportIslandFailure: clienterr в первой
 * загрузке каждой страницы по своей причине (instrumentation-client), а
 * модуль островка — только пока его везут оболочки лэйаута
 * (components/BackstageLazy, components/ReadOnlyNote), и вес кнопки от них
 * зависеть не должен. Прогрев (warm) отказ не отчитывает: это догадка, а не
 * нажатие, и его отказа человек не видел.
 *
 * Просьба обновить страницу живёт, только пока поиск правда сломан. Гаснет
 * она с каждым нажатием — до быстрого пути, а не после него, — и с каждым
 * приехавшим прогревом: связь моргнула и вернулась (фокус, вернувшийся на
 * кнопку после отказа, сам запускает прогрев) или окно уже привезла другая
 * кнопка — шапка и /games делят один модуль. Иначе окно открывалось бы под
 * кнопкой, которая всё ещё говорит «обнови страницу», и говорила бы это до
 * перезагрузки.
 */

type Dialog = typeof import('./CatalogSearch').CatalogSearch

/**
 * Модуль окна — один на вкладку, общий для всех кнопок: шапка и /games
 * открывают одно и то же. Отказ загрузки забывается — следующее нажатие
 * попробует снова.
 */
let loaded: Dialog | null = null
let loading: Promise<Dialog> | null = null

function loadDialog(): Promise<Dialog> {
  loading ??= import('./CatalogSearch').then(
    (m) => (loaded = m.CatalogSearch),
    (err: unknown) => {
      loading = null
      throw err
    },
  )
  return loading
}

/**
 * Имя значка и подставки. Константой, а не двумя литералами: каждая копия
 * кириллицы — ~20 байт в первой загрузке каждой страницы.
 *
 * По-английски — «Search games», а не «Find a game»: ту фразу глоссарий
 * (docs/i18n.md) отдаёт подбору, и два одинаковых имени в одной шапке звали
 * бы в разные места. Строки обоих языков — объектом по языку, без tr():
 * кнопка стоит в первой загрузке каждой страницы и везёт только то, что ей
 * нужно (lib/searchlazy.test.ts).
 */
const NAME = { ru: 'Найти игру', en: 'Search games' } satisfies Record<Locale, string>

/** Чанк окна не пришёл на нажатие. Одной константой — по той же причине, что NAME */
const MISSED = {
  ru: 'Поиск не загрузился — обнови страницу',
  en: "Search didn't load — reload the page",
} satisfies Record<Locale, string>

/** Подпись строки-поля на /games и 404 */
const FIELD = { ru: 'Найти игру по названию', en: 'Search games by title' } satisfies Record<Locale, string>

/**
 * Подставка для клавиатуры, пока чанк окна в пути (докблок выше): невидимое
 * поле, фокус в которое пришёл внутри жеста, — и iPhone поднимает клавиатуру
 * сразу, а не по второму тапу.
 *
 * 16 px, иначе Safari приблизит страницу (как у поля окна); не readonly —
 * у readonly клавиатуры нет; fixed у верхнего края — фокус ничего не
 * прокручивает.
 *
 * Глазу её нет, скринридеру — есть, и так и должно быть. Прятать её
 * aria-hidden нельзя: фокус в ней — вся её суть, а aria-hidden на элементе с
 * фокусом Chrome не исполняет — пишет «Blocked aria-hidden…» и отдаёт
 * скринридеру безымянное поле. На медленной связи чанк едет секунды, и
 * человек слышал «поле редактирования» без имени, набирал в него, а фокус
 * молча прыгал в окно. Поэтому подставка — то, чем станет: комбобокс поиска
 * (поле окна — role="combobox"), свёрнутый — списка ещё нет, — с именем
 * нажатой кнопки. Переход в поле окна звучит продолжением, а не сменой поля.
 *
 * Уходит сама, как только фокус ушёл: в поле окна — его забирает эффект
 * монтирования components/CatalogSearch, — или куда угодно ещё. Набранное в
 * неё, пока чанк ехал, не пропадает: окно открывается с ним (seed).
 *
 * Каждый байт здесь — в первой загрузке каждой страницы, поэтому только то,
 * без чего не работает: автодополнение и регистр клавиатуры поправит поле
 * окна, когда фокус перейдёт в него.
 */
export function holdKeyboard(locale: Locale = 'ru'): HTMLInputElement {
  const proxy = document.createElement('input')
  proxy.setAttribute('role', 'combobox')
  proxy.setAttribute('aria-expanded', 'false')
  // Подставку создаёт не React, а обработчик нажатия: язык ей передаёт кнопка
  proxy.setAttribute('aria-label', NAME[locale])
  proxy.style.cssText = 'position:fixed;top:0;opacity:0;font-size:16px'
  proxy.addEventListener('blur', () => proxy.remove())
  document.body.append(proxy)
  proxy.focus({ preventScroll: true })
  return proxy
}

export function SearchLauncher({ variant = 'icon' }: { variant?: 'icon' | 'field' }) {
  const locale = useLocale()
  const opener = useRef<HTMLButtonElement>(null)
  // Компонент окна в состоянии: есть — окно открыто (см. докблок выше).
  // seed — набранное в подставку, пока чанк ехал (holdKeyboard)
  const [open, setOpen] = useState<{ Dialog: Dialog; seed: string } | null>(null)
  // Нажатие не принесло окна: кнопка говорит об этом сама (докблок выше)
  const [missed, setMissed] = useState(false)
  const field = variant === 'field'
  // Прогрев по намерению. Готовый модуль отдаёт тот же выполненный промис —
  // нового import() нет, — и его приезд гасит прежний отказ (докблок выше)
  const warm = () => loadDialog().then(() => setMissed(false), () => {})

  return (
    <>
      <button
        ref={opener}
        type="button"
        aria-haspopup="dialog"
        // У строки имя — её подпись; у значка подписи нет
        aria-label={field ? undefined : NAME[locale]}
        title={field ? undefined : missed ? MISSED[locale] : NAME[locale]}
        className={
          field
            ? 'search-field'
            : `tap btn-glass size-10 !rounded-full !p-0 md:max-lg:hidden ${missed ? 'text-danger' : 'text-dim hover:text-ink'}`
        }
        onPointerEnter={warm}
        onFocus={warm}
        onClick={() => {
          // Прежний отказ гаснет с каждым нажатием, и до быстрого пути: чанк
          // мог доехать прогревом после отказа, и окно открылось бы под
          // «обнови страницу». А на новой попытке второй такой же отказ иначе
          // промолчал бы — живая область объявляет смену текста
          setMissed(false)
          if (loaded) {
            setOpen({ Dialog: loaded, seed: '' })
            return
          }
          // Синхронно, до первого await: после него жест уже кончился
          const proxy = holdKeyboard(locale)
          loadDialog().then(
            (Dialog) => setOpen({ Dialog, seed: proxy.value }),
            // Чанк не доехал — окна нет, кнопка на месте. Моргнула связь —
            // нажатие повторит; 404 после деплоя повтор не вылечит, поэтому
            // кнопка просит обновить страницу, а отчёт уходит в лог. Фокус —
            // с подставки обратно на кнопку: клавиатура опускается, подставка
            // уходит по blur. Ушёл фокус раньше сам — подставки уже нет, и
            // фокус не трогаем
            (err: unknown) => {
              reportClientError({
                kind: 'boundary',
                error: err,
                island: 'search',
                href: window.location.href,
                code: clientErrorCode(err),
              })
              setMissed(true)
              if (proxy.isConnected) opener.current?.focus()
            },
          )
        }}
      >
        <Icon name="search" size={field ? 18 : 17} />
        {field && (missed ? MISSED[locale] : FIELD[locale])}
      </button>
      {/* Стоит всегда, текст приходит с отказом: область, вставленная
          вместе с текстом, звучит не везде (components/StatusLine). Не
          StatusLine — лишний модуль в первой загрузке каждой страницы.
          У значка с отказом она же — видимая строка под ним (.search-miss в
          globals.css: классом, а не утилитами, — по той же причине, что
          .search-field); у строки-поля отказ и так написан на ней самой */}
      <span role="status" className={missed && !field ? 'search-miss' : 'sr-only'}>
        {missed ? MISSED[locale] : ''}
      </span>
      {open && <open.Dialog opener={opener} seed={open.seed} onClose={() => setOpen(null)} />}
    </>
  )
}
