import type { ReactNode } from 'react'

/**
 * Строка статуса: живая область, которая стоит в DOM всегда, а меняется в
 * ней только текст.
 *
 * Скринридер объявляет ИЗМЕНЕНИЕ содержимого живой области, а не её
 * появление. Абзац с role="status", вставленный в DOM сразу с текстом, звучит
 * не во всех связках — VoiceOver в Safari промолчит, NVDA через раз, — и
 * отказы вида `{miss && <p role="status">…</p>}` доходили только до глаза:
 * «Голос не ушёл», «Связь потеряна», «Не вышло — попробуй ещё раз».
 *
 * Поэтому условие стоит не снаружи, а внутри, на тексте. Текста нет — абзац
 * пустой и sr-only: в потоке он дал бы лишний зазор колонки, а sr-only
 * вынимает его из раскладки. Текст пришёл — тот же узел получает его вместе
 * с видимыми классами. Приём тот же, что у #connect-error в ConnectCard.
 *
 * className="sr-only" — строка только для скринридера: объявление рядом с
 * видимой копией, которой негде жить дольше события (плитка полки уходит и
 * возвращается откатом).
 *
 * Чего компонент НЕ спасает:
 *  - условного предка. `{open && <div><StatusLine …/></div>}` рождает
 *    область вместе с div, и текст, пришедший тем же рендером, снова
 *    прозвучит не везде. Строка ставится туда, где живёт дольше события, о
 *    котором говорит (сторож — lib/liveregion.test.ts);
 *  - повтор. Тот же текст второй раз подряд — не изменение, и область
 *    промолчит. Поэтому отказ, который может повториться, гаснет в начале
 *    новой попытки, до первого await (setMiss(null)): тогда повтор приходит
 *    изменением текста. Такие места перечислены в стороже (REPEAT в
 *    lib/liveregion.test.ts), и новое место добавляется туда же.
 */
export function StatusLine({
  text,
  className,
}: {
  /** Что сказать. null, undefined, false и '' — область пустая и невидимая */
  text: ReactNode
  /** Классы строки, когда в ней есть текст */
  className: string
}) {
  const said = text !== null && text !== undefined && typeof text !== 'boolean' && text !== ''
  return (
    <p role="status" className={said ? className : 'sr-only'}>
      {said ? text : null}
    </p>
  )
}
