import { tagRu } from '@/lib/tagsru'

/**
 * РЯД ТЕГОВ ПОД НАЗВАНИЕМ ИГРЫ — И ОТМЕТКА НА ТЕХ, КОТОРЫЕ И РЕШИЛИ ДЕЛО.
 *
 * Ряд стоял ровно под фразой, которая называет те же теги словами: «её теги
 * (MOBA, Co-op) совпадают с тем, во что ты играешь больше всего». Ниже —
 * четыре одинаковых чипса, среди которых те же два, и ещё два просто так.
 * Утверждение и доказательство лежали рядом, но связать их приходилось
 * глазами: прочитать два слова в скобках и найти их в ряду.
 *
 * Это не про украшение ряда. Весь продукт держится на том, что рекомендация
 * себя объясняет, — на странице поддержки это записано прямо: «Рекомендация —
 * это доверие». Ряд, в котором видно, ЧТО именно совпало, и есть объяснение;
 * плоский ряд — просто справка о жанре.
 *
 * Отметка не только цветом. Здесь тот же довод, что у переключателя источника
 * в выдаче («скринридеру и тому, кто не различает ember на стекле, нужен
 * признак»): у совпавшего чипса есть залитая точка и текст для озвучки, а не
 * один оттенок.
 *
 * Форма отметки повторяет ведомость на странице конфиденциальности: залитая
 * точка — «есть», её отсутствие — «нет». Один жест на весь продукт.
 *
 * Плашка — bg-ember/20, то есть ровно та прозрачность, которую сторож
 * контраста уже считает по разметке (lib/contrast.test.ts): пара
 * «--ember-text на bg-ember/20» проверена в обеих темах.
 *
 * Теги приходят английскими ключами, и совпадение сверяется по ним же —
 * по-русски только подпись (tagRu, lib/tagsru.ts). Переведи ключ раньше, и
 * отметка «совпадает с твоим вкусом» не нашла бы ни одного тега: профиль
 * вкуса собран из английских.
 */
export function TagChips({
  tags,
  matched = [],
  className = '',
}: {
  tags: string[]
  /** Теги, которые уже есть во вкусе игрока — lib/recommend.ts, sharedTasteTags */
  matched?: string[]
  className?: string
}) {
  if (tags.length === 0) return null
  const hit = new Set(matched)

  /*
   * «Премьера»: строкой через точку, как жанры под названием у стриминга, а
   * не россыпью пилюль. Пилюли спорили с кнопками героя за вес — теперь
   * кнопка одна выглядит кнопкой. Совпавший с твоим вкусом тег — ярче и с
   * зелёной точкой, той же, что у источника выдачи.
   */
  return (
    <ul className={`flex flex-wrap items-center gap-x-2 gap-y-1 text-sm ${className}`}>
      {tags.map((t, i) => (
        <li key={t} className="flex items-center gap-2">
          {i > 0 && (
            <span aria-hidden className="text-faint">
              ·
            </span>
          )}
          {hit.has(t) ? (
            <span className="inline-flex items-center gap-1.5 font-bold text-ink">
              <span aria-hidden className="size-1.5 shrink-0 rounded-full bg-ember-text" />
              {tagRu(t)}
              <span className="sr-only"> — совпадает с твоим вкусом</span>
            </span>
          ) : (
            <span className="font-medium text-dim">{tagRu(t)}</span>
          )}
        </li>
      ))}
    </ul>
  )
}
