'use client'

import dynamic from 'next/dynamic'

/**
 * SplitHeading, догружаемый отдельно.
 *
 * Зачем: gsap с плагином SplitText — это 69 КБ несжатого чанка, и он едет в
 * начальном наборе скриптов /daily и /play (замер: чанк тянут ровно эти два
 * маршрута). При том что на обеих страницах заголовок появляется ТОЛЬКО после
 * ответа API — то есть спустя секунды после первого кадра, а на экране ошибки
 * или пустой выдачи не появляется вовсе.
 *
 * Заглушка рисует тот же текст тем же классом, поэтому подмена не двигает
 * вёрстку: меняется только то, собирается ли заголовок по словам.
 *
 * ssr: false обязателен. С ним заголовок на сервере не рендерится, и это здесь
 * ничего не стоит — его и так нет в разметке обеих страниц. На /whatsnew,
 * /compat/[steamid] и /portrait/[steamid] такой приём применять НЕЛЬЗЯ: там
 * заголовок отдаёт сервер, и он же видимый LCP-текст.
 */
export const SplitHeadingLazy = dynamic(
  () => import('./SplitHeading').then((m) => m.SplitHeading),
  {
    ssr: false,
    loading: () => null,
  },
)
