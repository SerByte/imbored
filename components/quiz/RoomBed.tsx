'use client'

import { AnimatePresence, motion } from 'motion/react'
import { EASE_GLOW, DUR } from '@/lib/motion'
import type { AxisKey } from '@/lib/quiz'

/**
 * Свет комнаты. Шаг квиза не перекрашивает интерфейс — он МЕНЯЕТ ГЕЛЬ НА ЛАМПЕ.
 *
 * Комната освещена одной практической лампой за кадром слева-сверху (22% /
 * −12%), и всё в кадре подчиняется этой точке: куда падают тени, под каким
 * углом идут световые шахты, на какой кромке панели лежит блик. Время —
 * холодный циан, Вайб — магента, Компания — янтарь; дуга «холодно → горячо» за
 * три вопроса, и ключ третьего шага И ЕСТЬ --ember, так что на финальном
 * вопросе комната и бренд сливаются.
 *
 * МЕХАНИЗМ: A/B-кроссфейд двух СТАТИЧЕСКИ отрисованных постелей, а не
 * интерполяция цвета по площади экрана. Идиома дословно из ArtWash:
 * AnimatePresence БЕЗ mode — обе постели сосуществуют один такт, и это ровно
 * то, что нужно перекраске.
 *
 * Почему не @property + transition на --key. Инкрементный цвет заставил бы
 * поверхность размером с экран ПЕРЕРИСОВЫВАТЬСЯ каждый кадр все 720 мс, плюс
 * пересчёт наследуемого стиля во всём поддереве. Кроссфейд стоит один
 * композитный слой и НОЛЬ перерисовок — то есть главный аттракцион дешевле
 * того, что на странице уже работает. Побочно: @property не нужен вовсе,
 * значит нет деградации там, где он не поддержан, и не нужен трюк с обходом
 * зелёного при интерполяции из циана в магенту — ничто не интерполируется.
 *
 * reduce читается снаружи и приходит пропом: MotionConfig reducedMotion="user"
 * глушит transform и layout, но ОСТАВЛЯЕТ opacity, а здесь цвет обязан быть
 * состоянием, а не фейдом. Комната всё равно другого цвета на каждом шаге —
 * мгновенно. Различие остаётся, перетекание убрано.
 *
 * Постели выбираются по data-bed, а не инлайновым кастомным свойством: под
 * strict инлайновый --key это TS2353, и в проекте для такого принят
 * el.style.setProperty (см. SpotlightCard). Заодно постель, которая читает
 * переменную, — это постель, которая перерисовывается.
 */
export function RoomBed({ axis, reduce }: { axis: AxisKey; reduce: boolean }) {
  return (
    <div aria-hidden className="quiz-bed-wrap pointer-events-none absolute inset-0 overflow-hidden">
      {/*
        initial={false} — НЕ вкусовщина, а закон проекта: анимация может только
        добавить проявление, но не может спрятать. Без него первая постель
        приезжает из серверного HTML с opacity:0 и ждёт кадра, чтобы зажечься —
        а если кадра не будет (скрытая вкладка, задушенный rAF, сбой гидратации),
        комната остаётся тёмной НАВСЕГДА. Ровно этот отказ и был пойман на
        проверке. Теперь первая отрисовка уже несёт свет, а перекрещиваются
        только последующие смены геля — то есть ровно то, ради чего всё это.
      */}
      <AnimatePresence initial={false}>
        <motion.div
          key={axis}
          data-bed={axis}
          className="quiz-bed absolute inset-0"
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          transition={reduce ? { duration: 0 } : { duration: DUR.relight, ease: EASE_GLOW }}
        >
          {/* Объёмные шахты. Живут ВНУТРИ постели, чтобы уезжать вместе с ней:
              отдельный слой пришлось бы гасить и зажигать вторым таймлайном. */}
          <span className="quiz-rays" />
        </motion.div>
      </AnimatePresence>
    </div>
  )
}
