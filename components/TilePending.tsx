'use client'

import { useLinkStatus } from 'next/link'

/**
 * Плитка игры, по которой уже нажали, а /game ещё не приехала.
 *
 * Без префетча переход ждёт сервер (components/GameLink), а холодная
 * страница из хвоста каталога — это холодный рендер ISR, секунда и больше.
 * Всё это время на телефоне не менялось ничего: отклик плитки — только
 * :hover и :focus-visible, нажатия палец не видел, и по ней жали второй раз.
 *
 * Знак — сама плитка: обложка гаснет, и по её нижнему краю ползёт полоска
 * (.game-card:has(.tile-pending) в globals.css). Состояние — тот же
 * useLinkStatus, что у подписей шапки (components/LinkPending), и та же
 * задержка --dur-fast: быстрый переход не мигает вовсе. Хук обязан стоять
 * внутри <Link>, поэтому узел кладётся ребёнком ссылки — GameLink делает это
 * сам, а Link с префетчем (полка /explore) — руками; сторож и единственное
 * исключение, полка 404, — lib/gameprefetch.test.ts.
 *
 * Свой лист, а не пустой LinkPending внутри скрытой обёртки, — ради веса
 * страниц, а не бандла. Плиток на странице десятки, на хабе /games — сотни,
 * а /game пишется в ISR блоками по 8 КБ (lib/gamecache): обёртка с
 * вложенным островком стояла бы в HTML и RSC каждой плитки. Этот лист в
 * покое не рисует ничего — в HTML его нет, в RSC он одна короткая ссылка.
 *
 * Узел появляется только на время ожидания и скрыт (hidden): в раскладке
 * его нет — ни зазора gap у плиток-рядов (совместимость, строка поиска с
 * justify-between), ни строки в блочной плитке; :has() видит его и так.
 * Объявлять ожидание незачем: фокус остаётся на нажатой ссылке, пока не
 * придёт страница, — как и у подписей шапки.
 */
export function TilePending() {
  const { pending } = useLinkStatus()
  return pending ? <span hidden className="tile-pending" /> : null
}
