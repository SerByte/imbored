import { steamLoginFor } from '@/lib/destination'

/**
 * Одна строка для сессии, которой писать нельзя.
 *
 * Сессия по вставленной ссылке на профиль смотрит всё, но ничего не
 * сохраняет: оценки, баны и комнаты ей отвечают 403 needsteam (isWriter в
 * lib/server). Без этой строки кнопки просто исчезали бы — или, хуже,
 * жались бы вхолостую, — и человек не узнал бы ни почему, ни что сделать.
 *
 * Одна формулировка на все места, где кнопку записи прячут: выдача, полка
 * забаненного, пати. Ссылка возвращает туда же, где нажал (steamLoginFor), —
 * вход ради того, чтобы нажать «Зашло», не должен заканчиваться квизом.
 *
 * Обычная ссылка, а не Link: вход через Steam — переход на чужой сайт через
 * наш роут, клиентскому роутеру тут делать нечего.
 */
export function NeedSteam({ from, className = '' }: { from: string; className?: string }) {
  return (
    <p className={`text-sm text-dim ${className}`}>
      Чтобы сохранять оценки и создавать комнаты —{' '}
      <a href={steamLoginFor(from)} className="tap tap-tight text-ember-text hover:underline">
        войди через Steam
      </a>
    </p>
  )
}
