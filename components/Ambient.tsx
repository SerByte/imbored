/**
 * Тихий ambient-фон для утилитарных экранов — единый по всему приложению.
 *
 * ПОДНЯТ С 0.07/0.05 ДО 0.15/0.10, и это не «сделать поярче». Кино-главную
 * довели до поставленного света — тёплое ядро, холодный добор, виньетка, — а
 * одиннадцать экранов, которые идут ПОСЛЕ неё (квиз, комната, пати,
 * совместимость, прогрев, 404), остались в свете, которого на глаз не видно.
 * Замерено: 0.07 альфы поверх #0b0c10 даёт разницу в единицы уровней — то есть
 * слой формально есть, а кадра не ставит.
 *
 * Числа осторожные намеренно: это фон утилитарного экрана, а не сцена. Он
 * обязан читаться атмосферой, а не пятном, — отсюда и «тихий» в названии,
 * который остаётся в силе.
 */
export function Ambient({ className = '' }: { className?: string }) {
  return (
    <div
      aria-hidden
      className={`absolute inset-0 pointer-events-none ${className}`}
      style={{
        background:
          'radial-gradient(60% 45% at 50% 0%, color-mix(in srgb, var(--ink) 7%, transparent), transparent 70%), radial-gradient(40% 35% at 85% 95%, color-mix(in srgb, var(--ink) 4%, transparent), transparent 70%)',
      }}
    />
  )
}
