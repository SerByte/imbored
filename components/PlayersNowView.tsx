import { fmtNumber, tr, type Locale } from '@/lib/i18n'

/**
 * Насколько свежим должен быть замер, чтобы про него можно было сказать
 * «сейчас». Шесть часов — та же величина, что CCU_MAX_AGE_SEC в /api/prepare,
 * то есть ровно тот срок, после которого догрев сам считает число устаревшим.
 */
const СВЕЖЕСТЬ_SEC = 6 * 3600

/**
 * «Сейчас играют N» — живой онлайн игры.
 *
 * Сервис отсеивает мёртвый мультиплеер молча, и это выглядит как произвол.
 * Показанное число делает решение проверяемым: видно, почему одну игру
 * предлагают на вечер с друзьями, а другую нет.
 *
 * Точка красится --ok, а не bg-emerald-400. Зелёный в этой палитре занят
 * ролью «живое, на месте» и у роли есть токен; сырой цвет Tailwind не знает
 * про светлую тему — а именно на ней emerald и проваливался (в globals.css
 * записано: emerald-300 давал 1.39:1). Признак «сейчас играют» обязан быть
 * виден в обеих темах, иначе он не признак.
 *
 * Модуль универсальный, язык — пропом. Серверная страница игры рисует строку
 * отсюда со своим toLocale(params.lang), и в её клиентский бандл она не едет;
 * клиентские экраны (герой /play и /daily, колода пати) зовут
 * components/PlayersNow — тонкую обёртку с языком из контекста (useLocale).
 * Серверная страница из недельного кэша обязана передать часы, которые от
 * момента рендера не зависят (страница игры — см. её вызов): «сейчас»,
 * верное при рендере, через день было бы неправдой, а перегенерация с
 * другой подписью — новой записью ISR.
 */
export function PlayersNow({
  ccu,
  ccuAt,
  nowSec,
  className = '',
  locale,
}: {
  ccu: number | null
  /** unix-секунды замера; undefined значит «когда мерили — неизвестно» */
  ccuAt?: number | null
  /**
   * Серверные часы из того же ответа, что принёс карточку.
   *
   * Не Date.now() в рендере: он и нечист (React 19 ловит это правилом
   * purity), и на сервере с клиентом даёт разные значения — расхождение
   * гидратации. Ровно тот же довод записан в components/whatsnew/Now.
   *
   * Обязательный, а не со значением по умолчанию: забытые часы молча
   * превратили бы каждую карточку в «играли», и заметить это было бы нечем.
   */
  nowSec: number
  className?: string
  locale: Locale
}) {
  if (ccu === null || ccu === undefined) return null

  /*
   * «Сейчас» — утверждение про НАСТОЯЩИЙ момент, и до сих пор оно печаталось
   * над любым числом, каким бы старым оно ни было.
   *
   * Колонка ccu_at заведена как раз под это, и довод записан в
   * scripts/promote-catalog: «замер ручной, следующий прогон может случиться
   * через месяц, а подпись всё это время будет говорить сейчас». Отметку
   * ставят и promote-catalog, и догрев в /api/prepare — а вот СПРАШИВАТЬ её
   * было некому: половину работы сделали на стороне записи и не довели до
   * чтения.
   *
   * Замер на проде: из 2203 игр с показанным онлайном отметку имеют 183.
   * То есть у 92% чисел, подписанных словом «сейчас», возраст неизвестен —
   * они приехали из посева каталога, а он ходил неизвестно когда.
   *
   * Число оставляем: оно тут не ради точности, а чтобы отсев мёртвого
   * мультиплеера был проверяемым (докблок выше). Убираем ровно ложное — слово
   * «сейчас» и зелёную пульсирующую точку, которая говорит «прямо в эту
   * секунду». Прошедшее время ничего не выдумывает: столько играло на момент
   * замера, когда бы он ни был.
   */
  const свежий = typeof ccuAt === 'number' && nowSec - ccuAt < СВЕЖЕСТЬ_SEC

  /*
   * Пульсирующая точка — только при живом онлайне.
   *
   * Ноль показывать НУЖНО: докблок выше объясняет, зачем — он делает отсев
   * мёртвого мультиплеера проверяемым. А вот зелёная пульсирующая точка рядом
   * с нулём утверждает ровно обратное числу, которое стоит в сантиметре от неё:
   * значок говорит «живо», число говорит «никого». Из двух сигналов один лишний,
   * и убирать надо тот, что врёт.
   *
   * И подпись у нуля своя. «0 играли» читается не как «в момент замера в сети
   * никого», а как «в неё не играл никто и никогда» — на /game/711810 рядом с
   * «72% из 1 886 отзывов», в строке героя /play «Новое для тебя · 0 играли».
   * Прошедшее время рядом с числом честно для людей, которых посчитали, а для
   * пустоты нужно сказать, что пусто было в сети: «онлайн при замере: 0». Ноль
   * при этом остаётся цифрой — проверяемость отсева держится на ней.
   *
   * По-английски довод тот же: «0 were playing» — та же пустота про людей,
   * поэтому и там подпись про сеть — «online at last check: 0» (глоссарий).
   */
  if (ccu === 0) {
    return (
      <span
        className={`inline-flex items-center gap-1.5 text-xs text-dim ${className}`}
        title={
          свежий
            ? undefined
            : tr(locale, { ru: 'Онлайн по последнему известному замеру', en: 'Last known player count' })
        }
      >
        {свежий
          ? tr(locale, { ru: 'сейчас онлайн:', en: 'online now:' })
          : tr(locale, { ru: 'онлайн при замере:', en: 'online at last check:' })}{' '}
        <span className="tabular-nums">0</span>
      </span>
    )
  }
  return (
    <span
      className={`inline-flex items-center gap-1.5 text-xs text-dim ${className}`}
      title={
        свежий
          ? undefined
          : tr(locale, { ru: 'Онлайн по последнему известному замеру', en: 'Last known player count' })
      }
    >
      {ccu > 0 && свежий ? (
        <span aria-hidden className="h-1.5 w-1.5 rounded-full bg-ok anim-pulse-dot" />
      ) : null}
      <span className="tabular-nums">{fmtNumber(locale, ccu)}</span>{' '}
      {/* По-английски прошедшее время согласуется с числом: «1 was playing»,
          «1,234 were playing». Малые числа — ровно то, ради чего строка есть
          (мёртвый мультиплеер, «New to you · 1 …» героя /play); русскому
          «играли» согласовывать нечего */}
      {свежий
        ? tr(locale, { ru: 'сейчас играют', en: 'playing now' })
        : tr(locale, { ru: 'играли', en: ccu === 1 ? 'was playing' : 'were playing' })}
    </span>
  )
}
