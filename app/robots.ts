import type { MetadataRoute } from 'next'
import { appBaseUrl } from '@/lib/server'

/**
 * До этого файла домен отдавал заглушку Cloudflare про content-signals: ни
 * Sitemap, ни Disallow, то есть краулер ходил куда угодно.
 *
 * Закрываем три разных класса адресов, и по разным причинам:
 *
 *   • /api/ — работа, а не контент. /api/prepare и /api/recommend вдобавок
 *     дёргают Steam и платную модель.
 *   • /portrait/, /compat/, /room/ — чужие личные страницы. Портрет
 *     подставляет в заголовок настоящий ник Steam, а строится он по снапшоту
 *     без всякой авторизации: в индексе такому не место. На шеринг это не
 *     влияет — превью и og:image берутся по прямой ссылке, а не из индекса.
 *   • /play, /quiz, /library — состояние сессии, а не страница. Без куки они
 *     всё равно выбрасывают на лендинг, то есть краулер индексировал бы
 *     редирект.
 *
 * Открытыми остаются ровно те разделы, у которых есть собственное содержание:
 * лендинг, /game/*, /whatsnew и статические страницы.
 *
 * ТРИ АДРЕСА ДОБАВЛЕНЫ ПОСЛЕ ЗАМЕРА НА ДЕПЛОЕ, запросом без куки:
 *
 *   /daily      249 символов видимого текста, содержательного — «Изучаю твою
 *               библиотеку…». Выбор считается по ЛИЧНОЙ библиотеке, то есть
 *               это ровно тот же класс, что /play и /quiz. Заодно убран из
 *               карты сайта, где стоял с приоритетом 0.9 — выше всех пяти
 *               тысяч страниц игр.
 *   /portrait   232 символа: шапка и подвал, больше ничего.
 *   /compat     230 символов: то же самое.
 *
 * Хабы закрыты БЕЗ завершающего слэша намеренно: правило /portrait/ покрывает
 * только личные страницы под ним, а сам хаб оставался в обходе и на каждом
 * заходе краулера выполнял динамический рендер с чтением куки ради двухсот
 * символов шапки. Правило без слэша покрывает и хаб, и всё под ним.
 *
 * Если хабы когда-нибудь начнут отдавать содержание серверу (а не после
 * гидратации), их надо будет открыть обратно — ради этого замер и записан.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: '*',
      allow: '/',
      disallow: [
        '/api/',
        '/portrait',
        '/compat',
        '/room',
        '/rooms',
        '/play',
        '/quiz',
        '/library',
        '/daily',
      ],
    },
    sitemap: new URL('/sitemap.xml', appBaseUrl()).toString(),
  }
}
