/**
 * ГОЛОС «ПРЕМЬЕРЫ» — ОДИН НА ВСЁ.
 *
 * До редизайна у продукта было два голоса: широкий Onest для текста и узкий
 * Sofia Sans Condensed для заголовков. Узкий гротеск экономил ширину, но
 * говорил голосом афиши, а не сервиса: крупные титры кричали, а рядом с артом
 * игры спорили с ним за внимание.
 *
 * Manrope — геометрический гротеск с родной кириллицей и весами до 800. Он
 * держит и крупный титр с плотным трекингом (−0.045em), и мелкий текст на
 * телефоне, поэтому второй дисплейный шрифт больше не нужен: иерархию теперь
 * строят кегль и вес, как у стриминговых сервисов, а не смена гарнитуры.
 *
 * preload включён: шрифт стоит в шапке на каждой странице и всегда выше сгиба.
 */
const manrope = Manrope({
  variable: '--font-manrope',
  subsets: ['latin', 'cyrillic'],
})

/**
 * Моноширинный нужен почти везде: проценты, цены, коды комнат, счётчики — и
 * надзаголовки, набранные им же.
 *
 * PRELOAD ВЫКЛЮЧЕН, НО ПРИЧИНА ЗДЕСЬ БЫЛА ЗАПИСАНА НЕВЕРНАЯ. Стояло «ни одного
 * такого числа нет на первом экране» — и это неправда: моноширинным на первом
 * экране набраны подсказка «ЧТО ЭТО ТАКОЕ» внизу героя, надзаголовок карточки
 * «ДОСТУП К БИБЛИОТЕКЕ» и разделитель «ИЛИ». Замерено на живом проде:
 * getComputedStyle у обоих отдаёт "JetBrains Mono".
 *
 * Решение при этом остаётся прежним, и вот настоящая причина. Файлы шрифта на
 * первом экране весят 164 КБ в шести файлах, и на медленном канале это самая
 * крупная фиксированная статья загрузки. Preload моноширинного добавил бы к ней
 * ещё 52 КБ ради трёх мелких подписей — а размер их не меняется: next/font
 * подбирает метрически совпадающий запасной шрифт, и замер CLS на телефоне даёт
 * ровно 0. То есть платить полосой пришлось бы за подмену начертания у трёх
 * строк по одиннадцать пикселей, которую половина людей не заметит.
 *
 * Цену эту платит не только главная. Карточка игры — самая посещаемая
 * поверхность (почти шесть тысяч адресов в карте сайта против дюжины
 * остальных), и там моноширинным над сгибом набрано главное число страницы:
 * процент в кольце отзывов (ProgressRing) и цена (PriceTag). Замер на ветке
 * game-page-schema при окне в 675 пикселей: верхний моноширинный узел — «86%»
 * на 194-м пикселе. Включить preload для одной карточки нельзя — у next/font
 * он глобальный, — так что решение прежнее, но подмену начертания видит и
 * главное число самой посещаемой страницы, а не одни мелкие подписи.
 *
 * Кириллица у моноширинного НУЖНА, хотя «для чисел» подсказывает обратное: ей
 * набраны надзаголовки выше, «бесплатно», даты и «2 недели назад». Соблазн
 * выкинуть поддиапазон и сэкономить сломал бы их.
 *
 * Правило: причина в докблоке обязана быть той, по которой решение принято
 * СЕЙЧАС, а не той, что была верна когда-то.
 */
const jbMono = JetBrains_Mono({
  variable: '--font-jbmono',
  subsets: ['latin', 'cyrillic'],
  preload: false,
})

/**
 * viewportFit: 'cover' — без него env(safe-area-inset-bottom) на iOS всегда
 * равен нулю. То есть отступ под нижнюю панель, который в layout уже был
 * посчитан «с запасом на безопасную зону», по факту не срабатывал ни разу, и
 * на телефонах с домашней полоской панель уезжала под неё.
 *
 * themeColor двумя строками, а не одной: браузерная обвязка (адресная строка
 * в Chrome, статус-бар в PWA) должна совпадать с фоном страницы, а он у нас
 * зависит от темы. Одно значение красило бы шов при светлой теме тёмным.
 */
export const viewport: Viewport = {
  viewportFit: 'cover',
  themeColor: [
    { media: '(prefers-color-scheme: dark)', color: '#050505' },
    { media: '(prefers-color-scheme: light)', color: '#f5f5f7' },
  ],
}

