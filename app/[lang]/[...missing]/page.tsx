import { notFound } from 'next/navigation'

/**
 * Ловушка неизвестных адресов под /en: /en/xyz-nope, /en/quiz/xyz-nope,
 * /en/games/<нет такого жанра>.
 *
 * Без неё такой адрес не находит маршрута, и Next отдаёт
 * app/global-not-found.tsx — русскую 404 и для /en/… тоже: языка адреса
 * у /_not-found нет.
 * С ней адрес попадает под корневой layout своего языка, и notFound() рисует
 * app/[lang]/not-found.tsx на нужном языке, со всей обвязкой и настоящим 404.
 * Рисует — клиентом: HTML от сервера здесь пустая оболочка Next (почему — в
 * app/global-not-found.tsx); у адресов под языком другого способа нет. Голова
 * у оболочки при этом английская целиком, с подписью карточки
 * (generateMetadata в app/[lang]/not-found.tsx).
 *
 * Русских адресов здесь нет. Опечатку под русским разделом (/quiz/xyz,
 * /games/<нет такого жанра>) правило beforeFiles в /ru/… не переписывает —
 * оно знает формы настоящих маршрутов (SECTION_SHAPES в lib/i18nroutes.ts),
 * — и её, как и адрес вне всех разделов, куда ходят сканеры (/wp-login.php,
 * /wp-admin/x), next.config уводит в статическую /_not-found: сервером
 * целиком и без функции. Так русская 404 под разделом осталась такой же,
 * как до [lang]. /ru/… снаружи — редирект на адрес без префикса; сюда под
 * ru доходит разве что …/opengraph-image по чужому адресу (карточки под /ru
 * отдаются без редиректа, lib/i18nroutes.ts).
 *
 * force-dynamic — чтобы ISR не заводил запись на каждый мусорный адрес:
 * страница кэшировалась бы по пути, а путей у ловушки бесконечно много.
 * Цена — рендер функцией на каждый такой адрес, и поэтому сюда доходят
 * только опечатки под /en.
 */
export const dynamic = 'force-dynamic'

export default function Missing(): never {
  notFound()
}
