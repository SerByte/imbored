import { ImageResponse } from 'next/og'
import { EMBER, INK, PLATE } from '@/lib/palette'

/**
 * Иконка под маску Android — та, что реально ложится на домашний экран.
 *
 * Манифест заводился ровно ради «добавить на домашний экран», но обе иконки в
 * нём были purpose: 'any'. Android для таких рисует СВОЮ подложку и вписывает
 * картинку внутрь: знак с собственным тёмным квадратом оказывается в белом
 * или сером круге, уменьшённый примерно вдвое. То есть единственный сценарий,
 * ради которого манифест существует, выглядел хуже всего.
 *
 * Маскируемая иконка обязана быть заполнена ФОНОМ ДО КРАЁВ, а всё значимое —
 * помещаться в круг диаметром 80% холста (безопасная зона спецификации).
 * Отсюда два отличия от app/icon.svg: нет скругления (его нарисует система
 * своей маской, а собственное дало бы двойную фаску) и знак ужат до 82%.
 *
 * Числа посчитаны, а не подобраны: полудиагональ содержимого знака в исходных
 * координатах — 23.35 единицы, безопасный радиус при 512 px — 204.8, значит
 * предельный масштаб 8.77 при натуральном 8. Восьмёрка проходит и без ужатия,
 * но впритык к краю маски; 0.82 даёт запас, при котором знак не касается её
 * ни на круглой маске, ни на «сквиркле».
 */
const SIZE = 512
/** Исходный знак нарисован в сетке 64×64 — как app/icon.svg. */
const GRID = 64
const FIT = 0.82
const K = (SIZE / GRID) * FIT

/** Точка исходной сетки → точка холста, вокруг центра. */
const at = (v: number) => SIZE / 2 + (v - GRID / 2) * K

export function GET(): Response {
  return new ImageResponse(
    (
      <div style={{ width: '100%', height: '100%', display: 'flex', background: PLATE }}>
        <svg width={SIZE} height={SIZE} viewBox={`0 0 ${SIZE} ${SIZE}`}>
          <circle cx={at(22)} cy={at(25)} r={5.5 * K} fill={INK} />
          <circle cx={at(22)} cy={at(42)} r={5.5 * K} fill={INK} />
          <line
            x1={at(36)}
            y1={at(22)}
            x2={at(46)}
            y2={at(45)}
            stroke={EMBER}
            strokeWidth={9 * K}
            strokeLinecap="round"
          />
        </svg>
      </div>
    ),
    { width: SIZE, height: SIZE },
  )
}
