import type { GameJsonRepair } from '../lib/db'
import { plural } from '../lib/plural'

/**
 * SET-часть upsert'а публикации. Экспортируется РАДИ ТЕСТА: правило про язык
 * описаний легко потерять при следующей правке списка колонок, а потеря эта
 * молчаливая — карточки просто снова становятся английскими.
 */
export function buildSetList(cols: readonly string[]): string {
  const ОТ_ОБОГАЩЕНИЯ = new Set(['screenshots_json', 'genres_json'])

  /*
   * Описание — своя ось, и не про пустоту, а про ЯЗЫК.
   *
   * catalog:descriptions доливает витрине русский текст и умеет писать прямо в
   * облако (у него тот же TURSO_DATABASE_URL, что у seed и promote). Публикация
   * же берёт short_description из локального файла и клала его поверх
   * безусловно — то есть первый же publish из каталога, где описания ещё
   * английские, откатывал всю доливку обратно. Работа не ломалась заметно: она
   * просто исчезала, а карточки снова начинали встречать читателя по-английски.
   *
   * Правило узкое: НИКОГДА не заменять русское описание нерусским. Всё
   * остальное едет как прежде — русское русским (переводы в Steam правят),
   * английское английским, английское русским. Пустое локальное тоже не
   * затирает: оно нерусское по этой проверке.
   *
   * GLOB, а не сравнение диапазонов: LIKE в SQLite регистронезависим только
   * для ASCII, и '%[а-я]%' не сработал бы вовсе — квадратные скобки для LIKE
   * не метасимволы. Тот же класс букв, что в самом скрипте доливки.
   */
  const КИРИЛЛИЦА = "'*[абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ]*'"
  return cols
    .filter((c) => c !== 'appid')
    .map((c) => {
      if (ОТ_ОБОГАЩЕНИЯ.has(c)) {
        return `${c} = CASE WHEN excluded.${c} IS NULL OR excluded.${c} IN ('', '[]') THEN games.${c} ELSE excluded.${c} END`
      }
      if (c === 'short_description') {
        return (
          `${c} = CASE WHEN games.${c} GLOB ${КИРИЛЛИЦА}` +
          ` AND NOT (COALESCE(excluded.${c}, '') GLOB ${КИРИЛЛИЦА})` +
          ` THEN games.${c} ELSE excluded.${c} END`
        )
      }
      return `${c} = excluded.${c}`
    })
    .join(', ')
}

/**
 * Отказ заливки: текст, если в локальном каталоге есть строки с битыми
 * JSON-колонками (repairGameJson в режиме dryRun), и null, если везти можно.
 *
 * Отказ целиком, а не пропуск битых строк: заливка идёт по живому проду, и
 * «половина каталога приехала, половина нет» хуже, чем одна команда починки
 * перед повтором. А привезённую битую строку облако само уже не починит:
 * миграция repair_tags_v1 там разовая и к этому времени отработала.
 */
export function publishRefusal(broken: readonly GameJsonRepair[], show = 10): string | null {
  const n = broken.length
  if (!n) return null
  const lines = broken.slice(0, show).map((r) => `  ${r.appid}  ${r.name}`)
  if (n > show) lines.push(`  … и ещё ${n - show}`)
  return [
    `в локальном каталоге ${n} ${plural(n, 'строка', 'строки', 'строк')} с битыми JSON-колонками`,
    '(теги не объект, жанры или категории не массив) — в облако такое не везём:',
    ...lines,
    'почини и повтори: npm run catalog:repair-tags',
  ].join('\n')
}
