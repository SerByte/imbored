/**
 * Колонки-замеры и их отметки времени.
 *
 * Локальный каталог — снимок на момент промоута, а облако с тех пор живёт:
 * цены перемеряет refreshDeals (прогрев и игра дня, срок двенадцать часов),
 * онлайн — догрев в /api/prepare. Заливка клала поверх них локальные значения
 * безусловно, то есть откатывала цену на недели назад — вместе со скидкой,
 * которая уже кончилась, а карточка показывала бы её как действующую:
 * «неточная цена — полбеды, неправда про скидку — повод больше сюда не
 * возвращаться» (lib/discount).
 *
 * Правило — newerMeasureSql: замер едет, только если он не старше облачного.
 */
const ПО_ОТМЕТКЕ: Readonly<Record<string, string>> = {
  price_final: 'price_at',
  price_initial: 'price_at',
  discount_percent: 'price_at',
  discount_ends_at: 'price_at',
  // Регион и «не продаётся» — часть того же замера: едут только вместе с
  // ценой, иначе рубли облака получили бы долларовый регион локального или
  // наоборот (lib/steamregion)
  price_cc: 'price_at',
  store_hidden: 'price_at',
  price_at: 'price_at',
  ccu: 'ccu_at',
  ccu_at: 'ccu_at',
  // Отзывы в облаке сверяет крон (lib/catalogsignals), а у локального каталога
  // отметки нет вовсе: его числа — из посева неизвестной давности. Поэтому
  // reviews_at в список колонок заливки не входит, и сверенные кроном отзывы
  // заливка не трогает; не сверенные — едут, как раньше.
  reviews_total: 'reviews_at',
  reviews_percent: 'reviews_at',
  // Отзывы за 30 дней: в облаке их меряет пульс (refreshReviewPulse в
  // lib/catalogsignals) и ставит отметку проверки, а локальное число — снимок
  // промоута, тоже без отметки. Отметки нет в колонках заливки, как и
  // reviews_at, — значит, замеренное пульсом облачное число переживает
  // заливку, а у ни разу не замеренных едет промоутное. Без этого каждый
  // catalog:publish откатывал бы reviews_30d к промоуту, а по нему судит
  // живость совместной игры без замера онлайна (judgeLiveness), — и рядом
  // остался бы свежий пульс под кольцом, с другим числом за тот же месяц
  reviews_30d: 'reviews_recent_checked_at',
}

/**
 * SET-часть upsert'а публикации. Экспортируется РАДИ ТЕСТА: правило про язык
 * описаний легко потерять при следующей правке списка колонок, а потеря эта
 * молчаливая — карточки просто снова становятся английскими.
 */
export function buildSetList(cols: readonly string[]): string {
  // Трейлер — такое же поле обогащения: в облаке его привозит крон карточек,
  // а локальный каталог без доливки медиа приходит с пустотой. Английское
  // описание — туда же: в облаке его пишут прогрев и крон карточек (GetItems
  // по-английски), а каталог, промоутнутый до английской версии, его не знает.
  // Правила языка, как у short_description, ему не нужно — колонка и так
  // одного языка
  const ОТ_ОБОГАЩЕНИЯ = new Set(['screenshots_json', 'genres_json', 'trailer_json', 'short_description_en'])

  /*
   * Описание — своя ось, и не про пустоту, а про ЯЗЫК.
   *
   * catalog:descriptions доливает витрине русский текст и умеет писать прямо в
   * облако (у него тот же TURSO_DATABASE_URL, что у seed и promote). Публикация
   * же берёт short_description из локального файла и клала его поверх
   * безусловно — то есть первый же publish из каталога, где описания ещё
   * английские, откатывал всю доливку обратно. Работа не ломалась заметно: она
   * просто исчезала, а карточки снова начинали встречать читателя по-английски.
   *
   * Правило узкое: НИКОГДА не заменять русское описание нерусским. Всё
   * остальное едет как прежде — русское русским (переводы в Steam правят),
   * английское английским, английское русским. Пустое локальное тоже не
   * затирает: оно нерусское по этой проверке.
   *
   * Сами SQL-правила — в lib/db рядом с апсертом games: та же защита стоит и
   * на прогреве, и на промоуте, и копий у неё быть не должно.
   */
  return cols
    .filter((c) => c !== 'appid')
    .map((c) => {
      if (ОТ_ОБОГАЩЕНИЯ.has(c)) return `${c} = ${keepFilledSql(c)}`
      if (c === 'short_description') return `${c} = ${keepRussianSql(c)}`
      // Название — по тем же правилам, что у апсерта (nameSql в lib/db):
      // русское, которое крон карточек клал в name облака до этих правил,
      // заливка английским локальным уводит во второе название, а не
      // выбрасывает. name_ru в списке колонок нет — локальный каталог его
      // не везёт, — и колонка выводится из name: прежний русский name облака
      // становится вторым, а свой name_ru облака остаётся
      if (c === 'name') return `name = ${nameSql()}, name_ru = ${nameRuSql()}`
      // Русский язык в облаке привозят крон карточек и доливка медиа, а
      // локальный каталог знает его только у игр, прошедших промоут после
      // появления колонки. NULL отсюда — «не спрашивали», а не «русского нет».
      // И локальное число — снимок дня промоута: оно только заполняет пустоту
      // облака, а известный там язык не трогает (fillUnknownSql в lib/db, там
      // же — чем за это платим). Иначе промоутное «нет» откатывало бы свежее
      // «субтитры» от крона, а доливка медиа перечитывает известный язык
      // только у игр без трейлера или кадров — у остальных неправда жила бы
      // до следующего круга крона, полгода. Заставить облако переспросить язык
      // (скажем, после правки ruLangOf): UPDATE games SET ru_lang = NULL в
      // облаке и catalog:media по нему же — локальный promote --redo с
      // заливкой этого больше не сделает
      if (c === 'ru_lang') return `${c} = ${fillUnknownSql(c)}`
      // Отметки нет в списке колонок — excluded.<отметка> равен NULL, и
      // локальный замер считается безотметочным, то есть старше любого
      // датированного облачного. Для отзывов и их месяца это и нужно (см.
      // ПО_ОТМЕТКЕ)
      const stamp = ПО_ОТМЕТКЕ[c]
      if (stamp) return `${c} = ${newerMeasureSql(c, stamp)}`
      return `${c} = excluded.${c}`
    })
    .join(', ')
}

/**
 * Колонки games, которых в локальном каталоге может не быть.
 *
 * Локальную базу заливка не мигрирует (как и словарь тегов, см. tagsSelectSql),
 * а колонку приносит миграция любого скрипта наполнения. Каталог, собранный
 * до трейлеров и с тех пор не открытый ни одним из них, ответил бы на
 * SELECT trailer_json «no such column» и уронил всю заливку ради колонки,
 * которую в нём всё равно нечем было заполнить.
 */
const ПОЗДНИЕ = new Set(['trailer_json', 'price_cc', 'store_hidden', 'ru_lang', 'short_description_en'])

/** Колонки замера цены — вся группа отметки price_at, включая её саму */
const ЦЕНОВЫЕ = new Set(Object.keys(ПО_ОТМЕТКЕ).filter((c) => ПО_ОТМЕТКЕ[c] === 'price_at'))

/**
 * Список колонок заливки под то, что есть в локальной games: поздние колонки
 * без пары в базе выпадают, остальные остаются всегда — пропавшая обычная
 * колонка должна ронять заливку, а не молча уезжать пустой.
 *
 * Цена без региона не едет вовсе, всей группой. Каталог старше колонки
 * price_cc не знает, в чьей валюте его цены, а облако после смены
 * STEAM_STORE_CC держит другие: поехав одна, price_final легла бы под чужой
 * price_cc облака, и доллары подписались бы рублями. Облако цены перемеряет
 * само (lib/deals, lib/catalogsignals), так что не потеряно ничего.
 */
export function presentCols<T extends string>(cols: readonly T[], have: ReadonlySet<string>): T[] {
  const priced = have.has('price_cc')
  return cols.filter((c) => (!ПОЗДНИЕ.has(c) || have.has(c)) && (priced || !ЦЕНОВЫЕ.has(c)))
}

/**
 * Отказ заливки: текст, если в локальном каталоге есть строки с битыми
 * JSON-колонками (repairGameJson в режиме dryRun), и null, если везти можно.
 *
 * Отказ целиком, а не пропуск битых строк: заливка идёт по живому проду, и
 * «половина каталога приехала, половина нет» хуже, чем одна команда починки
 * перед повтором. А привезённую битую строку облако само уже не починит:
 * миграция repair_tags_v1 там разовая и к этому времени отработала.
 */
export function publishRefusal(broken: readonly GameJsonRepair[], show = 10): string | null {
  const n = broken.length
  if (!n) return null
  const lines = broken.slice(0, show).map((r) => `  ${r.appid}  ${r.name}`)
  if (n > show) lines.push(`  … и ещё ${n - show}`)
  return [
    `в локальном каталоге ${n} ${plural(n, 'строка', 'строки', 'строк')} с битыми JSON-колонками`,
    '(теги не объект, жанры или категории не массив) — в облако такое не везём:',
    ...lines,
    'почини и повтори: npm run catalog:repair-tags',
  ].join('\n')
}

/**
 * Чтение словаря тегов из локального каталога.
 *
 * Локальную базу заливка не мигрирует, и каталог, собранный до колонки
 * name_ru, ответил бы на неё «no such column» — поэтому колонку спрашивают, а
 * не предполагают: hasRu — есть ли она в локальной tags.
 */
export function tagsSelectSql(hasRu: boolean): string {
  return `SELECT tagid, name, game_count, ${hasRu ? 'name_ru' : 'NULL AS name_ru'} FROM tags`
}

/**
 * Upsert словаря в облако. Русское имя — по правилу полей обогащения: пустое
 * локальное облачное не затирает (каталог без перевода не стирает подписи,
 * привезённые раньше), а непустое едет — Steam правит переводы.
 */
export const TAGS_UPSERT_SQL = `INSERT INTO tags (tagid, name, game_count, name_ru) VALUES (?, ?, ?, ?)
  ON CONFLICT(tagid) DO UPDATE SET name = excluded.name, game_count = excluded.game_count,
    name_ru = COALESCE(NULLIF(excluded.name_ru, ''), tags.name_ru)`
